"""Generate readable typed adapters from C declarations and the verified ledger.

No instruction translation: game logic remains in the existing hand ports.
ABI exceptions live in ae_calls_special.c and are deliberately not inferred.
"""
import re
from pathlib import Path
from game_call_inventory import ROOT, declarations, ledger

SPECIAL = {
    "ae_sdk_square0_lane", "ae_sdk_normalize_core", "ae_pad_CameraRotMatrix",
    "ae_player_normalize", "ae_player_can_switch_gadget", "ae_player_gadget_select_request",
    "ae_player_is_swimming", "ae_GadgetSlotsInitForExit",
    "ae_PlayerAct_ScaleMoveVel",
    "ae_PlayerAct_TurnAroundAndJump",
}


def generate():
    protos = declarations()
    # Public declaration absent from the module header; do not edit module logic.
    protos["ae_CollProbe_Slope"] = ("src/collision/ae_collprobe.h", "int32_t",
        ["AeRam *r", "const AeCollProbeHooks *h", "uint32_t shape", "uint32_t probe", "uint32_t out"])
    for name, ret, args in [
        ("ae_GadgetSlotsSave", "void", ["AeRam *r"]),
        ("ae_GadgetSlotsRestore", "void", ["AeRam *r"]),
        ("ae_GadgetSlotsInitForArea", "int32_t", ["AeRam *r", "int32_t gadget"]),
    ]:
        protos[name] = ("src/game/ae_calls_special.h", ret, args)
    rows = ledger()
    used = sorted({protos[r["c_function"]][0] for r in rows if r["c_function"] not in SPECIAL})
    hook_types = sorted({re.search(r"\b(Ae\w+Hooks)\b", a)[1]
                         for r in rows if r["c_function"] in protos
                         for a in protos[r["c_function"]][2] if re.search(r"\b(Ae\w+Hooks)\b", a)})
    fields = {t: re.sub(r"(?<!^)(?=[A-Z])", "_", t[2:-5]).lower() for t in hook_types}
    fields.update(AeMonkeyHooks="monkey", AeBodyHooks="body", AeWorldHooks="world",
                  AeSolidHooks="solid", AeSpawnHooks="spawn", AeGimmickHooks="gimmick", AeAnimEventHooks="anim")
    header = ["/* Generated by tools/generate_game_calls.py. */", "#ifndef AE_GAME_MODULES_H", "#define AE_GAME_MODULES_H"]
    # Module-local offset macros collide (some are relative, others absolute).
    # The host uses explicit addresses; keep these macros local to their headers.
    offsets = ["AE_PLAYER_STATE", "AE_PLAYER_STATE_FLAGS", "AE_PLAYER_FACING_X", "AE_PLAYER_FACING_Z",
               "AE_PLAYER_VEL_X", "AE_PLAYER_VEL_Y", "AE_PLAYER_VEL_Z", "AE_PLAYER_ANIM_FRAME",
               "AE_PLAYER_HEALTH", "AE_G_PLAYER_SCRATCH"]
    for p in used:
        if "/game/" in p: continue
        header += [f"#undef {m}" for m in offsets]
        header += [f'#include "../../{p}"']
    header += [f"#undef {m}" for m in offsets]
    header += ["#define AE_GAME_MODULE_FIELDS \\"]
    members = [f"    {t} {fields[t]};" for t in hook_types if fields[t] not in {"monkey", "body", "world", "solid", "spawn", "gimmick", "anim"}]
    header += [m + (" \\" if i < len(members)-1 else "") for i,m in enumerate(members)]
    header += ["#endif", ""]
    (ROOT / "src/game/ae_game_modules.h").write_text("\n".join(header))
    out = ['/* Generated typed adapters; edit tools/generate_game_calls.py to regenerate. */',
           '#include "ae_calls.h"', '#include "ae_calls_special.h"',
           'int32_t ae_CollProbe_Slope(AeRam *, const AeCollProbeHooks *, uint32_t, uint32_t, uint32_t);', ""]
    previous = None
    entries = []
    for index, row in enumerate(sorted(rows, key=lambda r:(r["source"], r["c_function"]))):
        name = row["c_function"]
        wrapper = f"call_{name}"
        entries.append((int(row["address"],16), name, wrapper, row))
        if previous != row["source"]:
            out += [f'/* ---- {row["source"]} ---- */']
            previous = row["source"]
        out += [f"static int32_t {wrapper}(AeGame *g, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3) {{",
                "    (void)g; (void)a0; (void)a1; (void)a2; (void)a3;"]
        if name in SPECIAL:
            out += [f"    return special_{name}(g, a0, a1, a2, a3);", "}", ""]
            continue
        if name=='ae_CollisionRayTest':
            out += ['    return ae_game_collision_ray(g, a0, a1, a2);', '}', '']
            continue
        _, ret, params = protos[name]
        args, abi = [], 0
        for param in params:
            if "AeRam" in param: args.append("g->ram")
            elif "AeSoundHw" in param: args.append("&g->host.sound_hw")
            elif re.search(r"\b(Ae\w+Hooks)\b", param):
                args.append("&g->"+fields[re.search(r"\b(Ae\w+Hooks)\b",param)[1]])
            else:
                assert "[" not in param and "*" not in param, (name, param)
                typ = param.rsplit(" ",1)[0].strip()
                word = f"a{abi}" if abi < 4 else f"ae_rd32(g->ram, g->call_stack_pointer + {abi*4}u)"
                args.append(f"({typ}){word}")
                abi += 1
        call = f'{name}({", ".join(args)})'
        if ret == "void": out += [f"    {call};", "    return 0;"]
        else: out += [f"    return (int32_t){call};"]
        out += ["}", ""]
    out += ["/* Duplicate ledger ports share an address; RAM-image ports are preferred. */", "static const AeGameCall CALLS[] = {"]
    # Stable choice: full RAM implementation wins over partial/native helpers.
    entries.sort(key=lambda e:(e[0], e[1] in SPECIAL, "native" in e[3]["source"], e[1]))
    for address, name, wrapper, row in entries:
        identity=re.search(r'overlay member ([0-9A-Fa-f]+)\.bin',row['notes'] or '')
        overlay=int(identity[1],16) if identity else (0xFFFFFFFF if address>=0x80100000 else 0)
        out.append(f'    {{0x{address:08X}u, "{name}", {wrapper}, 0x{overlay:08X}u}},')
    out += ["};", "", "size_t ae_game_call_count(void) { return sizeof(CALLS) / sizeof(CALLS[0]); }",
            "const AeGameCall *ae_game_call_at(size_t index) {", "    return index < ae_game_call_count() ? &CALLS[index] : NULL;", "}",
            "const AeGameCall *ae_game_find_call(uint32_t address) {",
            "    size_t lo = 0, hi = ae_game_call_count();",
            "    while (lo < hi) {", "        size_t mid = lo + (hi - lo) / 2;",
            "        if (CALLS[mid].address < address) lo = mid + 1; else hi = mid;", "    }",
            "    return lo < ae_game_call_count() && CALLS[lo].address == address ? &CALLS[lo] : NULL;", "}",
            "int32_t ae_game_call(AeGame *g, uint32_t address, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3) {",
            "    const AeGameCall *call = ae_game_find_call(address);",
            "    if (call && address >= 0x80100000u) {",
            "        size_t index = (size_t)(call - CALLS);",
            "        call = NULL;",
            "        for (; index < ae_game_call_count() && CALLS[index].address == address; ++index)",
            "            if (CALLS[index].overlay_member == g->loaded_overlay) { call = &CALLS[index]; break; }",
            "    }",
            "    /* Overlay address alone cannot identify the loaded code. */",
            "    if (!call || (address >= 0x80100000u && (call->overlay_member == UINT32_MAX || call->overlay_member != g->loaded_overlay)))",
            '        return ae_game_missing_call(g, call ? call->name : "UnknownFunction", address, a0, a1, a2, a3);',
            "    return call->invoke(g, a0, a1, a2, a3);", "}", ""]
    (ROOT / "src/game/ae_calls.c").write_text("\n".join(out))
    special_header = ['#ifndef AE_CALLS_SPECIAL_H', '#define AE_CALLS_SPECIAL_H', '#include "ae_game.h"']
    special_header += [f'int32_t special_{name}(AeGame *, uint32_t, uint32_t, uint32_t, uint32_t);' for name in sorted(SPECIAL)]
    special_header += ['void ae_GadgetSlotsSave(AeRam *);', 'void ae_GadgetSlotsRestore(AeRam *);', 'int32_t ae_GadgetSlotsInitForArea(AeRam *, int32_t);', '#endif', '']
    (ROOT / "src/game/ae_calls_special.h").write_text("\n".join(special_header))
    print(f"Generated {len(entries)} wrappers for {len(set(e[0] for e in entries))} original addresses")


if __name__ == "__main__":
    generate()
