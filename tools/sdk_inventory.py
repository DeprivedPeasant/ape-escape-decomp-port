"""Build the PS1 SDK / hardware surface the game depends on (native-port checklist).

Inputs (from tools/ghidra_scripts/DumpCallGraph.java, in notes/inventory/):
  functions.csv, calls.csv, gte.csv, hwrefs.csv
plus the PsyQ 4.5 signature data shipped with ghidra_psx_ldr (label -> library/object)
and tools/symbols.csv (our own names, never SDK).

Output: notes/06-sdk-inventory.md

Usage: uv run python tools/sdk_inventory.py
"""
import collections
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INV = ROOT / "notes" / "inventory"
PSYQ = ROOT / "tools/ghidra_12.1.2_PUBLIC/Ghidra/Extensions/ghidra_psx_ldr/data/psyq/450"
OUT = ROOT / "notes" / "06-sdk-inventory.md"
OBJ_NAME = re.compile(r"^([A-Z0-9_]+?)_OBJ_[0-9A-F]+$")


def load_psyq() -> tuple[dict[str, tuple[str, str]], dict[str, str]]:
    """label -> (lib, obj), obj stem -> lib"""
    labels, objs = {}, {}
    for f in sorted(PSYQ.glob("*.json")):
        lib = f.name.removesuffix(".json")
        for obj in json.loads(f.read_text()):
            stem = obj["name"].rsplit(".", 1)[0].upper()
            objs.setdefault(stem, lib)
            for lab in obj.get("labels", []):
                name = lab["name"]
                if not name.startswith("loc_"):
                    labels.setdefault(name, (lib, obj["name"]))
    return labels, objs


def main() -> None:
    labels, objs = load_psyq()
    ours = {line.split(",", 2)[1].strip() for line in (ROOT / "tools/symbols.csv").read_text().splitlines()
            if line and not line.startswith("#") and "," in line}

    funcs = {}
    for r in csv.DictReader(open(INV / "functions.csv", encoding="utf-8")):
        funcs[r["entry"]] = r

    def classify(f) -> tuple[str, str | None]:
        """('sdk', lib) | ('gte-macro', None) | ('game', None)"""
        name, block = f["name"], f["block"]
        if block == "GTEMAC":
            return "gte-macro", None
        if name in ours:
            return "game", None
        base = re.sub(r"_\d+$", "", name)  # duplicate copies in overlays may get suffixes
        if base in labels:
            return "sdk", labels[base][0]
        m = OBJ_NAME.match(name)
        if m:
            return "sdk", objs.get(m.group(1), "?")
        return "game", None

    kind = {e: classify(f) for e, f in funcs.items()}

    # SDK functions called directly from game code = the API a port must provide.
    api = collections.defaultdict(lambda: {"sites": 0, "callers": set(), "blocks": set()})
    for r in csv.DictReader(open(INV / "calls.csv", encoding="utf-8")):
        caller, callee = r["caller"], r["callee"]
        if kind.get(caller, ("?",))[0] != "game" or kind.get(callee, ("?",))[0] != "sdk":
            continue
        key = (kind[callee][1], re.sub(r"_\d+$", "", funcs[callee]["name"]))
        api[key]["sites"] += int(r["count"])
        api[key]["callers"].add(caller)
        api[key]["blocks"].add("main" if funcs[caller]["block"] in ("CODE",) else "overlays")

    # SDK copies statically linked into overlays.
    ovl_sdk = collections.Counter(f["block"] for e, f in funcs.items()
                                  if kind[e][0] == "sdk" and f["block"].startswith("ovl_"))

    # Inline GTE in game code.
    gte = collections.Counter()
    gte_funcs = set()
    for r in csv.DictReader(open(INV / "gte.csv", encoding="utf-8")):
        if kind.get(r["function"], ("?",))[0] == "game":
            gte[r["mnemonic"]] += int(r["count"])
            gte_funcs.add(r["function"])

    # Direct hardware access from game code.
    hw = collections.defaultdict(lambda: {"refs": 0, "funcs": set(), "addrs": set()})
    for r in csv.DictReader(open(INV / "hwrefs.csv", encoding="utf-8")):
        if kind.get(r["function"], ("?",))[0] == "game":
            block = r["block"]
            if block == "?" and 0x1F801DC0 <= int(r["address"], 16) < 0x1F801E00:
                block = "SPU_REVERB_REGS"  # not named by the PSX loader's memory map
            h = hw[block]
            h["refs"] += int(r["count"])
            h["funcs"].add(r["function"])
            h["addrs"].add(r["address"])

    n = collections.Counter(k for k, _ in kind.values())
    by_lib = collections.defaultdict(list)
    for (lib, name), v in api.items():
        by_lib[lib].append((name, v))

    lines = [
        "# SDK and hardware surface (native-port checklist)",
        "",
        "Generated by `tools/sdk_inventory.py` from a Ghidra call-graph dump "
        "(`tools/ghidra_scripts/DumpCallGraph.java`). Don't edit by hand; re-run both.",
        "",
        "## Summary",
        "",
        f"- Functions in the program: {len(funcs)} — game {n['game']}, PsyQ SDK {n['sdk']}, "
        f"GTE macro pseudo-functions {n['gte-macro']}.",
        f"- SDK functions called directly by game code: **{len(api)}** across "
        f"{len(by_lib)} libraries. This is the API a native port has to reimplement.",
        f"- Game functions using inline GTE (COP2) instructions: **{len(gte_funcs)}** "
        f"({sum(gte.values())} instructions).",
        f"- Game functions touching hardware registers / scratchpad directly: "
        f"**{len(set().union(*[h['funcs'] for h in hw.values()]) if hw else 0)}**.",
        "",
        "## SDK API used by game code",
        "",
        "Sorted by call sites. `where` says whether callers are in the main EXE, overlays, or both.",
        "",
    ]
    for lib in sorted(by_lib, key=lambda l: -sum(v["sites"] for _, v in by_lib[l])):
        rows = sorted(by_lib[lib], key=lambda x: -x[1]["sites"])
        total = sum(v["sites"] for _, v in rows)
        lines += [f"### {lib} — {len(rows)} functions, {total} call sites", "",
                  "| Function | Call sites | Callers | Where |", "|---|---|---|---|"]
        for name, v in rows:
            lines.append(f"| `{name}` | {v['sites']} | {len(v['callers'])} | {'+'.join(sorted(v['blocks']))} |")
        lines.append("")

    lines += ["## Inline GTE instructions in game code", "",
              "These bypass libgte and need a GTE implementation (or a software rewrite of each "
              "caller) in the port.", "",
              "| Mnemonic | Count |", "|---|---|"]
    lines += [f"| `{m}` | {c} |" for m, c in gte.most_common()]
    lines += ["", "## Direct hardware access from game code", "",
              "`CACHE` is the 1 KB scratchpad (0x1F800000) — just fast RAM, easy to keep. "
              "Everything else is memory-mapped I/O the port must emulate or remove.", "",
              "| Block | Refs | Functions | Distinct addresses |", "|---|---|---|---|"]
    for blk, h in sorted(hw.items(), key=lambda x: -x[1]["refs"]):
        lines.append(f"| {blk} | {h['refs']} | {len(h['funcs'])} | {len(h['addrs'])} |")
    lines += ["", "## SDK code linked into overlays", "",
              "Overlays carry their own copies of some SDK functions. In the port these all "
              "map to the one shared implementation.", "",
              "| Overlay | SDK functions |", "|---|---|"]
    lines += [f"| {b} | {c} |" for b, c in sorted(ovl_sdk.items())]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(api)} SDK functions used by game code, {len(by_lib)} libraries")


if __name__ == "__main__":
    main()
