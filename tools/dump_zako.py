"""Dump the enemy ('zako') spawn tables of every area blob (blob +0x4E0, magic '.ZED').

Header (u32 words, offsets relative to the section): [0] 0x44455A2E, [1] low u16 = entry count, high u16 = ?,
[2] offset of the entries, [3] offset of a second table. Entry = 0x20 bytes:
  +0 u16 type (< 0xB7 spawns via the table), +2/+4/+6 s16 x y z, +8 u16 param (-> Obj+0xA4), +0xA u16 param
  (-> Obj+0xA6 radius), +0xC u16 collider index (-> Obj+0x70, -1 none), +0xE s16 link (-1 none),
  +0x10 s16 remaining spawns, +0x12 u16 spawn radius, +0x16 u8 active flag, +0x18 model offset (relative to the ZED section, ObjInitModel -> ModelInitAuto), +0x1C animation header offset (u16 count, 4 byte header, count first/last u16 pairs, packed frames).
Output: notes/22-enemies.md (generated).

Usage: uv run python tools/dump_zako.py
"""
import struct
from collections import Counter
from pathlib import Path

import dump_areas as da

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    rows = ["# Enemy ('zako') spawn tables (generated)", "",
            "Generated by `tools/dump_zako.py`. System overview and function names: `ZakoInit` and the `Zako*` / "
            "`Obj*` symbols; objects live in `g_Objs` (16 x 0xE4 bytes). Types index the handler table at 0x800AF350.", "",
            "| Area | Entries | Types |", "|---|---|---|"]
    total = Counter()
    for area, member in sorted(da.area_members().items()):
        b = (da.MEMBERS / f"{member:03X}.bin").read_bytes()
        sec = struct.unpack_from("<I", b, 0x4E0)[0]
        if sec + 16 > len(b) or struct.unpack_from("<I", b, sec)[0] != 0x44455A2E:
            rows.append(f"| 0x{area:02X} | - | (no .ZED section) |")
            continue
        n = struct.unpack_from("<H", b, sec + 4)[0]
        off = struct.unpack_from("<I", b, sec + 8)[0]
        types = Counter()
        for i in range(n):
            t = struct.unpack_from("<H", b, sec + off + i * 0x20)[0]
            types[t] += 1
            total[t] += 1
        rows.append(f"| 0x{area:02X} | {n} | " + " ".join(f"0x{t:02X}x{c}" for t, c in sorted(types.items())) + " |")
    rows += ["", "## Type totals", "", " ".join(f"0x{t:02X}x{c}" for t, c in sorted(total.items()))]
    (ROOT / "notes/22-enemies.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"{sum(total.values())} entries, {len(total)} types")


if __name__ == "__main__":
    main()
