"""Map every monkey AI state (0..0x42) to its handler, from the dispatch table in the EXE.

MonkeyAiStateUpdate jumps through the table at 0x800A4AB0 into small code blocks that call the
real state handlers (`jal`) and rejoin the common tail at 0x80041A38. This script walks each block,
lists the called functions (names from tools/symbols.csv) and joins the per-state table at 0x800AE940
(anim index, flags). Output: notes/17-monkey-states.md.

Usage: uv run python tools/dump_monkey_states.py
"""
import csv
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXE = (ROOT / "extract/disc/SCUS_944.23").read_bytes()
DISPATCH, STATES, TAIL, NSTATES = 0x800A4AB0, 0x800AE940, 0x80041A38, 0x43
GUARDS = {0x80033A3C}  # MonkeyAnimFinished: guard calls, not the handler


def u32(a: int) -> int:
    return struct.unpack_from("<I", EXE, a - 0x80010000 + 0x800)[0]


def names() -> dict[int, str]:
    out = {}
    for line in (ROOT / "tools/symbols.csv").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#") and "::" not in line.split(",")[0]:
            parts = next(csv.reader([line]))
            out[int(parts[0], 16)] = parts[1]
    return out


def block_calls(start: int) -> list[int]:
    calls, a = [], start
    while a < start + 0x120:
        x = u32(a)
        if x >> 26 == 3:
            calls.append(((x & 0x3FFFFFF) << 2) | 0x80000000)
        if x >> 26 == 2 and ((x & 0x3FFFFFF) << 2 | 0x80000000) == TAIL:
            break
        a += 4
    return calls


def main() -> None:
    nm = names()
    label = lambda a: nm.get(a, f"FUN_{a:08x}")
    rows = ["# Monkey AI states (generated)", "",
            "Generated by `tools/dump_monkey_states.py` from the dispatch table at 0x800A4AB0 and the state "
            "table at 0x800AE940 (`g_MonkeyStateTable`: anim index, flags). Handlers marked *inline* are "
            "code blocks inside `MonkeyAiStateUpdate` that call other functions directly. Flags: bit2 "
            "non-looping clip, bit4 LOD scale, bit5/6 awareness/sight, bits0-1 attack kind.", "",
            "| State | Handler (first non-guard call) | Other calls in block | Anim | Flags |", "|---|---|---|---|---|"]
    groups: dict[int, list[int]] = {}
    for s in range(NSTATES):
        blk = u32(DISPATCH + 4 * s)
        groups.setdefault(blk, []).append(s)
        calls = block_calls(blk)
        main_calls = [c for c in calls if c not in GUARDS]
        first = label(main_calls[0]) if main_calls else "(none)"
        rest = ", ".join(label(c) for c in main_calls[1:])
        inline = " *inline*" if len(calls) > 1 and first.startswith("FUN_") is False and blk > 0x80041570 else ""
        rows.append(f"| 0x{s:02X} | {first}{inline} | {rest} | {u32(STATES + s * 8)} | 0x{u32(STATES + s * 8 + 4):02X} |")
    rows += ["", "## States sharing a handler block", ""]
    for blk, ss in sorted(groups.items()):
        calls = [c for c in block_calls(blk) if c not in GUARDS]
        rows.append(f"- `0x{blk:08X}` {label(calls[0]) if calls else ''}: " + " ".join(f"0x{s:02X}" for s in ss))
    (ROOT / "notes/17-monkey-states.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"{NSTATES} states, {len(groups)} blocks -> notes/17-monkey-states.md")


if __name__ == "__main__":
    main()
