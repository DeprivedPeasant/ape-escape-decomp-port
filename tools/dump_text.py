"""Decode the in-game hint / tutorial texts (archive member 0x014) to notes/26-hint-text.md.

Text format (validated on the whole member, 100 sectors of 0x800 bytes; Indicator_Activate reads sector `arg`):
  glyph code = cell of the 16x16 font page (u = (c & 15) * 16, v = (c & 0x70)); the text uses  A-Z = 0x10..0x29,
  a-z = 0x30..0x49, digits 0-5 = 0x6A..0x6F and 6-9 = 0x7A..0x7D (checked on the font page), 0xFF = space, 0xAC '.', 0xAD ',', 0x7E '!', 0x7F '?', 0xBB apostrophe, 0xBA quote, 0x8D slash, 0x8B '-', 0xBE '&'
  0x0D = new line, 0x0F = next message page, 0x00 = end, 0x0A xx = button icon xx (font page 1), 0x0B xx = portrait / speaker
  icon xx (font page 2, shown in the box corner).
The mapping was derived from the plain English text and the glyph widths; unknown codes are printed as <XX>.

Monkey biographies: every monkey of an area blob has a 0x88 byte info record with the name (12 bytes) at +0x1C and a one line
description (0x28 bytes) at +0x28, both in the same glyph codes (validated: the number of records equals the number of
monkey spawns for 91 of the 101 areas; see notes/27-monkey-bios.md).

Usage: uv run python tools/dump_text.py            -> notes/26-hint-text.md and notes/27-monkey-bios.md
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MEMBER = ROOT / "extract/members/014.bin"
OUT = ROOT / "notes/26-hint-text.md"
OUT_MONKEYS = ROOT / "notes/27-monkey-bios.md"
VALID = set(range(0x10, 0x2A)) | set(range(0x30, 0x4A)) | set(range(0x6A, 0x70)) | set(range(0x7A, 0x7E)) | {0xFF, 0xAC, 0xAD, 0x7E, 0x7F, 0xBB, 0xBA, 0x8B, 0x8D, 0xBE, 0x0D}

PUNCT = {0xFF: " ", 0xAC: ".", 0xAD: ",", 0x7E: "!", 0xBB: "'", 0x8B: "-", 0x0D: "\n", 0x0F: "\n\f", 0x7F: "?", 0xBA: '"', 0xBE: "&", 0x8D: "/"}


def decode(sec: bytes) -> str:
    out, i = [], 0
    while i < len(sec) and sec[i]:
        c = sec[i]
        if c in (0x0A, 0x0B):
            out.append(f"[{'btn' if c == 0x0A else 'face'}{sec[i + 1]:02X}]")
            i += 2
            continue
        if c in PUNCT:
            out.append(PUNCT[c])
        elif 0x10 <= c <= 0x29:
            out.append(chr(65 + c - 0x10))
        elif 0x30 <= c <= 0x49:
            out.append(chr(97 + c - 0x30))
        elif 0x6A <= c <= 0x6F:
            out.append(chr(48 + c - 0x6A))
        elif 0x7A <= c <= 0x7D:
            out.append(chr(54 + c - 0x7A))
        else:
            out.append(f"<{c:02X}>")
        i += 1
    return "".join(out)


def _txt(b: bytes, o: int, n: int):
    s = b[o:o + n]
    e = s.find(0)
    s = s[:e if e >= 0 else n]
    return s if s and all(c in VALID for c in s) else None


def monkey_records(b: bytes) -> list[tuple[int, str, str]]:
    """(offset, name, description) of the monkey info records of an area blob."""
    out = []
    for p in range(0, len(b) - 0x88):
        n, d = _txt(b, p + 0x1C, 0xC), _txt(b, p + 0x28, 0x28)
        if n and d and 0x10 <= n[0] <= 0x29 and len(n) >= 2 and len(d) >= 4 and b[p + 0x27] == 0:
            out.append((p, decode(n).strip(), decode(d).strip()))
    return out


def write_monkeys() -> None:
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import dump_areas
    import dump_monkeys
    lines = ["# Monkey biographies (generated by tools/dump_text.py)", "",
             "Name (12 bytes at +0x1C) and one line description (+0x28) of the 0x88 byte info record of every monkey, per area "
             "blob. `spawns` is the number of monkey spawns of the area (notes/15); the counts agree for most areas.", ""]
    total = 0
    for area, member in sorted(dump_areas.area_members().items()):
        b = (ROOT / f"extract/members/{member:03X}.bin").read_bytes()
        recs = monkey_records(b)
        mk = dump_monkeys.monkeys(b)
        sp = len(mk["spawns"]) if mk else 0
        if not recs and not sp:
            continue
        total += len(recs)
        lines += [f"## Area 0x{area:02X} (member 0x{member:03X}): {len(recs)} records, {sp} spawns" + ("" if len(recs) == sp else "  (counts differ)"), "",
                  "| Offset | Name | Description |", "|---|---|---|"]
        lines += [f"| 0x{p:X} | {n} | {d} |" for p, n, d in recs]
        lines.append("")
    lines.insert(2, f"{total} records in total.")
    OUT_MONKEYS.write_text(chr(10).join(lines), encoding="utf-8")
    print(f"{total} monkey records -> {OUT_MONKEYS}")


OUT_STRINGS = ROOT / "notes/28-game-strings.md"
EXE = ROOT / "extract/disc/SCUS_944.23"
# (member, description, load address of byte 0 or None); the UI overlays all load at 0x80136000
# (e.g. ovl_188 file 0x5490 = 0x8013B490, the packed objective strings of notes/59).
STRING_SOURCES = [
    ("02F", "Professor dialogue data (water net demo)", None),
    ("186", "ovl 0x186 save / load / PocketStation menu (modes 14, 21, 22, 35)", 0x80136000),
    ("187", "ovl 0x187 stage clear / race results", 0x80136000),
    ("188", "ovl 0x188 stage start screen (objectives, notes/59)", 0x80136000),
    ("189", "ovl 0x189 time machine / stage select (mode 9)", 0x80136000),
    ("18B", "ovl 0x18B special area entry (mode 16); Japanese-era gadget names", 0x80136000),
    ("1AD", "ovl 0x1AD monkey data / book (mode 28)", 0x80136000),
    ("1AF", "ovl 0x1AF ending (modes 31, 32)", 0x80136000),
]
CTRL = (0x0A, 0x0B)


def _string_runs(b: bytes) -> list[tuple[int, str]]:
    """Maximal zero-terminated runs of glyph codes (button / face escapes allowed)."""
    out, i, n = [], 0, len(b)
    while i < n:
        if b[i] in VALID and b[i] != 0x0D and (i == 0 or (b[i - 1] not in VALID and b[i - 2] not in CTRL)):
            j = i
            while j < n and (b[j] in VALID or b[j] == 0x0F or (b[j] in CTRL and j + 1 < n)):
                j += 2 if b[j] in CTRL else 1
            if j < n and b[j] == 0:
                out.append((i, decode(b[i:j])))
            i = max(j, i + 1)
        else:
            i += 1
    return out


def _wordlike(t: str) -> bool:
    import re
    s = re.sub(r"\[(btn|face)[0-9A-F]{2}\]", "", t)
    words = re.findall(r"[A-Za-z']{2,}", s)
    letters = sum(len(w) for w in words)
    if s != t and len([w for w in words if len(w) >= 3]) < 2:
        return False  # icon escapes inside short runs are almost always data
    if "<" in s or letters < 4 or re.search(r"([A-Za-z])\1\1", s):
        return False
    # every word must look like English capitalisation (Word, word, WORD); random glyph data does not
    if any(not re.fullmatch(r"[A-Z]?[a-z']+|[A-Z']+", w) for w in words):
        return False
    if not all(re.search(r"[aeiouyAEIOUY]", w) for w in words if len(w) > 2):
        return False
    core = re.sub(r"\s", "", s)
    return letters / max(len(core), 1) >= 0.7


def game_strings(b: bytes) -> list[tuple[int, str]]:
    """Plausible text strings: word-like runs, kept in clusters (gap < 0x40) with 20+ letters or a 2-word string."""
    import re
    groups: list[list[tuple[int, str]]] = []
    for o, t in _string_runs(b):
        if not _wordlike(t):
            continue
        if groups and o - groups[-1][-1][0] - len(groups[-1][-1][1]) < 0x40:
            groups[-1].append((o, t))
        else:
            groups.append([(o, t)])
    keep = []
    for g in groups:
        ws = [re.findall(r"[A-Za-z]{3,}", t) for _, t in g]
        if any(len(w) >= 2 for w in ws) or sum(len(x) for w in ws for x in w) >= 20:
            keep += g
    return keep


def _md(t: str) -> str:
    return t.replace("\n", " / ").replace("\f", " // ").replace("|", "\\|")


STAGE_NAMES_188, STAGE_INDEX_188 = 0x8013AED0, 0x8013B450  # ovl 0x188 (loaded at 0x80136000)


def stage_names() -> dict[int, str]:
    """level id -> English stage name: ovl 0x188 maps the level (AreaGetLevel) through the s8 table 0x8013B450 to an
    index into the packed name list 0x8013AED0 (StageStartUi_StringTableIndex) and copies it to 0x800F4458."""
    b = (ROOT / "extract/members/188.bin").read_bytes()
    names, p = [], STAGE_NAMES_188 - 0x80136000
    for _ in range(22):
        e = b.index(0, p)
        names.append(decode(b[p:e]).strip())
        p = e + 1
    out = {}
    for level in range(0x1F):
        i = b[STAGE_INDEX_188 - 0x80136000 + level]
        if i != 0xFF:
            out[level] = names[i]
    return out


def stage_name_section() -> list[str]:
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import dump_areas
    names = stage_names()
    by_level: dict[int, list[int]] = {}
    for area, _ptr in dump_areas.area_chains():
        level = dump_areas.exe_u32(dump_areas.AREA_PTRS + area * 8 + 4) & 0xFFFF
        by_level.setdefault(level, []).append(area)
    lines = ["## Stage names by level and area", "",
             "The stage start overlay (0x188) maps the level of the current area (`AreaGetLevel`, area table entry +4) "
             "through the byte table 0x8013B450 to an index into the packed name list 0x8013AED0 "
             "(`StageStartUi_StringTableIndex`) and copies the name to 0x800F4458. Levels without an entry (0xFF) have no "
             "stage name (hub / special levels).", "", "| Level | Stage | Areas |", "|---|---|---|"]
    for level in sorted(by_level):
        lines.append(f"| {level} | {names.get(level, '-')} | {', '.join(f'0x{a:02X}' for a in by_level[level])} |")
    lines.append("")
    return lines


def write_strings() -> None:
    import struct
    lines = ["# Game strings (generated by tools/dump_text.py)", "",
             "Font-coded strings (same glyph codes as notes/26) found by scanning the EXE and the UI overlay / dialogue "
             "members for word-like zero-terminated runs (heuristic: random data rarely decodes to capitalised English words; "
             "very short isolated strings are dropped, so a few labels may be missing). A line break inside a string is "
             "shown as ` / `.", ""]
    exe = EXE.read_bytes()
    lines += ["## SCUS_944.23", "", "| Address | Text |", "|---|---|"]
    lines += [f"| 0x{0x80010000 + o - 0x800:08X} | {_md(t)} |" for o, t in game_strings(exe) if o >= 0x800]
    # The gadget menu text table (5 string pointers per gadget id, notes/08)
    lines += ["", "### Gadget menu table (0x800B25A0, 8 x 5 pointers, indexed by gadget id)", "",
              "| Id | Name | Description |", "|---|---|---|"]
    for g in range(8):
        ss = []
        for k in range(5):
            p = struct.unpack_from("<I", exe, 0xA2DA0 + (g * 5 + k) * 4)[0] - 0x80010000 + 0x800
            ss.append(decode(exe[p:exe.index(0, p)]))
        lines.append(f"| {g} | {ss[0]} | {' '.join(s for s in ss[1:] if s)} |")
    lines.append("")
    for member, desc, base in STRING_SOURCES:
        b = (ROOT / f"extract/members/{member}.bin").read_bytes()
        lines += [f"## Member 0x{member}: {desc}", "", f"| {'Address' if base else 'Offset'} | Text |", "|---|---|"]
        lines += [f"| 0x{(base or 0) + o:0{8 if base else 1}X} | {_md(t)} |" for o, t in game_strings(b)]
        lines.append("")
    lines += stage_name_section()
    OUT_STRINGS.write_text("\n".join(lines), encoding="utf-8")
    print(f"strings -> {OUT_STRINGS}")


def main() -> None:
    b = MEMBER.read_bytes()
    lines = ["# Hint / tutorial texts (generated by tools/dump_text.py)", "",
             "Archive member 0x014, one text block per 0x800 byte sector (`Indicator_Activate` reads sector `arg` into a heap "
             "block, `MessageBoxSetText` shows it). `[btnNN]` = button icon, `[faceNN]` = portrait icon, a form feed starts "
             "the next message page. Unknown glyph codes appear as `<XX>`.", ""]
    n = 0
    unknown: dict[int, int] = {}
    for s in range(len(b) // 0x800):
        sec = b[s * 0x800:(s + 1) * 0x800]
        if not any(sec):
            continue
        txt = decode(sec)
        n += 1
        for part in txt.replace("<", "\0<").split("\0"):
            if part.startswith("<") and part[3:4] == ">":
                unknown[int(part[1:3], 16)] = unknown.get(int(part[1:3], 16), 0) + 1
        lines += [f"## Sector {s}", "", "```", txt.replace("\f", "\n--- page ---"), "```", ""]
    if unknown:
        lines += ["## Unmapped codes", "", ", ".join(f"0x{k:02X} x{v}" for k, v in sorted(unknown.items())), ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{n} texts -> {OUT}; unmapped codes: {sorted(unknown)}")
    write_monkeys()
    write_strings()


if __name__ == "__main__":
    main()
