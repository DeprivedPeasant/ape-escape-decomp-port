"""Parse the sound bank members (SShd / SSsq / SSvb container) and export their samples.

Container (found in ~55 archive members, loaded by SoundBankUpload -> SpuDriver):
    u32 w[13]: [0] SShd0 size  [1] SShd1 size (0 = none)  [2] SSsq size  [3] VB0 size  [4] VB1 size
               [5] SShd0 offset (0x28)  [6] SShd1 offset  [7] SSsq offset  [8] VB0 offset  [9] VB1 offset
               [10] = [0], [11] = [3]
    each SShd / SSsq chunk starts 12 bytes before its magic (u32 size, u32 vb size, u32 0, magic 'SShd'/'SSsq').
    VBx = raw SPU ADPCM blocks (16 bytes), uploaded to SPU RAM; the first block is silence.
Standalone SShd members (e.g. 0x00B, 0x01E) hold only the header chunk: u32 size, u32 vb size, 0, 'SShd'.

The header-chunk tone tables are decoded by tools/dump_tones.py (notes/24-tone-tables.md); here the samples are split by the ADPCM end flag (block byte 1
bit 0) and decoded to 16-bit PCM, written at 22050 Hz as a placeholder rate.

Usage: uv run python tools/dump_sound.py            -> notes/18-sound-banks.md (generated)
       uv run python tools/dump_sound.py wav 01B   -> extract/sound/01B_vbN_sMMM.wav
"""
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MEMBERS = ROOT / "extract/members"
OUT = ROOT / "extract/sound"
FILTERS = [(0, 0), (60, 0), (115, -52), (98, -55), (122, -60)]


def parse(b: bytes):
    """Return the container description or None when the member is not a sound bank."""
    if len(b) < 0x40 or b[0x34:0x38] != b"SShd":
        return None
    w = struct.unpack_from("<13I", b, 0)
    if b[w[5] + 12:w[5] + 16] != b"SShd":
        return None
    c = {"shd": [], "ssq": None, "vb": []}
    if b[w[6] + 12:w[6] + 16] == b"SShd" and w[1]:
        c["shd"] = [(w[5], w[0]), (w[6], w[1])]
    else:
        c["shd"] = [(w[5], w[0])]
    if b[w[7] + 12:w[7] + 16] == b"SSsq":
        c["ssq"] = (w[7], w[2])
    c["vb"] = [(w[8], w[3])] + ([(w[9], w[4])] if w[4] else [])
    c["ok"] = all(off + size <= len(b) for off, size in c["vb"]) and w[8] + w[3] <= w[9]
    return c


def decode_adpcm(blocks: bytes) -> list[int]:
    out, s1, s2 = [], 0, 0
    for i in range(0, len(blocks) - 15, 16):
        shift, filt = blocks[i] & 15, min(blocks[i] >> 4, 4)
        k1, k2 = FILTERS[filt]
        for byte in blocks[i + 2:i + 16]:
            for nib in (byte & 15, byte >> 4):
                v = (nib - 16 if nib > 7 else nib) << 12 >> shift
                v += (s1 * k1 + s2 * k2 + 32) >> 6
                v = max(-32768, min(32767, v))
                out.append(v)
                s2, s1 = s1, v
    return out


def split_samples(vb: bytes) -> list[tuple[int, int]]:
    """(start, end) block-aligned byte ranges split at ADPCM end flags (first silent block skipped)."""
    res, start = [], 16 if vb[:16] == bytes(16) else 0
    for i in range(start, len(vb) - 15, 16):
        if vb[i + 1] & 1:
            res.append((start, i + 16))
            start = i + 16
    if start < len(vb) - 15:
        res.append((start, len(vb)))
    return res


def main() -> None:
    if len(sys.argv) > 2 and sys.argv[1] == "wav":
        b = (MEMBERS / f"{sys.argv[2].upper()}.bin").read_bytes()
        c = parse(b)
        OUT.mkdir(parents=True, exist_ok=True)
        for n, (off, size) in enumerate(c["vb"]):
            vb = b[off:off + size]
            for k, (s, e) in enumerate(split_samples(vb)):
                pcm = decode_adpcm(vb[s:e])
                with wave.open(str(OUT / f"{sys.argv[2].upper()}_vb{n}_s{k:03d}.wav"), "wb") as w:
                    w.setnchannels(1)
                    w.setsampwidth(2)
                    w.setframerate(22050)
                    w.writeframes(struct.pack(f"<{len(pcm)}h", *pcm))
        print("done ->", OUT)
        return
    rows = ["# Sound banks (generated)", "",
            "Generated by `tools/dump_sound.py`. Layout in the script header (SShd header chunks, SSsq "
            "sequence chunk, raw SPU ADPCM VBs). Samples = runs of ADPCM blocks ending in an end-flag block.", "",
            "| Member | Size | SShd | SSsq | VB0 (bytes / samples) | VB1 (bytes / samples) | Consistent |", "|---|---|---|---|---|---|---|"]
    n = good = 0
    for f in sorted(MEMBERS.glob("*.bin")):
        b = f.read_bytes()
        c = parse(b)
        if not c:
            continue
        n += 1
        good += bool(c["ok"])
        vbs = []
        for off, size in c["vb"]:
            vbs.append(f"{size} / {len(split_samples(b[off:off + size]))}")
        vbs += [""] * (2 - len(vbs))
        rows.append(f"| {f.stem} | {len(b)} | {len(c['shd'])} | {c['ssq'][1] if c['ssq'] else ''} | {vbs[0]} | {vbs[1]} | {'yes' if c['ok'] else 'NO'} |")
    rows.insert(3, f"{n} bank members, {good} with consistent offsets/sizes.\n")
    (ROOT / "notes/18-sound-banks.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"{n} banks, {good} consistent")


if __name__ == "__main__":
    main()
