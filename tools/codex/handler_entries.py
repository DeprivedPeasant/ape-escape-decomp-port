"""Prepare and report private Ghidra boundary checks for proven overlay dispatch targets."""
import argparse
import csv
import json
import re
from collections import defaultdict,Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def inventory():
    rows = json.loads((ROOT/'extract/codex/area-overlays.json').read_text())['areas']
    out = defaultdict(lambda:{'areas':set(),'levels':set(),'types':set()})
    for row in rows:
        for handler in row['handlers']:
            if handler['space'] == 'resident':
                continue
            key = f'{handler["space"]}::{handler["address"]:08x}'
            out[key]['areas'].add(row['area'])
            out[key]['levels'].add(row['level'])
            out[key]['types'].add(handler['type'])
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode',choices=['prepare','report'])
    parser.add_argument('--propose',action='store_true')
    options = parser.parse_args()
    entries = inventory()
    if options.mode == 'prepare':
        (ROOT/'extract/codex/dispatch-entries.tsv').write_text('\n'.join(sorted(entries))+'\n')
        print(f'prepared {len(entries)} overlay targets')
        return
    baseline = ROOT/'extract/codex/dispatch-baseline.json'
    previous = ROOT/'extract/codex/handler-entries.json'
    if not baseline.exists() and previous.exists():
        baseline.write_text(previous.read_text())
    with (ROOT/'notes/decomp/codex/dispatch-entries.tsv').open() as f:
        inspected = list(csv.DictReader(f,delimiter='\t'))
    assert {r['address'] for r in inspected} == set(entries)
    decomp = (ROOT/'notes/decomp/codex/overlay-handlers.c').read_text(encoding='utf-8')
    exported = set(re.findall(r'/\* ==== .*? @ (ovl_[A-Fa-f0-9]+::[A-Fa-f0-9]+)',decomp))
    if exported != set(entries) or 'decompile failed' in decomp.lower() or 'ERROR:' in decomp:
        raise ValueError('incomplete or failed dispatch decompilation')
    counts = Counter()
    rows = []
    for result in inspected:
        key = result['address']
        status = 'exact function' if result['exact_function'] else ('inside another function' if result['containing_entry'] else 'no function defined')
        counts[status] += 1
        meta = entries[key]
        rows.append({'address':key,'areas':sorted(meta['areas']),'levels':sorted(meta['levels']),
                     'types':sorted(meta['types']),'status':status,'exact_function':result['exact_function'],
                     'containing_entry':result['containing_entry'],'containing_name':result['containing_name'],
                     'source':result['source'],'decoded':result['instruction'] != 'UNDECODED',
                     'stack_prologue':bool(result['word']) and int(result['word'],16)&0xFFFF0000 == 0x27BD0000})
    (ROOT/'extract/codex/handler-entries.json').write_text(json.dumps({'counts':dict(counts),'entries':rows},indent=2)+'\n')
    note = ['# Overlay enemy dispatch boundaries (generated)','',
            'Generated by tools/codex/handler_entries.py after private InspectDispatchEntries.java.', '',
            'Targets come only from the validated active ZED type/area pairs and the resident '
            'ZakoUpdateLoop table at 0x800AF350. They are resolved in the overlay actually loaded '
            'by each area. The inspection asks whether Ghidra has an exact function '
            'at that address, an overlapping function, or no definition. The initial read-only audit '
            'found all 50 absent, with no overlapping function. A subsequent private-only scratch '
            'pass disassembled and defined 49 after requiring a negative stack prologue. '
            'The remaining ovl_191::8013E090 is a leaf entry starting with an Obj+0xE0 load; '
            'it was inspected separately before definition. '
            'Main-project changes are proposed only through the inbox.', '',
            f'Unique overlay dispatch addresses: {len(rows)}. Boundary results: {dict(counts)}.', '',
            f'All {len(exported)} target functions decompile successfully in the private export. '
            'The leaf entry tests object flags, initializes several object fields, and returns without stack allocation. '
            'Numeric type names are proposed because the handler entry is proven while character identity is not.', '',
            'A dispatch table address proves a callable entry, but an existing containing function '
            'can be a shared-tail/alternate entry or an analysis boundary error. Such entries need '
            'control-flow review before defining a separate function. A stack adjustment is only '
            'a supporting observation, not enough to establish a function boundary by itself.', '',
            '| Address | Areas | Types | Boundary | Function / containing function | Decoded | Stack prologue |',
            '|---|---|---|---|---|---|---|']
    for row in rows:
        fmt = lambda values: ', '.join(f'{v:02X}' for v in values)
        label = row['exact_function'] or row['containing_name'] or '-'
        note.append(f'| {row["address"]} | {fmt(row["areas"])} | {fmt(row["types"])} | {row["status"]} | '
                    f'{label} | {row["decoded"]} | {row["stack_prologue"]} |')
    (ROOT/'notes/58-overlay-handlers.md').write_text('\n'.join(note)+'\n',encoding='utf-8')
    if options.propose:
        names = {}
        for line in (ROOT/'tools/symbols.csv').read_text(encoding='utf-8').splitlines():
            if line and not line.startswith('#'):
                key,name,*_ = line.split(',',2)
                names[key.lower()] = name
        proposals = []
        for row in rows:
            key = row['address']
            leaf = key == 'ovl_191::8013e090'
            if row['status'] != 'exact function' or not row['decoded'] or not (row['stack_prologue'] or leaf):
                raise ValueError(f'unvalidated entry {key}')
            if key.lower() in names:
                continue
            if len(row['areas']) == 1:
                prefix = f'Area{row["areas"][0]:02X}'
            elif len(row['levels']) == 1:
                prefix = f'Stage{row["levels"][0]:02X}'
            else:
                prefix = 'Areas'+'_'.join(f'{a:02X}' for a in row['areas'])
            types = '_'.join(f'{t:02X}' for t in row['types'])
            name = f'{prefix}_EnemyType{types}_Update'
            areas = '/'.join(f'{a:02X}' for a in row['areas'])
            proposals.append(f'{key},{name},Validated ZakoUpdateLoop dispatch entry for type(s) {types} in area(s) {areas}; private function boundary checked by disassembly/decompilation.')
        proposed_names = [line.split(',',2)[1] for line in proposals]
        if len(proposed_names) != len(set(proposed_names)) or any(n in names.values() for n in proposed_names):
            raise ValueError('handler proposal name collision')
        (ROOT/'extract/codex/handler-proposals.csv').write_text('\n'.join(proposals)+'\n')
        inbox = ROOT/'notes/codex-inbox.md'
        text = inbox.read_text(encoding='utf-8')
        title = 'missing overlay enemy dispatch entries'
        if title not in text:
            text += ('\n## 2026-10-06 14:13 AEDT — '+title+'  [status: open]\n'
                     'Evidence: notes/58-overlay-handlers.md, tools/codex/handler_entries.py; '
                     'private dispatch-entries.tsv/overlay-handlers.c. These 50 targets were absent '
                     'from the private function listing (not overlapping another function), despite '
                     'proven resident table calls in their respective loaded overlays. Forty-nine have negative '
                     'stack prologues; one leaf starts with an Obj+0xE0 field load. Disassembly/function creation '
                     'and decompilation are checked privately. '
                     'Numeric type names avoid guessing enemy identities.\n'
                     'symbols (paste into tools/symbols.csv as a new batch):\n```csv\n'+
                     '\n'.join(proposals)+'\n```\n')
            inbox.write_text(text,encoding='utf-8')
        print(f'proposals={len(proposals)}')
    print(dict(counts))


if __name__ == '__main__':
    main()
