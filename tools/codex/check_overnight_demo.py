"""End-to-end combined morning demo configuration, not original gameplay proof."""
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
from codex.build_native_viewer import build
from codex.pack_actor import pack_actor
from codex.pack_area import OUT, pack
from codex.pack_indicators import pack as indicators
from codex.pack_ui import pack_ui
from codex.check_native_viewer import ppm


def main():
    exe = build(ROOT / 'src/player')
    actor = pack_actor()
    rows = []
    for area, frame_count in ((1, 90), (5, 180)):
        scene = pack(area, sky_props=True)
        ui = pack_ui(area)
        world = indicators(area, runtime=True)
        args = [str(exe), scene['pack'], '--actor', actor['path'],
                '--ground', str(ROOT / f'extract/members/{scene["member"]:03X}.bin'),
                '--collision-exe', str(ROOT / 'extract/disc/SCUS_944.23'),
                '--player-member', str(ROOT / 'extract/members/008.bin'),
                '--ui-pack', ui['pack'], '--indicators-pack', world['pack'],
                '--native-player', '--native-camera', '--stage-camera',
                '--indicator-proximity', '--keyboard-only']
        if ui['sound_bank'] is not None:
            args += ['--music-bank', str(ROOT / f'extract/members/{ui["sound_bank"]:03X}.bin')]
        runs, images = [], []
        for repeat in range(2):
            trace = OUT / f'overnight_combined_{area:02X}_{repeat}.json'
            image = trace.with_suffix('.ppm')
            result = subprocess.run([*args, '--frames', str(frame_count), '--walk-test', str(trace),
                                     '--capture', str(image)], cwd=ROOT, capture_output=True,
                                    text=True, timeout=45, env=dict(os.environ, SDL_AUDIO_DRIVER='dummy'))
            trace.with_suffix('.log').write_text(result.stdout+'\n'+result.stderr)
            assert result.returncode == 0, (area, repeat, result.stderr)
            data = json.loads(trace.read_text())
            frames = data['frames']
            assert len(frames) == frame_count
            assert all(f['stage_camera'] and f['stage_camera_status'] == 0 for f in frames)
            assert all(f['indicator_proximity_ticks'] == i+1 for i, f in enumerate(frames))
            if area == 5:
                assert {4, 5} <= {f['stage_slot_kind'] for f in frames}
                assert {0, 1} <= {f['stage_region'] for f in frames}
            capture = json.loads(Path(str(image)+'.json').read_text())
            assert capture['native_camera'] and capture['stage_camera'] and capture['covered_pixels'] > 100
            runs.append(data)
            images.append(ppm(image))
            rows.append(dict(area=f'{area:02X}', repeat=repeat, frames=frame_count,
                             covered_pixels=capture['covered_pixels'],
                             selected_kinds=sorted({f['stage_slot_kind'] for f in frames}),
                             regions=sorted({f['stage_region'] for f in frames}),
                             music_bank=ui['sound_bank'], image=str(image.relative_to(ROOT)),
                             trace_sha256=hashlib.sha256(trace.read_bytes()).hexdigest()))
        assert runs[0] == runs[1] and images[0] == images[1], ('nondeterministic combined demo', area)
    report = dict(combined_native_frames=sum(r['frames'] for r in rows), runs=rows, failures=0)
    (OUT / 'overnight-demo-validation.json').write_text(json.dumps(report, indent=2)+'\n')
    (ROOT / 'notes/port/validation/overnight_demo_validation.md').write_text(
        '# Combined overnight demo validation\n\nGenerated by check_overnight_demo.py.\n\n' +
        f'{report["combined_native_frames"]} SDL frames across two repeated area01/05 walks; zero failures.\n\n' +
        '| Area | Repeat | Frames | Camera kinds | Regions | Covered pixels |\n'
        '|---|---|---|---|---|---|\n' +
        ''.join(f'| {r["area"]} | {r["repeat"]} | {r["frames"]} | {r["selected_kinds"]} | {r["regions"]} | {r["covered_pixels"]} |\n' for r in rows) +
        '\nNative player/body, local stage camera, runtime indicator proximity, material/sky '
        'renderer and stage music bank are enabled together. Traces and rendered pixels '
        'repeat exactly, camera status stays zero, and proximity advances every tick. '
        'Molten Lava enters both regions and selects scripted slot kinds4/5. Audio uses '
        'the SDL dummy driver: this checks integration, not listening quality or physical '
        'audio devices. Synthetic walking is a native integration check, not an original '
        'gameplay capture or full gameplay/console visual parity.\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
