"""Verify original projection constants and normal color-matrix setup, excluding GTE math."""
import json
import random
import struct
from pathlib import Path
from mips_ground_reference import Reference, da

ROOT = Path(__file__).resolve().parents[2]


def main():
    blob = (da.MEMBERS / '05B.bin').read_bytes()
    ref = Reference(blob)
    u = lambda off: struct.unpack_from('<I', blob, off)[0]
    ah = u(0x4D0)
    mt, pt = ah + u(ah + 8) * 4, ah + u(ah + 12) * 4
    clouds = []
    for prop in (7, 8, 9):
        mesh = struct.unpack_from('<H', blob, pt + 4 + prop * 12)[0]
        off = mt + struct.unpack_from('<H', blob, mt + 4 + mesh * 4)[0] * 4
        flags = u(off)
        assert mesh == prop and flags == 0xF0081003 and not flags & 0x100000
        clouds.append(dict(prop=prop, mesh=mesh, type=flags & 255, flags=flags))
    controls = []
    # Read three actual LI v0 / CTC2 v0 pairs. No GTE operation is emulated here.
    for address, expected_reg, value, name in ((0x80020A88, 26, 0x148, 'H'),
                                              (0x80020A90, 30, 0x100, 'ZSF4'),
                                              (0x80020A98, 29, 0x155, 'ZSF3')):
        li, ctc = ref.read(address, 4), ref.read(address + 4, 4)
        assert li >> 26 == 9 and (li >> 21 & 31) == 0 and (li >> 16 & 31) == 2
        assert li & 0xFFFF == value
        assert ctc >> 26 == 18 and (ctc >> 21 & 31) == 6 and (ctc >> 16 & 31) == 2
        assert (ctc >> 11 & 31) == expected_reg
        controls.append(dict(name=name, register=expected_reg, value=value))
    rng = random.Random(94423148)
    cases = 0
    expected = (4096, 4096, 0) * 3
    for _ in range(1000):
        initial = rng.randbytes(32)
        for i, b in enumerate(initial):
            ref.write(0x800EBFF0 + i, 1, b)
        calls = []

        def back(cpu, regs):
            calls.append(('back', tuple(regs[4:7])))
            return 0

        def matrix(cpu, regs):
            data = tuple(ref.read(regs[4] + i * 2, 2) for i in range(9))
            calls.append(('matrix', regs[4], data))
            return 0

        ref.call(0x80015D58, (0, rng.randrange(65536), rng.randrange(65536), rng.randrange(65536)),
                 hooks={0x800315E0: back, 0x80031600: matrix})
        assert calls == [('back', (0, 0, 0)), ('matrix', 0x800EBFF0, expected)]
        assert bytes(ref.ram[0xEBFF0:0xEC010]) == struct.pack('<9H', *expected) + initial[18:]
        cases += 1
    report = dict(projection_control_pairs=len(controls), controls=controls, fossil_clouds=clouds,
                  original_normal_color_matrix_cases=cases, failures=0)
    (ROOT / 'extract/codex/native/prop-projection-setup.json').write_text(json.dumps(report, indent=2) + '\n')
    (ROOT / 'notes/port/validation/prop_projection_setup.md').write_text(
        '# Original prop projection and normal color setup\n\nGenerated by check_prop_projection_setup.py.\n\n' +
        '\n'.join(f'- {c["name"]}: {c["value"]} (control register {c["register"]})' for c in controls) +
        f'\n- original normal color-matrix cases: {cases}\n- failures: 0\n\n' +
        'GteInitProjection contains three verified immediate/control-write pairs. '
        'Complete original SetColorMatrixMode(0) executes with only SDK SetBackColor and SetColorMatrix endpoints hooked: '
        'black background color, matrix rows (4096,4096,0), and untouched bytes after its nine halfwords agree. '
        'MeshDrawAnimColors static-color instructions load IR=(4096,0,0) before CC and use the model palette; '
        'export_area_obj already resolves primitive palette indices. Fossil cloud meshes 7/8/9 use type3 with '
        'flags 0xF0081003, whose color-animation bit 0x100000 is clear. '
        'This does not execute CC, RTPT, AVSZ4, DPCS or GPU packets, and supplies no rendered-color/depth parity proof. '
        'Actual transformed SZ values, flags, dynamic matrix state, color saturation and primitive ordering are the next evidence requirements. '
        'Do not substitute world Z for OTZ or identify type3 cloud cards with the type4/5 sky pass.\n')
    print(report)


if __name__ == '__main__':
    main()
