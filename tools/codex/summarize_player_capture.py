"""Publish aggregate real-capture findings without uploading RAM/input traces."""
import collections
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT/'extract/codex/cloud-player-review'
OUT = ROOT/'extract/cloud_evidence/player/capture_validation'

def main():
    trace = LOCAL/'player_trace.jsonl'
    records = [json.loads(s) for s in trace.read_text().splitlines() if s]
    frames = [r for r in records if r['kind']=='frame']
    assert frames
    for r in frames:
        assert all(len(bytes.fromhex(r[k]))==0x150 for k in ['pre','post_update','post_collision'])
        assert len(r['input'])==16 and len(r['ground'])==6
    increments = collections.Counter(b['frame']-a['frame'] for a,b in zip(frames,frames[1:]))
    assert dict(increments)=={1:len(frames)-1}
    comparison = json.loads((LOCAL/'full_player_audit.json').read_text())
    assert comparison['audit_all']
    assert comparison['trace_sha256']==hashlib.sha256(trace.read_bytes()).hexdigest()
    report = dict(capture_sha256=comparison['trace_sha256'],records=dict(collections.Counter(r['kind'] for r in records)),
                  first_frame=frames[0]['frame'],last_frame=frames[-1]['frame'],consecutive=True,
                  states=dict(sorted(collections.Counter(struct.unpack_from('<H',bytes.fromhex(r['pre']),0x5e)[0] for r in frames).items())),
                  markers=[r['label'] for r in records if r['kind']=='mark'],
                  hard_fall='Not captured: user found no suitable location in Fossil Field',
                  comparison={k:v for k,v in comparison.items() if k!='source_sha256'},
                  source_sha256={Path(p).name:d for p,d in comparison['source_sha256'].items()},
                  cloud_revision='935fe62464bcf03e12ec8832164151b5e5f3f021')
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/'report.json').write_bytes((json.dumps(report,indent=2)+'\n').encode())
    text=f'''# First real movement capture (generated)

Generated by tools/codex/summarize_player_capture.py from locally ignored JSONL and
check_native_player.py --audit-all output. Raw RAM/input capture is not uploaded.
Cloud revision: {report['cloud_revision']}. Sources linked unchanged.

Capture: {len(frames)} complete consecutive frames {frames[0]['frame']}..{frames[-1]['frame']},
seven scenario markers, no incomplete phase records. Hard fall was not performed;
the user found no suitable location. Analog input varies naturally and is recorded.
Markers describe intended scenarios; observed actions sometimes cross marker labels.

Results: {comparison['checked_frames']} independently seeded PlayerUpdate comparisons;
{comparison['matched_frames']} match all represented fields; {comparison['mismatched_frames']}
differ only in next_frame; {comparison['excluded_frames']} unsupported frames excluded.
All represented movement fields match in compared frames. No uninterrupted replay or
body/collision equivalence claim. Unsupported contact/attachment/gadget behavior needs work.

First mismatch: frame2020, next_frame original59/native74 (original state2 after update).
Evidence: 80060780_PlayerUpdate.c invokes PlayerAnimateAndDraw; at 80063628,
when (stateFlags & 0xF0)==0x20 or animBlend==0xFFFF it writes
nextFrame=animFrame+1 before decoding. native_player.c never writes next_frame.
This is an omitted drawing-phase side effect, not analog noise. Proposal for Claude:
model this scalar update at the original drawing call phase (before blend decrement),
or expose/test drawing separately with an explicit capture boundary. Do not exclude
the field silently. First supported mismatch is preserved when a later unsupported
case is reached; checker previously overwrote the earlier issue.

The enhanced checker rejects original post-update gadget states outside module scope
even if native flags omit them; --audit-all continues by re-seeding subsequent frames,
never counting unsupported frames as validated. Per-marker counts are in report.json.
Remaining evidence gap: continuous body/world replay, hard-fall scenario and runtime
callback geometry. Current corpus is sufficient to investigate the animation side effect;
no repeat capture needed for that finding. Original trace remains local at
extract/codex/cloud-player-review/player_trace.jsonl.
'''
    (OUT/'README.md').write_bytes(text.encode())
    print(f'Published aggregate report: {len(frames)} real frames, {comparison["checked_frames"]} compared')

if __name__=='__main__':main()
