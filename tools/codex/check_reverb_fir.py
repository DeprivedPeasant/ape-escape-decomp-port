"""Delegated FIR implementation vs independent full-convolution reference."""
import ctypes as C,json,re,shutil,subprocess
from pathlib import Path
import numpy as np
from check_adsr_counters import ROOT,OUT,DEPS,COMMIT,oracle

def main():
    OUT.mkdir(parents=True,exist_ok=True);oracle()
    # Numeric filter facts from pinned external reference, not copied algorithm code.
    text=(DEPS/'spu.cpp').read_text().split('resample_coeff = {',1)[1].split('};',1)[0]
    coeff=np.zeros(39,dtype=np.int64)
    coeff[::2]=[int(x,16) if not x.startswith('-') else -int(x[1:],16) for x in re.findall(r'-?0x[0-9A-Fa-f]+',text)]
    coeff[19]=16384
    source=OUT/'fir_probe.c';source.write_text('''#include "../../../src/audio/reverb_fir.h"
static AeReverbFir f;static int16_t d[2];
__declspec(dllexport) void reset(void){ae_reverb_fir_reset(&f);d[0]=1234;d[1]=-4321;}
__declspec(dllexport) int trace(const int16_t *in,const int16_t *wet,int n,int16_t *down,int16_t *out){
 for(int i=0;i<n;i++){
  int16_t old[2]={d[0],d[1]};int ready=ae_reverb_fir_push(&f,in+i*2,d);
  if(ready!=(int)(f.phase&1))return 1;
  if(!ready&&(d[0]!=old[0]||d[1]!=old[1]))return 2;
  down[i*2]=d[0];down[i*2+1]=d[1];ae_reverb_fir_pull(&f,wet+i*2,out+i*2);
 }
 return 0;
}
''')
    dll=OUT/'fir_probe.dll';subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',str(source),'-o',str(dll),'-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));ptr=C.POINTER(C.c_int16);lib.trace.argtypes=[ptr,ptr,C.c_int,ptr,ptr]
    rng=np.random.default_rng(94423);cases=samples=0;n=65537
    for signal in ('impulse','noise','limits','silence'):
        inputs=np.zeros((n,2),dtype=np.int16);wet=np.zeros_like(inputs)
        if signal=='impulse':inputs[0]=[32767,-32768];wet[1]=[-32768,32767]
        elif signal=='noise':
            inputs[:]=rng.integers(-32768,32768,(n,2),dtype=np.int16);wet[:]=rng.integers(-32768,32768,(n,2),dtype=np.int16)
        elif signal=='limits':inputs[::2]=32767;inputs[1::2]=-32768;wet[:]=inputs
        expected_down=np.empty_like(inputs);expected_down[0]=[1234,-4321];expected_out=np.empty_like(inputs)
        for ch in range(2):
            decimated=np.clip(np.convolve(inputs[:,ch].astype(np.int64),coeff)[:n]>>15,-32768,32767)
            expected_down[1::2,ch]=decimated[1::2];expected_down[2::2,ch]=decimated[1:n-1:2]
            stuffed=wet[:,ch].astype(np.int64).copy();stuffed[::2]=0
            expected_out[:,ch]=np.clip(np.convolve(stuffed,coeff)[:n]>>14,-32768,32767)
        for block in (1,512,735,1024):
            lib.reset();actual_down=np.empty_like(inputs);actual_out=np.empty_like(inputs)
            for start in range(0,n,block):
                length=min(n-start,block)
                assert lib.trace(inputs[start:].ctypes.data_as(ptr),wet[start:].ctypes.data_as(ptr),length,
                                 actual_down[start:].ctypes.data_as(ptr),actual_out[start:].ctypes.data_as(ptr))==0
            assert np.array_equal(actual_down,expected_down),(signal,block,'down')
            assert np.array_equal(actual_out,expected_out),(signal,block,'up')
            cases+=1;samples+=n
    report=dict(cases=cases,stereo_frames=samples,failures=0,chunk_sizes=[1,512,735,1024],oracle_coefficients_commit=COMMIT,
                scope='Independent NumPy full39tap convolution, impulse/random/extrema/silence, phase/history wrap, untouched even-phase output and chunk independence. No hardware capture or full mixer validation.')
    (OUT/'reverb-fir-validation.json').write_text(json.dumps(report,indent=2)+'\n');print(report)
    (ROOT/'notes/port/validation/reverb_fir_validation.md').write_text(f'''# Reverb FIR validation

Generated by tools/codex/check_reverb_fir.py. Sonnet5.5 implemented the header through the isolated worker bridge; Codex reviewed the files and ran these checks before integration.

{cases} cases, {samples:,} stereo frames, zero failures. Both downsample and upsample outputs match independent NumPy full39tap convolution using numeric filter coefficients read from pinned DuckStation {COMMIT}. This uses a full convolution reference rather than the native circular/polyphase implementation. Impulse, full-range noise, alternating limits and silence exercise phase/history wrapping across1/512/735/1024-frame callback sizes. Even-phase down output is verified unchanged.

This is arithmetic/filter validation against documented/reference facts, not console capture. The FIR and previously validated integer network remain separate from viewer integration. Shared music/effect wet input, output gain, disabled-master behavior and whole-song hardware/listening validation remain pending.
''')

if __name__=='__main__':main()
