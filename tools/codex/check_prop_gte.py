"""Restricted native GTE helpers versus unchanged pinned external C emulator backend."""
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
import gte_oracle
import prop_fog
import prop_materials

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


def main():
    oracle = gte_oracle.build()
    dll = OUT / f'prop_gte_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', str(ROOT / 'src/render/native_prop_gte.c'), '-o', str(dll),
                    '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    u8, u16 = C.POINTER(C.c_uint8), C.POINTER(C.c_uint16)
    lib.ae_prop_otz3.argtypes = lib.ae_prop_otz4.argtypes = [u16, u16]
    lib.ae_prop_dpcs.argtypes = [u8, u8, C.c_uint16, u8]
    depths = 0
    rng = random.Random(9442300780010)
    for n in (3, 4):
        values = (C.c_uint16 * n)()
        fun = getattr(lib, f'ae_prop_otz{n}')
        out = C.c_uint16()
        # Cover every achievable sum; random arrangements additionally exercise all SZ slots.
        for total in range(n * 65535 + 1):
            rest = total
            for i in range(n):
                values[i] = min(65535, rest)
                rest -= values[i]
            assert fun(values, C.byref(out)) == 1
            assert out.value == oracle.oracle_otz(values, n)
            depths += 1
        for _ in range(20000):
            values[:] = [rng.randrange(65536) for _ in range(n)]
            assert fun(values, C.byref(out)) == 1 and out.value == oracle.oracle_otz(values, n)
            depths += 1
    source, far, out = (C.c_uint8 * 4)(), (C.c_uint8 * 4)(), (C.c_uint8 * 4)()
    colors = 0

    def check(s, f, factor):
        nonlocal colors
        source[:] = s
        far[:3] = f
        assert lib.ae_prop_dpcs(source, far, factor, out) == 1
        actual = int.from_bytes(bytes(out), 'little')
        assert actual == oracle.oracle_dpcs(source, far, factor), (s, f, factor, tuple(out))
        colors += 1
    for factor in (0, 1, 15, 255, 256, 1023, 2047, 2048, 2049, 4095, 4096):
        for s in range(256):
            for f in range(256):
                check((s, 255-s, s*3 & 255, s ^ f), (f, 255-f, f*5 & 255), factor)
    for factor in range(4097):
        for s in range(256):
            for f in (0, 255):
                check((s, 255-s, s*3 & 255, factor & 255), (f, f, f), factor)
    synthetic = colors
    areas = palettes = 0
    for area, member in sorted(prop_materials.da.area_members().items()):
        blob = (prop_materials.MEMBERS / f'{member:03X}.bin').read_bytes()
        fields = prop_fog.load(member)
        data = prop_materials.load(member)
        for mesh in data['meshes'].values():
            m, count = mesh['offset'], mesh['colors']
            for i in range(count):
                rgba = tuple(blob[m+0x18+i*4:m+0x1C+i*4])
                for factor in (0, 1, 2048, 3825, 4096):
                    check(rgba, fields['rgb'], factor)
                palettes += 1
        areas += 1
    alias = 0
    for _ in range(2000):
        s = tuple(rng.randrange(256) for _ in range(4))
        f = tuple(rng.randrange(256) for _ in range(3))
        factor = rng.randrange(4097)
        check(s, f, factor)
        expected = bytes(out)
        assert lib.ae_prop_dpcs(source, far, factor, source) == 1 and bytes(source) == expected
        source[:] = s
        assert lib.ae_prop_dpcs(source, far, factor, far) == 1 and bytes(far) == expected
        alias += 2
    guards = 0
    for n in (3, 4):
        fun = getattr(lib, f'ae_prop_otz{n}')
        value = C.c_uint16(0xA5A5)
        assert fun(None, C.byref(value)) == 0 and value.value == 0xA5A5
        assert fun((C.c_uint16 * n)(), None) == 0
        guards += 2
    for s, f, factor, dest in ((None, far, 0, out), (source, None, 0, out),
                               (source, far, 0, None), (source, far, 4097, out),
                               (source, far, 65535, out)):
        out[:] = [0xA5] * 4
        assert lib.ae_prop_dpcs(s, f, factor, dest) == 0 and bytes(out) == b'\xA5' * 4
        guards += 1
    report = dict(oracle_commit=gte_oracle.COMMIT, areas=areas, source_palette_records=palettes,
                  avsz_cases=depths, dpcs_synthetic_cases=synthetic, dpcs_total_cases=colors,
                  alias_cases=alias, guards=guards, failures=0)
    (OUT / 'prop-gte-validation.json').write_text(json.dumps(report, indent=2) + '\n')
    (ROOT / 'notes/port/validation/prop_gte_validation.md').write_text(
        '# Restricted GTE helper validation\n\nGenerated by check_prop_gte.py.\n\n' +
        '\n'.join(f'- {k}: {v}' for k, v in report.items()) +
        '\n\nIndependent oracle: unchanged PCSX-ReARMed gte.c/gte_divider.c at the pinned revision, '
        'compiled only under ignored extract/. Its source paths/checksums are recorded in oracle-source.json. '
        'Port helpers were implemented from the documented mathematical specification; no emulator code is copied into them. '
        'All achievable sums at original ZSF3/ZSF4 constants, randomized SZ layouts, RGB pair ranges at boundary factors, '
        'all factors with every source channel and endpoint far colors, actual area palettes/fog colors, and aliases/guards agree. '
        'This is emulator differential evidence, not an original-console gameplay capture. '
        'The DPCS domain is byte far colors loaded by SetFarColor and factor0..4096, sf1/lm0. '
        'Flags, FIFOs, MAC/IR side effects, CC, full projection/SZ generation, runtime color matrices and GPU ordering are excluded. '
        'The helpers are not wired into the viewer.\n')
    print(report)


if __name__ == '__main__':
    main()
