"""Update the generated fidelity section in notes/30 from completed checks."""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/audio-audit'
MARKER = '\n## Sustained music fidelity correction (Codex, 2026-10-06)\n'


def main():
    component = json.loads((OUT / 'music-fidelity.json').read_text())
    independent = json.loads((OUT / 'spu-reference.json').read_text())
    whistle_log = OUT / 'whistle-all-music-check.log'
    log_path = whistle_log if whistle_log.exists() else OUT / 'all-music-check.log'
    log = log_path.read_text(encoding='utf-8-sig')
    pattern = r'([0-9A-F]{3}):\s+([\d.]+) s\s+rel rms diff ([\deE.+-]+)\s+peak diff ([\deE.+-]+) \(ref peak ([\d.]+)\)\s+tails ref ([\deE.+-]+) c ([\deE.+-]+)'
    rows = re.findall(pattern, log)
    # The initial sweep exposed a three-second offline release-tail truncation.
    # Keep its log intact and replace affected rows with the five-second checks.
    followup = OUT / 'final-tail-check.log'
    if followup.exists() and not whistle_log.exists():
        refreshed = {row[0]: row for row in re.findall(pattern, followup.read_text(encoding='utf-8-sig'))}
        assert set(refreshed) == {'0FB', '136'}, 'tail follow-up incomplete'
        rows = [refreshed.get(row[0], row) for row in rows]
    assert len(rows) == 43, f'full music check incomplete: {len(rows)}/43'
    for member, seconds, rms, peak, level, tail1, tail2 in rows:
        assert float(rms) < 5e-4 and float(peak) < max(float(level), 1e-9)*2e-3, member
        assert max(float(tail1), float(tail2)) < 1e-3, member
    assert '172 effects match' in (OUT / 'sfx-regression.log').read_text(encoding='utf-8-sig')
    sdl_log = OUT / ('whistle-sdl-check.log' if whistle_log.exists() else 'sdl-music-check.log')
    assert 'PASS SDL3.4.18' in sdl_log.read_text(encoding='utf-8-sig')
    assert component['failures'] == independent['failures'] == 0
    summary = dict(songs=len(rows), worst_relative_rms=max(float(row[2]) for row in rows),
                   components=component, independent=independent, failures=0)
    (OUT / 'music-validation-summary.json').write_text(json.dumps(summary, indent=2)+'\n')
    pad_rows = '\n'.join(f"| {row['sample']} | {row['pitch']} | {row['previous']['relative_rms']:.2%} | {row['updated']['relative_rms']:.2%} |"
                         for row in independent['tests'])
    note = ROOT / 'notes/30-native-audio.md'
    text = note.read_text().split(MARKER)[0]
    text = text.replace('tables 0x800B3D90 / 0x800B4190,', 'tables 0x800B3D90 / 0x800B4190 and the pitch table 0x800B38D0,')
    text = text.replace('the game\'s integer volume and pan law, SPU ADPCM samples with loops, 4 point cubic resampling,',
                        "the game's integer volume, pan and pitch laws, streaming SPU ADPCM with repeat history and Gaussian interpolation,")
    text = text.replace('* songs: `check_player.py --all`', '* original validation before the correction below: songs: `check_player.py --all`')
    text += MARKER + f'''
Generated by `python tools/codex/write_music_report.py` from the completed checks.
This section supersedes the earlier cubic/pitch approximations in notes/23 and notes/24.

The user-reported `extract/native_audio/136_ref.wav` was current: the pre-fix C render and
saved Python array agreed to relative RMS 3.73e-8, and normalized WAVs differed by at most
one PCM LSB. The issue was shared playback behavior rather than a stale export.

`SeqPitchFromNote` (0x8009E594) indexes halfwords at 0x800B38D0, adding a signed fine-tune
value and `(bendRange * (bend - 64)) >> 2`, then applies integer octave shifts and a
16-bit result mask. The SPU clamps pitch to 0x4000. Music now uses those actual EXE data,
integer LFO scaling, and increments by an exact multiple of 1/4096 input samples.
Program 28's paired Time Station pads use pitches 1490,1479,1495,1485, confirmed both
by original instructions and an independently executed PSF register trace. Floating
exponentiation previously produced 1490.589,1479.865,1495.980,1485.217; the altered
relative detuning changes beating and produces phase drift in held notes. The first
pair starts at 0.0035/0.0456 seconds, with approximately 10.783-second key-on durations.

Music voices now carry ADPCM predictor and interpolation history through each repeat
jump, with fixed-size decoder state. The four-tap filter uses the physical SPU ROM
coefficients, eight fraction bits, and integer products. The all-ones sustain rate
holds its level. Legacy SFX helpers retain their previously validated behavior.
Hardware facts and ROM data: [PSX-SPX SPU reference](https://psx-spx.consoledev.net/ps1/spu/soundprocessingunitspu/).
No emulator implementation or game data was copied into the player.

Independent references: the [Zophar PSF set](https://www.zophar.net/music/playstation-psf/ape-escape)
contains byte-identical local member-136 SSsq, SShd0 and VB0. Its replacement Wild Arms 2
driver is useful for SPU registers, but does not prove Ape Escape event/loop timing.
`render_psf_reference.py` runs a pinned [Audacious PSF core](https://github.com/audacious-media-player/audacious-plugins/tree/master/src/psf)
using HLE; `check_spu_reference.py` runs a pinned Highly Experimental SPU core with
isolated tones. These are separate test executables/libraries under ignored extract/;
they require no BIOS image and are never linked into the native port.

Validation:

- {component['original_mips_pitch_cases']:,} randomized valid pitch cases match original MIPS instructions and both C/Python.
  {component['artificial_out_of_guard']} artificial out-of-table combinations are explicitly excluded; real songs are checked separately.
- {sum(row['output_checks'] for row in component['streaming_samples']):,} C/Python sample positions agree exactly across four held-note samples,
  multiple repeat boundaries, variable rates and all 256 interpolation fractions.
- Four independent 11-second sustained-oscillator checks all improve. The metric below
  permits a constant gain and at most eight startup samples of alignment; it never
  stretches time or re-aligns individual windows. ADSR shape, event timing and reverb
  are excluded. Residual core differences mean this is not a bit-exact SPU claim.

| Sample | Pitch | Previous relative RMS error | Updated relative RMS error |
|---|---:|---:|---:|
{pad_rows}

- All {len(rows)} complete songs render successfully; worst C/Python relative RMS difference
  {summary['worst_relative_rms']:.2e}. These comparisons validate implementation agreement, not hardware accuracy.
- The initial sweep caught a Python export truncation: bank 0FB retained audible release
  beyond the fixed three-second export tail. The comparator now requests five seconds;
  0FB and Time Station were rechecked with that window. The streaming player is unchanged.
- All 172 common sound effects retain their prior reference match (worst relative peak
  difference 4.06e-7). SDL3 stream/window integration and audio failure paths pass.
- Updated Time Station: `extract/native_audio/136_ref.wav` (Python) and `136.wav` (C).
  Pre-fix comparison: `extract/codex/audio-audit/136_current.wav`. All generated audio is ignored.

Reproduce with installed system Python (numpy is available there):

```powershell
python tools/codex/render_psf_reference.py --seconds 30
python tools/codex/check_music_fidelity.py
python tools/codex/check_spu_reference.py
python tools/native_audio/check_player.py --all --wav > extract/codex/audio-audit/all-music-check.log
python tools/native_audio/check_player.py --sfx > extract/codex/audio-audit/sfx-regression.log
python tools/codex/check_sdl.py > extract/codex/audio-audit/sdl-music-check.log
python tools/codex/write_music_report.py
```

The PSF renderer expects the previously downloaded PSF ZIP in the audit directory.
The two reference tools can download their pinned emulator source into ignored extract/;
the native player itself still has no extra dependency. Listening QA has not been performed.
Remaining fidelity work includes exact ADSR phase/counter stepping, integer reverb and
frame-quantized sequencer timing; the existing song portamento and shared music/SFX
voice-budget limitations also remain.
'''
    whistle_file = OUT / 'whistle-modulation.json'
    if whistle_file.exists():
        whistle = json.loads(whistle_file.read_text())
        assert whistle['failures'] == 0
        shutil.copy2(ROOT / 'extract/native_audio/136_ref.wav', OUT / 'time_station_whistle_corrected_full.wav')
        text += f"""
## Whistle modulation follow-up (Codex, 2026-10-06)

The user's remaining warble near43s/64s is channel6/program3/sample0x1DD80,
not the program28 pad tested earlier. Its long notes begin43.132/44.143 and
64.705/65.716seconds. Controller1 changes the modulation depth between10 and50;
the sequence also contains explicit pitch-bend slides.

Original SeqUpdateVoices (0x8009CE18), with normal-music mode +0x1C=0, first
decomposes the written channel bend into signed note and fine offsets, using
truncation toward zero. It then applies the modulation waveform with a
ONE-semitone range. The previous model replaced channel bend with the waveform
and used the tone's12-semitone bend range, losing the slides and making the
vibrato twelve times too wide. The corrected music helper reproduces the
normalization, signed8-bit fine wrapping, and separate small modulation lookup.
Flag0x40 also correctly selects program header[5] as the curve index.

`python tools/codex/check_whistle_modulation.py` validates C and Python against
{whistle['original_update_cases']} executions of the original full SeqUpdateVoices routine (24-slot
loop, one seeded music voice, seven real curves). All cases pass. The whistle
line has {whistle['real_whistle_settings']} distinct real bend/depth combinations in the reported windows;
maximum modulation pitch span drops from {whistle['maximum_previous_span']} to {whistle['maximum_corrected_span']} SPU pitch units.
The current all-song sweep revalidates43 complete songs after this correction.

A separate80-second PSF trace supports the whistle's written pitch slides, but
its replacement driver does not reproduce Ape Escape's modulation. The original
instruction routine is the authority for this fix. Earlier pad-only comparisons
were not sufficient to establish correctness of this other instrument.

Current full output: extract/native_audio/136_ref.wav and136.wav; a distinct listening
copy is extract/codex/audio-audit/time_station_whistle_corrected_full.wav. Focused
comparison: extract/codex/audio-audit/time_station_whistle_fixed_40-76s.wav,
with prior output at time_station_whistle_before_40-76s.wav.
Original frame quantization and additional modulation controller/state edge
cases remain separate fidelity work; this correction does not claim bit-exact
whole-song playback or listening QA.
"""
    note.write_text(text)
    print(f'Updated {note}: 43 songs and independent component checks pass')


if __name__ == '__main__':
    main()
