"""Complete original SDK matrix instructions with independent external GTE execution."""
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
import gte_oracle
from mips_ground_reference import Reference, da, signed

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


def main():
    oracle = gte_oracle.build()
    dll = OUT / f'sdk_matrix_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', str(ROOT / 'src/math/native_sdk_matrix.c'), '-o', str(dll),
                    '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    buf = C.c_uint8 * 32
    ref = Reference((da.MEMBERS / '05B.bin').read_bytes())
    state = (C.c_uint32 * 64)()
    gte_steps = 0

    def backend(ins, value):
        nonlocal gte_steps
        gte_steps += 1
        return oracle.oracle_gte_step(state, ins, value)

    ref.gte_backend = backend

    def trace(pc, regs):
        ins = ref.read(pc, 4)
        if ins >> 26 == 0 and ins & 63 == 32:
            total = signed(regs[ins >> 21 & 31]) + signed(regs[ins >> 16 & 31])
            if not -2147483648 <= total <= 2147483647:
                raise OverflowError('original ADD trap domain')
    ref.trace = trace
    rng = random.Random(0x94423002FF50)
    # Structural identity cases, negative/padding cases, extreme rotations, plus broad raw matrices.
    identity = struct.pack('<9hH3i', 4096, 0, 0, 0, 4096, 0, 0, 0, 4096, 0xA5A5, 0, 0, 0)
    seeds = [(identity, identity)]
    for value in (-32768, -1, 0, 4096, 32767):
        seeds.append((struct.pack('<9hH3i', *([value] * 9), 0xFFFF, 20000, -20000, 10000),
                      struct.pack('<9hH3i', *([value] * 9), 0, 65535, 65536, -65537)))
    seeds += [(rng.randbytes(32), rng.randbytes(32)) for _ in range(5000)]
    seeds += [(struct.pack('<9hH3i', *struct.unpack('<9h', identity[:18]), 0, t, t, t),
               struct.pack('<9hH3i', *struct.unpack('<9h', identity[:18]), 0, d, d, d))
              for t in (-2147483648, 2147483647) for d in (-32768, -1, 1, 32767)]
    cases = traps = aliases = 0
    by_root = {}
    for name, root in (('mul_matrix0', 0x80031830), ('comp_matrix', 0x8002FF50)):
        fun = getattr(lib, 'ae_sdk_' + name)
        fun.argtypes = [C.POINTER(C.c_uint8)] * 3
        count = 0
        for left, right in seeds:
            for alias in ('none', 'left', 'right'):
                initial = rng.randbytes(32)
                a, b, out = buf.from_buffer_copy(left), buf.from_buffer_copy(right), buf.from_buffer_copy(initial)
                target = a if alias == 'left' else b if alias == 'right' else out
                original_before = bytes(target)
                for address, data in ((0x80130000, left), (0x80130040, right), (0x80130080, initial)):
                    for i, v in enumerate(data):
                        ref.write(address+i, 1, v)
                dest = {'left': 0x80130000, 'right': 0x80130040, 'none': 0x80130080}[alias]
                C.memset(state, 0, C.sizeof(state))
                try:
                    ref.call(root, (0x80130000, 0x80130040, dest))
                except OverflowError:
                    assert fun(a, b, target) == 0 and bytes(target) == original_before
                    traps += 1
                    continue
                expected = bytes(ref.ram[dest-0x80000000:dest-0x80000000+32])
                assert fun(a, b, target) == 1 and bytes(target) == expected, (name, alias, bytes(target).hex(), expected.hex())
                cases += 1
                count += 1
                if alias != 'none':
                    aliases += 1
        by_root[name] = count
    guards = 0
    for name in ('mul_matrix0', 'comp_matrix'):
        fun = getattr(lib, 'ae_sdk_' + name)
        for a, b, out_null in ((None, buf(), False), (buf(), None, False), (buf(), buf(), True)):
            out = buf(*([0xA5] * 32))
            assert fun(a, b, None if out_null else out) == 0 and bytes(out) == b'\xA5' * 32
            guards += 1
    report = dict(oracle_commit=gte_oracle.COMMIT, original_whole_matrix_cases=cases,
                  by_root=by_root, alias_cases=aliases, external_gte_steps=gte_steps,
                  original_add_trap_fail_closed_cases=traps, guards=guards, failures=0)
    (OUT / 'sdk-matrix-validation.json').write_text(json.dumps(report, indent=2) + '\n')
    (ROOT / 'notes/port/validation/sdk_matrix_validation.md').write_text(
        '# Original SDK matrix validation\n\nGenerated by check_sdk_matrix.py.\n\n' +
        '\n'.join(f'- {k}: {v}' for k, v in report.items()) +
        '\n\nComplete original MulMatrix0 and CompMatrix CPU instructions execute from extracted EXE bytes; '
        'each actual COP2 transfer/command runs through unchanged pinned PCSX-ReARMed GTE. '
        'All 32 destination bytes match in separate and both exact-alias configurations. '
        'Rotation saturation/padding, truncated right translation and preserved MulMatrix0 translation are covered. '
        'Original ADD-overflow domains are detected before the trapping instruction; native rejects with unchanged output. '
        'Original partial writes before that trap are deliberately not reproduced. '
        'This excludes partial buffer overlaps, GTE timing/flags as runtime effects, CameraLookAt and scene parity.\n')
    print(report)


if __name__ == '__main__':
    main()
