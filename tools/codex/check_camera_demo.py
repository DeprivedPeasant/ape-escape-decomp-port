"""Deterministic SDL follow-camera integration and original frame-order evidence."""
import hashlib,json,os,struct,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from codex.build_native_viewer import build
from codex.pack_area import pack,OUT
from codex.pack_actor import pack_actor
from codex.pack_ui import pack_ui
import export_model

def main():
    # Original mode ordering and zero-offset root bone justify the cached anchor.
    listing=(ROOT/'extract/cloud_evidence/archive/exports/codex/cloud-movement/8005bf70_Mode_Stage.asm.txt').read_text()
    assert listing.index('jal 0x80047bd0')<listing.index('jal 0x80060780')<listing.index('jal 0x8007247c')
    spike=export_model.parse_actor((ROOT/'extract/members/008.bin').read_bytes(),0xBC)
    assert spike and spike['ok'] and spike['bones'][0][2:]==((0,0,0),0)
    matrix=(ROOT/'extract/cloud_evidence/archive/exports/codex/cloud-player/80015504_ModelBuildBoneMatrices.asm.txt').read_text()
    for instruction in ('8001568c\tlhu v1,0x34(v0)','80015694\tsh v1,0x1c(s3)','800156a0\tsh v1,0x1e(s3)','800156ac\tsh v0,0x20(s3)'):assert instruction in matrix
    exe=build(ROOT/'src/player');scene=pack(1);actor=pack_actor();ui=pack_ui(1)
    args=[str(exe),scene['pack'],'--actor',actor['path'],'--ground',str(ROOT/'extract/members/05B.bin'),
        '--collision-exe',str(ROOT/'extract/disc/SCUS_944.23'),'--player-member',str(ROOT/'extract/members/008.bin'),
        '--ui-pack',ui['pack'],'--native-camera']
    env=dict(os.environ,SDL_AUDIO_DRIVER='dummy');runs=[]
    for frames in (90,180):
        traces=[]
        for repeat in range(2):
            trace=OUT/f'camera_walk_{frames}_{repeat}.json';image=OUT/f'camera_walk_{frames}_{repeat}.ppm'
            result=subprocess.run([*args,'--frames',str(frames),'--walk-test',str(trace),'--capture',str(image)],cwd=ROOT,env=env,capture_output=True,text=True,timeout=40)
            (OUT/f'camera_walk_{frames}_{repeat}.log').write_text(result.stdout+'\n'+result.stderr)
            assert result.returncode==0,(frames,repeat,result.stdout,result.stderr)
            data=json.loads(trace.read_text());assert len(data['frames'])==frames
            rows=data['frames'];initial=rows[0]['camera_body_at_update']
            for i,row in enumerate(rows):
                assert row['camera_status']==0,(i,row['camera_status'])
                assert row['camera_distance']>0 and row['accepted']==i+1
                body=initial if i==0 else rows[i-1]['xyz']
                render=initial if i<2 else rows[i-2]['xyz']
                assert row['camera_body_at_update']==body,(i,'body order',row['camera_body_at_update'],body)
                assert row['camera_render_at_update']==render,(i,'draw order',row['camera_render_at_update'],render)
            capture=json.loads(Path(str(image)+'.json').read_text());assert capture['native_camera'] and capture['covered_pixels']>100
            traces.append(trace.read_bytes())
            runs.append(dict(frames=frames,repeat=repeat,capture=str(image.relative_to(ROOT)),covered_pixels=capture['covered_pixels'],sha256=hashlib.sha256(traces[-1]).hexdigest()))
        assert traces[0]==traces[1],frames
    default=build();r=subprocess.run([str(default),scene['pack'],'--check'],cwd=ROOT,capture_output=True,text=True,timeout=20);assert r.returncode==0
    reject=subprocess.run([*args,'--check','--yaw','20'],cwd=ROOT,capture_output=True,text=True,timeout=20);assert reject.returncode!=0
    report=dict(runs=runs,deterministic_frames=540,original_frame_order=True,default_build=True,invalid_override_rejected=True,failures=0)
    (OUT/'camera-demo-validation.json').write_text(json.dumps(report,indent=2)+'\n');print(report)
    (ROOT/'notes/port/validation/native_camera_demo_validation.md').write_text(f'''# Native follow-camera integration validation

Generated by tools/codex/check_camera_demo.py. Strict player-enabled and default SDL builds pass. Two repeated 90-frame and two repeated 180-frame walks produce identical native state traces: 540 total frames, zero camera failure/status bits. Captures contain visible terrain and actor geometry. Incompatible manual camera overrides are rejected.

Mode_Stage instruction order is CameraUpdate, PlayerUpdate, then CollisionUpdate. The test verifies each camera body snapshot equals the previous integrated body position and its render snapshot equals the preceding draw position. Actual Spike member 008 +0xBC has first-bone offset (0,0,0), parent 0. ModelBuildBoneMatrices (flags 3, mode 0) stores the first world-bone translation at actor+0x1C, making the cached pre-collision position an evidence-backed anchor in this supported case.

Projection remains approximate; stage camera regions/scripts, water-active and stage-exit globals, original input mapping and complete player-render phase ordering remain unvalidated. These native walking traces are integration smoke tests, not console gameplay captures. Captures and raw logs stay under ignored extract/codex/native.
''')

if __name__=='__main__':main()
