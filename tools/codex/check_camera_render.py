"""Geometric conformance of the explicitly approximate camera presentation adapter."""
import ctypes as C,json,math,os,random,shutil,struct,subprocess
from pathlib import Path
from check_native_camera import Slot
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'extract/codex/native'

def main():
    OUT.mkdir(parents=True,exist_ok=True);dll=OUT/f'camera_render_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',str(ROOT/'src/camera/native_camera.c'),str(ROOT/'src/camera/native_camera_render.c'),'-o',str(dll),'-lm','-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));ptr=C.POINTER(C.c_float)
    lib.ae_camera_render_orbit.argtypes=[C.POINTER(Slot),ptr,ptr,ptr,ptr]
    lib.ae_camera_project_approx.argtypes=[C.POINTER(Slot),C.POINTER(C.c_int16),C.c_float,C.c_float,C.c_float,C.POINTER(C.c_uint32)]
    rng=random.Random(94423);worst=0;project_cases=0
    for case in range(5000):
        s=Slot();eye=[rng.randrange(-15000,15001) for _ in range(3)];target=[eye[i]+rng.randrange(-3000,3001) for i in range(3)]
        if eye[0]==target[0] and eye[2]==target[2]:target[2]+=1
        for off,vec in [(0xA,eye),(0x12,target)]:struct.pack_into('<hhh',s.raw,off,*vec)
        t=(C.c_float*3)();yaw=C.c_float();pitch=C.c_float();distance=C.c_float()
        assert lib.ae_camera_render_orbit(C.byref(s),t,C.byref(yaw),C.byref(pitch),C.byref(distance))==1
        y=math.radians(yaw.value);p=math.radians(pitch.value);d=distance.value
        delta=[-math.sin(y)*math.cos(p)*d,math.sin(p)*d,math.cos(y)*math.cos(p)*d]
        expected=[eye[0]/256,-eye[1]/256,eye[2]/256]
        error=max(abs(t[i]+delta[i]-expected[i]) for i in range(3));worst=max(worst,error);assert error<0.0001,(case,error)
        assert list(t)==[target[0]/256,-target[1]/256,target[2]/256]
        # Use a gravity basis independently of the orbit-angle conversion.
        f=[target[i]-eye[i] for i in range(3)];length=math.sqrt(sum(x*x for x in f));f=[x/length for x in f]
        horizontal=math.hypot(f[0],f[2]);right=[f[2]/horizontal,0,-f[0]/horizontal]
        down=[f[1]*right[2],f[2]*right[0]-f[0]*right[2],-f[1]*right[0]]
        point=[int(target[i]+rng.randrange(-100,101)) for i in range(3)];relative=[point[i]-eye[i] for i in range(3)]
        depth=sum(f[i]*relative[i] for i in range(3));xy=[sum(axis[i]*relative[i] for i in range(3)) for axis in (right,down)]
        out=C.c_uint32(0x12345678);point_c=(C.c_int16*3)(*point)
        assert lib.ae_camera_project_approx(C.byref(s),point_c,328,192,120,C.byref(out))==1
        expected_xy=[max(-1024,min(1023,int(offset+328*value/depth))) for value,offset in zip(xy,(192,120))]
        actual_xy=[C.c_int16(out.value&65535).value,C.c_int16(out.value>>16).value]
        assert all(abs(a-b)<=1 for a,b in zip(actual_xy,expected_xy)),(case,actual_xy,expected_xy)
        project_cases+=1
    s=Slot();struct.pack_into('<hhh',s.raw,0x12,0,0,4096)
    point=(C.c_int16*3)(100,100,4096)
    failure_cases=0
    for focal,ox,oy in [(0,192,120),(-1,192,120),(float('nan'),192,120),(float('inf'),192,120),(328,float('nan'),120),(328,192,float('inf'))]:
        out=C.c_uint32(0x12345678)
        assert lib.ae_camera_project_approx(C.byref(s),point,focal,ox,oy,C.byref(out))==0 and out.value==0x12345678
        failure_cases+=1
    behind=(C.c_int16*3)(0,0,-1);out=C.c_uint32(0x12345678)
    assert lib.ae_camera_project_approx(C.byref(s),behind,328,192,120,C.byref(out))==0 and out.value==0x12345678;failure_cases+=1
    # Large screen values saturate before any float-to-integer conversion.
    assert lib.ae_camera_project_approx(C.byref(s),point,1e30,192,120,C.byref(out))==1
    assert out.value==1023|(1023<<16)
    zero=Slot();t=(C.c_float*3)(1,2,3);yaw=C.c_float(4);pitch=C.c_float(5);distance=C.c_float(6)
    assert lib.ae_camera_render_orbit(C.byref(zero),t,C.byref(yaw),C.byref(pitch),C.byref(distance))==0
    assert list(t)==[1,2,3] and (yaw.value,pitch.value,distance.value)==(4,5,6);failure_cases+=1
    report=dict(orbit_cases=5000,project_cases=project_cases,failure_cases=failure_cases,worst_eye_error_world_units=worst,failures=0)
    (OUT/'camera-render-validation.json').write_text(json.dumps(report,indent=2)+'\n');print(report)
    (ROOT/'notes/port/validation/native_camera_render_validation.md').write_text(f'''# Approximate camera presentation validation

Generated by tools/codex/check_camera_render.py. {report}.

Orbit conversion reconstructs the input eye from the existing renderer angles and target, including its reflected horizontal basis. Projection is checked independently with a double-precision gravity basis, allowing one screen unit for floating-point rounding. Invalid projection and degenerate camera inputs preserve outputs; large screen coordinates saturate.

This validates geometry and bounds, not original GTE arithmetic, SDK view matrices, stage camera event dispatch or a console gameplay camera replay. The follow-camera integer core has separate original-instruction tests.
''')

if __name__=='__main__':main()
