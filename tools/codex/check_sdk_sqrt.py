"""Complete original SquareRoot0 calls against the external-table native helper."""
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
import gte_oracle
from mips_ground_reference import Reference

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


class Tables(C.Structure):
    _fields_ = [('values', C.c_int16 * 192), ('loaded', C.c_int)]


def main():
    oracle = gte_oracle.build()
    dll = OUT / f'sdk_sqrt_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', str(ROOT / 'src/math/native_sdk_sqrt.c'), '-o', str(dll),
                    '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    lib.ae_sdk_sqrt_load.argtypes = [C.POINTER(Tables), C.c_char_p, C.c_size_t]
    lib.ae_sdk_sqrt0.argtypes = [C.POINTER(Tables), C.c_uint32, C.POINTER(C.c_uint32)]
    exe = (ROOT / 'extract/disc/SCUS_944.23').read_bytes()
    tables = Tables()
    assert lib.ae_sdk_sqrt_load(C.byref(tables), exe, len(exe)) == 1 and tables.loaded == 1
    ref = Reference((ROOT / 'extract/members/05B.bin').read_bytes())
    state = (C.c_uint32 * 64)()
    steps = 0

    def backend(ins, value):
        nonlocal steps
        steps += 1
        return oracle.oracle_gte_step(state, ins, value)

    ref.gte_backend = backend
    rng = random.Random(0x9442300303C0)
    values = list(range(65536))
    values += [x for power in range(31) for x in (max(0, (1 << power)-1), 1 << power, (1 << power)+1)]
    values += [x for scale in range(14) for index in range(64, 256)
               for x in (index << (scale*2), (index << (scale*2)) + (1 << (scale*2))-1)
               if x <= 2147483647]
    values += [rng.randrange(2147483648) for _ in range(20000)]
    values += [2147483647, 33554432, 16777216]
    for value in values:
        C.memset(state, 0, C.sizeof(state))
        expected = ref.call(0x800303C0, (value,))[2]
        out = C.c_uint32(0xA5A5A5A5)
        assert lib.ae_sdk_sqrt0(C.byref(tables), value, C.byref(out)) == 1 and out.value == expected, (value, out.value, expected)
    guards = 0
    for table, value, nullout in ((None, 1, False), (C.byref(Tables()), 1, False),
                                 (C.byref(tables), 2147483648, False),
                                 (C.byref(tables), 0xFFFFFFFF, False), (C.byref(tables), 1, True)):
        out = C.c_uint32(0xA5A5A5A5)
        assert lib.ae_sdk_sqrt0(table, value, None if nullout else C.byref(out)) == 0 and out.value == 0xA5A5A5A5
        guards += 1
    assert lib.ae_sdk_sqrt_load(None, exe, len(exe)) == 0
    guards += 1
    for data, size in ((None, len(exe)), (exe, 100)):
        tables.loaded = 1
        assert lib.ae_sdk_sqrt_load(C.byref(tables), data, size) == 0 and tables.loaded == 0
        guards += 1
    offset = 0x800AE5C0 - 0x80010000 + 0x800
    for index, value in ((0, 4097), (191, 8174), (20, 32767)):
        bad = bytearray(exe)
        struct.pack_into('<h', bad, offset + 2*index, value)
        tables.loaded = 1
        assert lib.ae_sdk_sqrt_load(C.byref(tables), bytes(bad), len(bad)) == 0 and tables.loaded == 0
        guards += 1
    report = dict(whole_original_sqrt_calls=len(values), exhaustive_small_values=65536,
                  external_gte_steps=steps, guards=guards, oracle_commit=gte_oracle.COMMIT, failures=0)
    (OUT / 'sdk-sqrt-validation.json').write_text(json.dumps(report, indent=2)+'\n')
    (ROOT / 'notes/port/validation/sdk_sqrt_validation.md').write_text(
        '# Original SquareRoot0 validation\n\nGenerated by check_sdk_sqrt.py.\n\n' +
        '\n'.join(f'- {key}: {value}' for key, value in report.items()) +
        '\n\nComplete original CPU calls execute from EXE bytes, including GTE LZCS/LZCR '
        'through the unchanged pinned external backend. Coverage includes exhaustive '
        '0..65535, normalized table-bin boundaries at successive scales, powers of two '
        'and neighbors, INT32_MAX and randomized nonnegative signed32 values. The native '
        'helper loads the actual external EXE table; no game data is embedded in code. '
        'Negative inputs are explicitly unsupported. No full CameraLookAt, runtime '
        'matrix, GPU scene or gameplay parity claim.\n')
    print(report)


if __name__ == '__main__':
    main()
