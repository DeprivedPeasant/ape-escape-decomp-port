"""Original-MIPS distance and proximity trigger state/event comparisons."""
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
from src_paths import src
from mips_ground_reference import Reference, signed
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'extract/codex/native'
class Trigger(C.Structure):
    _fields_=[('raw',C.c_uint8*24)]
class Events(C.Structure):
    _fields_=[('activate',C.c_uint32),('effect',C.c_uint32),('index',C.c_int32),('sector',C.c_int32),('position',C.c_int32*3)]


def main():
    dll=OUT/f'indicator_trigger_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',
                    *[str(src(s+'.c')) for s in ('native_indicator_trigger','native_collision','native_ground')],
                    '-o',str(dll),'-lm','-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));lib.ae_indicator_trigger_update.argtypes=[C.POINTER(Trigger),C.POINTER(C.c_int16),C.c_int16,C.c_int32,C.c_uint32,C.c_uint32,C.POINTER(Events)]
    lib.ae_indicator_trigger_distance.argtypes=[C.POINTER(C.c_int32),C.POINTER(C.c_int16)]
    ref=Reference((ROOT/'extract/members/05B.bin').read_bytes());rng=random.Random(94423)
    for case in range(4000):
        center=[rng.randrange(-32768,32768) for _ in range(3)]
        player=[rng.randrange(-2147483648,2147483648) if case%10==0 else center[i]+rng.randrange(-2000,2000) for i in range(3)]
        delta=[signed(player[i]-center[i]) for i in range(3)]
        expected=signed(ref.call(0x80046618,delta)[2])
        actual=lib.ae_indicator_trigger_distance((C.c_int32*3)(*player),(C.c_int16*3)(*center))
        assert actual==expected,(case,player,center,actual,expected)
    event_calls=0
    for case in range(6000):
        data=bytearray(rng.randbytes(24));state=rng.choice([0,1,2,3,4,-1,-32768])
        radius=rng.choice([-32768,-1,0,1,512,32767]);distance=rng.choice([radius-1,radius,radius+1,rng.randrange(-2147483648,2147483648)])
        struct.pack_into('<h',data,2,state);struct.pack_into('<h',data,4,0);struct.pack_into('<h',data,14,radius)
        struct.pack_into('<h',data,16,rng.choice([0,0,1,-1]))
        area=rng.choice([1,0x5B,0x5C,0x62,0x63,65535]);exit_code=rng.choice([0,3,7,0x15,0x17,255]);touched=rng.choice([-32768,-1,0,1,32767])
        center=[rng.randrange(-32768,32768) for _ in range(3)]
        trigger=Trigger.from_buffer_copy(data);events=Events()
        ref.ram[0x13A000:0x13A018]=data;ref.write(0x800F455C,4,0x80130000)
        for i,v in enumerate(center):ref.write(0x80130000+i*2,2,v)
        ref.write(0x8013001E,2,touched);ref.write(0x800F4476,2,area);ref.write(0x800F447C,1,exit_code)
        calls=[]
        def activate(cpu,regs):calls.append(('activate',signed(regs[4]),signed(regs[5])));return 0
        def effect(cpu,regs):calls.append(('effect',regs[4],*[signed(regs[i]) for i in (5,6,7)]));return 0
        ref.call(0x80091178,(0x8013A000,),hooks={0x80046618:lambda cpu,regs:distance,
                                             0x800717B4:activate,0x800698E4:effect})
        assert lib.ae_indicator_trigger_update(C.byref(trigger),(C.c_int16*3)(*center),touched,distance,area,exit_code,C.byref(events))
        actual=[]
        if events.activate:actual.append(('activate',events.index,events.sector))
        if events.effect:actual.append(('effect',0x112,*events.position))
        assert actual==calls and bytes(trigger)==ref.ram[0x13A000:0x13A018],(case,state,radius,distance,calls,actual)
        event_calls+=len(calls)
    report=dict(original_distance_cases=4000,original_trigger_cases=6000,event_calls=event_calls,failures=0)
    (OUT/'indicator-trigger-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/indicator_trigger_validation.md').write_text(
        '# Indicator trigger validation\n\nGenerated by `check_indicator_triggers.py`.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items())+'\n\n'+
        'Original VecLength3 executes GTE signed16 SQR inputs and original IntSqrt instructions. '
        'Original Gimmick_ProxTrigger_Update compares complete trigger bytes and ordered activation/effect calls '
        'with controlled distance, collider touch and stage globals. No full gameplay contact/progress proof.\n')
    print(report)


if __name__=='__main__':main()
