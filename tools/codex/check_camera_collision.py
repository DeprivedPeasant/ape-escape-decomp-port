"""Original camera ground-clamp instruction/query ordering vs portable callbacks."""
import ctypes as C,json,os,random,shutil,subprocess
from pathlib import Path
from check_native_camera import Slot
from mips_ground_reference import Reference,signed
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'extract/codex/native'
Normalize=C.CFUNCTYPE(C.c_uint32,C.c_void_p,C.POINTER(C.c_int16))
Sqrt=C.CFUNCTYPE(C.c_int32,C.c_void_p,C.c_uint32)
Ground=C.CFUNCTYPE(C.c_int32,C.c_void_p,C.c_int32,C.c_int32,C.c_int32)
class Queries(C.Structure):
    _fields_=[('user',C.c_void_p),('normalize',Normalize),('sqrt',Sqrt),('ground',Ground)]

def main():
    OUT.mkdir(parents=True,exist_ok=True);dll=OUT/f'camera_collision_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',str(ROOT/'src/camera/native_camera.c'),str(ROOT/'src/camera/native_camera_collision.c'),'-o',str(dll),'-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));lib.ae_camera_ground_clamp.argtypes=[C.POINTER(Slot),C.POINTER(C.c_int16),C.POINTER(Queries)]
    lib.ae_camera_ground_clamp_near.argtypes=[C.POINTER(Slot),C.POINTER(C.c_int16),C.c_int,C.POINTER(Queries)]
    ref=Reference((ROOT/'extract/members/05B.bin').read_bytes());rng=random.Random(94423);counts={};queries=0
    for mode in ('ground','near'):
        for case in range(2000):
            raw=rng.randbytes(176);slot=Slot.from_buffer_copy(raw);ref.ram[0x13F000:0x13F0B0]=raw
            focus=[rng.randrange(-32768,32768) for _ in range(3)];normal=[rng.randrange(-32768,32768) for _ in range(3)]
            length=rng.randrange(0,0xFFFFFFFF);root=rng.choice([-100,0,1,63,64,65,32767,65536]);heights=[rng.randrange(-100000,100001) for _ in range(2)];near=rng.choice([-1,0,1,2])
            offset=0x18 if mode=='ground' else 0
            for i,v in enumerate(focus):ref.write(0x1F800000+offset+i*2,2,v)
            expected_normal=[];expected_ground=[];expected_sqrt=[]
            def norm_hook(cpu,r):
                expected_normal.append([signed(cpu.read(r[4]+i*2,2),16) for i in range(3)])
                for i,v in enumerate(normal):cpu.write(r[5]+i*2,2,v)
                return length
            def sqrt_hook(cpu,r):expected_sqrt.append(r[4]);return root
            def ground_hook(cpu,r):
                result=heights[len(expected_ground)];expected_ground.append([signed(r[i]) for i in (4,5,6)]);return result
            address=0x80048F6C if mode=='ground' else 0x8004906C
            ref.call(address,(0x8013F000,near),hooks={0x800301E0:norm_hook,0x800303C0:sqrt_hook,0x80043400:ground_hook})
            actual_normal=[];actual_ground=[];actual_sqrt=[]
            @Normalize
            def normalize(user,io):
                actual_normal.append(list(io[:3]))
                for i,v in enumerate(normal):io[i]=v
                return length
            @Sqrt
            def square_root(user,n):actual_sqrt.append(n);return root
            @Ground
            def ground(user,x,y,z):
                index=len(actual_ground);actual_ground.append([x,y,z]);return heights[index] if index<len(heights) else 0
            q=Queries(None,normalize,square_root,ground);point=(C.c_int16*3)(*focus)
            ok=lib.ae_camera_ground_clamp(C.byref(slot),point,C.byref(q)) if mode=='ground' else lib.ae_camera_ground_clamp_near(C.byref(slot),point,near,C.byref(q))
            assert ok==1 and actual_normal==expected_normal and actual_sqrt==expected_sqrt and actual_ground==expected_ground,(mode,case,'queries',actual_ground,expected_ground)
            assert bytes(slot)==bytes(ref.ram[0x13F000:0x13F0B0]),(mode,case,'slot')
            queries+=len(actual_ground);counts[mode]=counts.get(mode,0)+1
    null=Queries(None,Normalize(),Sqrt(),Ground());slot=Slot.from_buffer_copy(rng.randbytes(176));raw=bytes(slot);point=(C.c_int16*3)(0,0,0)
    assert lib.ae_camera_ground_clamp(C.byref(slot),point,C.byref(null))==0 and bytes(slot)==raw
    assert lib.ae_camera_ground_clamp_near(C.byref(slot),point,1,C.byref(null))==0 and bytes(slot)==raw
    report=dict(cases=sum(counts.values()),counts=counts,ground_queries=queries,missing_callback_checks=2,failures=0,
       scope='Original MIPS vs full slot bytes, normalize inputs, square-root arguments and ordered ground-query coordinates. Callback results deliberately supplied; exact math/world adapters and full follow remain pending.')
    (OUT/'camera-collision-validation.json').write_text(json.dumps(report,indent=2)+'\n');print(report)
    (ROOT/'notes/port/validation/native_camera_collision_validation.md').write_text(f'''# Camera ground-clamp validation

Generated by tools/codex/check_camera_collision.py. {report['cases']} cases, {queries} ordered ground queries and two missing-callback checks pass, zero failures. Full176slot bytes, normalize input vectors, square-root arguments and query coordinates match original executable instructions. Random signed extremes and squared-length/root/ground return values exercise wrapping, thresholds, byte saturation, rollback and timer state.

Callback results are deliberately supplied to isolate each routine; these tests do not validate VectorNormalSS, SquareRoot0, world geometry or the full follow camera. Missing callbacks return failure without slot writes. Sonnet implemented the bounded helpers; Codex reviewed and independently checked them.
''')

if __name__=='__main__':main()
