"""Execute actual F4 post-AVSZ4 depth prefix; excludes GTE and later culling."""
import ctypes as C
import json
import os
import random
import shutil
import subprocess
from pathlib import Path
from mips_ground_reference import Reference, da

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


def main():
    dll = OUT / f'prop_depth_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-Wall', '-Wextra', '-Werror',
                    '-O2', '-shared', str(ROOT / 'src/render/native_prop_depth.c'),
                    '-o', str(dll), '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    lib.ae_prop_f4_depth.argtypes = [C.c_uint16, C.c_uint16, C.c_uint8, C.POINTER(C.c_uint16)]
    lib.ae_prop_f4_depth.restype = C.c_int
    ref = Reference((da.MEMBERS / '05B.bin').read_bytes())

    def trace(pc, regs):
        if pc == 0x800193F0:
            regs[10] = 0x1F800000
    ref.trace = trace
    accepted = [False]

    def accept(cpu, regs):
        accepted[0] = True
        return 0

    hooks = {0x80019448: accept, 0x800197B8: lambda cpu, regs: 0}
    count = yes = no = 0

    def check(depth, near, flags):
        nonlocal count, yes, no
        ref.write(0x1F8003DC, 4, depth)
        ref.write(0x1F8003C2, 2, near)
        ref.write(0x1F8003F4, 1, flags)
        accepted[0] = False
        ref.call(0x800193F0, hooks=hooks)
        out = C.c_uint16(0xA5A5)
        result = lib.ae_prop_f4_depth(depth, near, flags, C.byref(out))
        assert result == int(accepted[0]), (depth, near, flags, result)
        if result:
            assert out.value == ref.read(0x1F8003DC, 4), (depth, near, flags, out.value)
            yes += 1
        else:
            assert out.value == 0xA5A5 and ref.read(0x1F8003DC, 4) == depth
            no += 1
        count += 1
    for near in (0, 1200, 2000, 65535):
        for flags in (0, 1):
            for depth in range(65536):
                check(depth, near, flags)
    exhaustive = count
    rng = random.Random(944234)
    for _ in range(10000):
        check(rng.randrange(65536), rng.randrange(65536), rng.randrange(256))
    assert lib.ae_prop_f4_depth(2000, 2000, 0, None) == 0
    report = dict(original_prefix_cases=count, exhaustive_cases=exhaustive,
                  accepted=yes, rejected=no, guards=1, failures=0)
    (OUT / 'prop-depth-validation.json').write_text(json.dumps(report, indent=2) + '\n')
    (ROOT / 'notes/port/validation/prop_depth_validation.md').write_text(
        '# F4 depth-prefix validation\n\nGenerated by check_prop_depth.py.\n\n' +
        '\n'.join(f'- {k}: {v}' for k, v in report.items()) +
        '\n\nOriginal EXE instructions execute from 0x800193F0 through accept at 0x80019448 '
        'or skip at 0x800197B8. Exhaustive u16 depths run at near 0/1200/2000/65535 with '
        'both near-limit flag states; additional randomized cases cover every flag byte. '
        'Acceptance, output clamping, and no output mutation on rejection match. '
        'AVSZ4/OTZ generation, subsequent NCLIP decisions, packet emission, depth-cued color '
        'and actual visibility remain excluded. No viewer integration.\n')
    print(report)


if __name__ == '__main__':
    main()
