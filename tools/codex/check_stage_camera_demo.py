"""SDL stage-camera integration at actual stage entries; no console parity claim."""
import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from codex.build_native_viewer import build
from codex.pack_area import pack,OUT
from codex.pack_actor import pack_actor
from codex.pack_ui import pack_ui


def main(areas):
    exe=build(ROOT/'src/player');actor=pack_actor()
    env=dict(os.environ,SDL_AUDIO_DRIVER='dummy');rows=[];blocked=[]
    for area in areas:
        scene=pack(area);ui=pack_ui(area)
        args=[str(exe),scene['pack'],'--actor',actor['path'],'--ground',str(ROOT/f'extract/members/{scene["member"]:03X}.bin'),
              '--collision-exe',str(ROOT/'extract/disc/SCUS_944.23'),'--player-member',str(ROOT/'extract/members/008.bin'),
              '--ui-pack',ui['pack'],'--stage-camera']
        runs=[]
        frame_count=180 if area == 5 else 90
        for repeat in range(2):
            trace=OUT/f'stage_camera_{area:02X}_{repeat}.json';image=OUT/f'stage_camera_{area:02X}_{repeat}.ppm'
            r=subprocess.run([*args,'--frames',str(frame_count),'--walk-test',str(trace),'--capture',str(image)],cwd=ROOT,env=env,
                             capture_output=True,text=True,timeout=45)
            (OUT/f'stage_camera_{area:02X}_{repeat}.log').write_text(r.stdout+'\n'+r.stderr)
            if r.returncode:
                # Existing advanced wall-response/entry geometry restrictions are independent of the camera.
                if any(reason in r.stderr for reason in ('unimplemented advanced wall responses','entry has no terrain or solid floor')):
                    blocked.append(dict(area=f'{area:02X}',reason=r.stderr.strip()));break
                raise AssertionError((area,repeat,r.returncode,r.stdout,r.stderr))
            data=json.loads(trace.read_text());frames=data['frames'];assert len(frames)==frame_count
            assert all(f.get('stage_camera') is True for f in frames),frames[0]
            # Missing stage handlers report explicit status, hold the last valid view and continue the demo.
            statuses=sorted({f['stage_camera_status'] for f in frames})
            if area == 5:
                assert statuses == [0],('Molten Lava handler unsupported',statuses)
                assert {4,5} <= {f['stage_slot_kind'] for f in frames},'Script slots never selected'
                assert {0,1} <= {f['stage_region'] for f in frames},'Molten Lava regions never entered'
            for i,f in enumerate(frames):
                if f['stage_camera_status'] and i:
                    assert f['camera_eye']==frames[i-1]['camera_eye'] and f['camera_target']==frames[i-1]['camera_target'],('failed camera moved',area,i)
            warning_transitions=sum(bool(f['stage_camera_status']) and (i==0 or f['stage_camera_status']!=frames[i-1]['stage_camera_status']) for i,f in enumerate(frames))
            assert r.stderr.count('CAMERA stage update unsupported')==warning_transitions,('warning spam',area,repeat)
            capture=json.loads(Path(str(image)+'.json').read_text())
            assert capture['native_camera'] and capture['stage_camera'] and capture['covered_pixels']>100,capture
            runs.append(trace.read_bytes())
            rows.append(dict(area=f'{area:02X}',repeat=repeat,frames=len(frames),statuses=statuses,
                             selected_kinds=sorted({f['stage_slot_kind'] for f in frames}),
                             regions=sorted({f['stage_region'] for f in frames}),
                             covered_pixels=capture['covered_pixels'],sha256=hashlib.sha256(runs[-1]).hexdigest(),
                             image=str(image.relative_to(ROOT))))
        if len(runs)==2:assert runs[0]==runs[1],('nondeterministic',area)
    assert rows,'No SDL camera cases ran'
    report=dict(runs=rows,blocked=blocked,deterministic_frames=sum(r['frames'] for r in rows),failures=0)
    (OUT/'stage-camera-demo-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/stage_camera_demo_validation.md').write_text(
        '# Stage-camera demo validation\n\nGenerated by check_stage_camera_demo.py.\n\n'+
        f'{report["deterministic_frames"]} SDL frames across {len(rows)//2} repeated actual stage-entry walks; {len(blocked)} existing collision/entry blockers; zero failures.\n\n'+
        '| Area | Repeat | Frames | Stage status | Covered pixels |\n|---|---|---|---|---|\n'+
        ''.join(f'| {r["area"]} | {r["repeat"]} | {r["frames"]} | {r["statuses"]} | {r["covered_pixels"]} |\n' for r in rows)+
        '\nLocal camera regions/scripts/blending are exercised through the native viewer. Area05 must select kinds4/5 and enter regions0/1 without missing-handler status. Native traces are smoke checks, not original gameplay captures. Approximate projection, missing indexed handlers, full event/aim/fixed/flight/RC/boss dispatch remain limitations. Raw logs/images/traces stay ignored.\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--areas',nargs='+',type=lambda s:int(s,0),default=[1,2,3,5,0x15])
    main(p.parse_args().areas)
