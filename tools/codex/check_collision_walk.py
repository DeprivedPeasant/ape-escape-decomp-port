from codex.mips_ground_reference import signed

def check_trace(reference,report):
    for frame in report['frames']:
        x,y,z=frame['xyz']
        reference.write(0x800F45E6,2,0);reference.write(0x800F45E8,2,0);reference.write(0x800F45E0,2,-1)
        expected=signed(reference.call(0x80043400,(x,y,z),limit=300000)[2])
        assert expected==y,(frame,expected)
    assert report['accepted']+report['blocked']==len(report['frames'])
    return len(report['frames'])

def main():
    executable=build();actor=pack_actor();rows=[];comparisons=0
    for area in (1,2,4,6,0x0E,5,7,0x0B,0x1D,0x37):
        packed=pack(area);member=da.MEMBERS/f'{packed["member"]:03X}.bin'
        reference,*_=full_reference(member.read_bytes())
        trace=OUT/f'collision_walk_{area:02X}.json';capture=OUT/f'collision_walk_{area:02X}.ppm'
        options=['--actor',actor['path'],'--ground',str(member),'--collision-exe',str(ROOT/'extract/disc/SCUS_944.23'),'--player','--focus-actor']
        run(executable,packed['pack'],*options,'--walk-test',trace,'--frames',120,'--capture',capture)
        report=json.loads(trace.read_text());assert len(report['frames'])==120
        assert report['accepted']>0
        comparisons+=check_trace(reference,report);ppm(capture)
        image=json.loads(Path(str(capture)+'.json').read_text());assert image['actor']
        rows.append(dict(area=area,accepted=report['accepted'],blocked=report['blocked'],contacts=report['contacts'],
                         first=report['frames'][0]['xyz'],last=report['frames'][-1]['xyz'],covered_pixels=image['covered_pixels']))
        print(f'Walk {area:02X}: {report["accepted"]} moved, {report["blocked"]} blocked, {report["contacts"]} wall contacts; original floors match',flush=True)
    # Put Spike beside an actual Fossil Field box. This must generate push contacts
    # while retaining the original floor, rather than merely exercising flat paths.
    member=da.MEMBERS/'05B.bin';reference,*_=full_reference(member.read_bytes())
    base=reference.read(0x800F455C,4)
    fixture=None
    for i in range(reference.read(0x800F45D4,2)):
        b=[signed(reference.read(base+i*56+j*2,2),16) for j in range(28)]
        if b[8]==0 and b[3]>128 and b[4]>512 and not b[12]&0x8000:
            x,z=b[0]+b[3]+130,b[2]
            y=signed(reference.call(0x80043400,(x,b[1],z),limit=300000)[2])
            if y<16384 and b[1]-b[4]<y-96<b[1]:fixture=(x,y,z);break
    assert fixture,'real box contact fixture not found'
    trace=OUT/'collision_walk_wall.json'
    run(executable,OUT/'area_01.aev','--actor',actor['path'],'--ground',member,
        '--actor-pos',fixture[0]/256,-fixture[1]/256,fixture[2]/256,
        '--player','--walk-test',trace,'--frames',120)
    wall=json.loads(trace.read_text());assert wall['contacts']>0
    comparisons+=check_trace(reference,wall)
    # Keep the guard tested even after every real static response class is implemented.
    # Make an owned malformed response fixture; extracted game assets remain untouched.
    broken=bytearray(member.read_bytes());ah=struct.unpack_from('<I',broken,0x4D0)[0]
    table=ah+struct.unpack_from('<I',broken,ah+0x10)[0]*4
    boxes=table+struct.unpack_from('<I',broken,table+8)[0]
    struct.pack_into('<H',broken,boxes+2+16,0x3001)
    struct.pack_into('<H',broken,boxes+2+24,0)
    invalid=OUT/'unsupported_response.bin';invalid.write_bytes(broken)
    outcome=run(executable,OUT/'area_01.aev','--actor',actor['path'],'--ground',invalid,
                '--player','--check',success=False)
    assert 'unimplemented advanced wall responses' in outcome.stderr
    result=dict(areas=rows,comparisons=comparisons,wall_fixture=fixture,wall_contacts=wall['contacts'],
                wall_blocked=wall['blocked'],unsupported_response_rejected=True,failures=0)
    (OUT/'collision-walk-validation.json').write_text(json.dumps(result,indent=2)+'\n')
    note=['# Native collision walking milestone (generated)','',
          'Generated by `tools/codex/check_collision_walk.py`. This supersedes the terrain-only walking checkpoint. Component reconstruction and coverage: notes/69-native-collision.md.','',
          '## Try it','', '```powershell','uv run --offline python tools/codex/build_native_viewer.py --player --run','```','',
          'After building, `tools/codex/run_native_demo.cmd` launches the prepared Fossil Field demo. WASD moves Spike; P toggles player/camera controls, right mouse or arrows orbit, wheel zooms, F focuses Spike, Home fits the area, C toggles collider outlines, T toggles textures and Escape closes. Space pauses animation.','',
          'The runtime reads original area entries, terrain, solid shape stacks, collider volumes and the original angle lookup asset. Native C handles floor/contact selection and the implemented original eight-probe horizontal/ceiling response. The runtime contains no emulator, BIOS or interpreted original instructions. Original MIPS execution is an offline test oracle.','',
          'Assets retain the exporter convention (x,-y,z). The shared view reflects camera X to compensate for its handedness; scenery, actor and collider outlines use the same view. Camera-relative movement uses the inverse reflected basis, while floor/collision coordinates stay in original PSX space.','',
          'Development controls remain: 30 Hz ticks, six exported units/second, radius128/height512 body proxy, normalized WASD, floor snapping and a 128-unit maximum height change. These are inspection controls; original acceleration, state transitions, landing, gravity, jump, climbing, moving-platform updates and camera behavior are still missing. Climb-target radial contacts return the original status but do not activate the player climbing state.','',
          '## Integration validation','',
          f'{len(rows)} real areas each have a deterministic 120-frame GPU capture, including terrainless area0x0E using solid floors and areas containing curved, half-pipe, trench and rope volumes. {comparisons} final positions match complete original GetGroundHeight instructions. A real Fossil Field box fixture produces {wall["contacts"]} wall contacts and {wall["blocked"]} blocked ticks. A mutated unsupported-response fixture still rejects walking explicitly.','',
          '| Area | Moved ticks | Blocked ticks | Wall contacts |','|---|---:|---:|---:|']
    note += [f'| 0x{r["area"]:02X} | {r["accepted"]} | {r["blocked"]} | {r["contacts"]} |' for r in rows]
    note += ['', 'Assets, binaries, captures and reports remain ignored under `extract/codex/native/`. Report: `collision-walk-validation.json`; captures: `collision_walk_<area>.ppm` for the tested area ids. PSX material/lighting/ordering and cloud/backdrop artifacts remain approximate. This is an advancing native prototype, not a playable full game.','']
    (ROOT/'notes/68-native-terrain-walk.md').write_text('\n'.join(note),encoding='utf-8')
    print(f'PASS: {comparisons} integrated original floor checks, wall contacts={wall["contacts"]}')
if __name__=='__main__':main()
