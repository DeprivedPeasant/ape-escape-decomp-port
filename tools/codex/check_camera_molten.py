from check_camera_math import Tables
from check_camera_select import Slot
from check_camera_collision import Queries,Normalize,Sqrt,Ground
from mips_ground_reference import Reference,signed
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'extract/codex/native'
BP=C.POINTER(C.c_uint8)

def main(source_dir):
    dll=OUT/f'camera_molten_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',
        str(source_dir/'native_camera_molten.c'),str(ROOT/'src/camera/native_camera.c'),
        str(ROOT/'src/camera/native_camera_math.c'),str(ROOT/'src/camera/native_camera_focus.c'),'-o',str(dll),'-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));lib.ae_camera_molten_update.argtypes=[C.POINTER(Slot),C.POINTER(Tables),C.POINTER(Queries),C.POINTER(C.c_int32),BP,BP]
    lib.ae_camera_math_load.argtypes=[C.POINTER(Tables),C.c_char_p,C.c_size_t]
    exe=(ROOT/'extract/disc/SCUS_944.23').read_bytes();math=Tables();assert lib.ae_camera_math_load(C.byref(math),exe,len(exe))
    area=(ROOT/'extract/members/05B.bin').read_bytes();ref=Reference(area);root=Reference(area)
    overlay=(ROOT/'extract/members/18D.bin').read_bytes();ref.ram[0x13D000:0x13D000+len(overlay)]=overlay
    rng=random.Random(5_18_94423);sqrt_calls=[]
    @Sqrt
    def sqrt(user,square):
        sqrt_calls.append(square);return signed(root.call(0x800303C0,(square,))[2])
    # This handler uses native SDK normalization, only the sqrt query is a required callback.
    @Normalize
    def unused_normalize(user,io):raise AssertionError('Unexpected normalization query')
    @Ground
    def unused_ground(user,x,y,z):raise AssertionError('Unexpected ground query')
    queries=Queries(None,unused_normalize,sqrt,unused_ground)
    def memset(cpu,r):
        for i in range(r[6]):cpu.write(r[4]+i,1,r[5])
        return r[4]
    counts=0
    for case in range(6000):
        raw=bytearray(rng.randbytes(176));scratch=rng.randbytes(128);focus=bytearray(rng.randbytes(8))
        low=[rng.randrange(-10000,10001) for _ in range(3)]
        player=[signed((rng.randrange(65536)<<16)|(v&65535)) for v in low]
        # Keep both SDK squared-length operations outside their signed-add overflow trap.
        for off in (0xA,0xC,0xE):struct.pack_into('<h',raw,off,rng.randrange(-10000,10001))
        for i in range(3):struct.pack_into('<h',focus,i*2,rng.randrange(-10000,10001))
        if case%20==0:struct.pack_into('<h',focus,0,low[0]);struct.pack_into('<h',focus,4,low[2])
        ref.ram[0x130000:0x1300B0]=raw;ref.ram[0xE68C0:0xE68C8]=focus;ref.scratch[:128]=scratch
        for i,v in enumerate(player):ref.write(0x800EC204+i*4,4,v)
        ref.call(0x80140B0C,(0x80130000,),hooks={0x800A3740:memset},limit=30000)
        slot=Slot.from_buffer_copy(raw);sc=(C.c_uint8*128).from_buffer_copy(scratch);fo=(C.c_uint8*8).from_buffer_copy(focus)
        assert lib.ae_camera_molten_update(C.byref(slot),C.byref(math),C.byref(queries),(C.c_int32*3)(*player),fo,sc),case
        assert bytes(slot)==ref.ram[0x130000:0x1300B0],('slot',case,[(hex(i),a,b) for i,(a,b) in enumerate(zip(bytes(slot),ref.ram[0x130000:0x1300B0])) if a!=b])
        assert bytes(sc)==ref.scratch[:128],('scratch',case)
        counts+=1
    before=(bytes(slot),bytes(sc));assert not lib.ae_camera_molten_update(C.byref(slot),None,C.byref(queries),(C.c_int32*3)(*player),fo,sc)
    assert (bytes(slot),bytes(sc))==before
    report=dict(original_handler_cases=counts,actual_sdk_sqrt_queries=len(sqrt_calls),transactional_missing_math=1,failures=0)
    (OUT/'camera-molten-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/camera_molten_validation.md').write_text('# Molten Lava camera handler validation\n\nGenerated by check_camera_molten.py.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items())+'\n\nComplete original overlay18D entry80140B0C executes with actual focus/SDK normalization/square-root/smoothing instructions. Only BIOS memset is supplied. All176 slot and128 scratch bytes compare. Synthetic inputs cover signed fullword positions, zero horizontal focus distance and randomized pre-existing scratch/padding. This is instruction evidence, not console gameplay parity.\n')
    print(report)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source-dir',type=Path,default=ROOT/'src/camera');main(p.parse_args().source_dir)
