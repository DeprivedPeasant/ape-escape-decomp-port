"""Complete original ApplyMatrixLV CPU/GTE instruction comparison, all output bytes."""
import ctypes as C
import itertools
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
import gte_oracle
from mips_ground_reference import Reference, da

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


def main():
    oracle = gte_oracle.build()
    dll = OUT / f'sdk_apply_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', str(ROOT / 'src/math/native_sdk_apply.c'), '-o', str(dll),
                    '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    buf, vec = C.c_uint8 * 32, C.c_uint8 * 16
    lib.ae_sdk_apply_matrix_lv.argtypes = [C.POINTER(C.c_uint8)] * 3
    ref = Reference((da.MEMBERS / '05B.bin').read_bytes())
    state = (C.c_uint32 * 64)()
    steps = 0

    def backend(ins, value):
        nonlocal steps
        steps += 1
        return oracle.oracle_gte_step(state, ins, value)
    ref.gte_backend = backend
    rng = random.Random(0x944230030450)
    identity = struct.pack('<9hH3i', 4096, 0, 0, 0, 4096, 0, 0, 0, 4096, 0xFFFF, 1, 2, 3)
    seeds = [(identity, struct.pack('<3iI', *v, 0xA5A5A5A5)) for v in itertools.product(
        (-2147483648, -2147483647, -65536, -32768, -1, 0, 32767, 65536, 2147483647), repeat=3)]
    seeds += [(struct.pack('<9hH3i', *([x] * 9), 0xA5A5, 1, 2, 3),
               struct.pack('<3iI', *v, 0xA5A5A5A5))
              for x in (-32768, -1, 0, 4096, 32767)
              for v in itertools.product((-2147483648, 0, 2147483647), repeat=3)]
    seeds += [(rng.randbytes(32), rng.randbytes(16)) for _ in range(10000)]
    cases = aliases = 0
    for matrix, vector in seeds:
        for alias in (False, True):
            initial = rng.randbytes(16)
            m, v, out = buf.from_buffer_copy(matrix), vec.from_buffer_copy(vector), vec.from_buffer_copy(initial)
            target = v if alias else out
            for address, data in ((0x80130000, matrix), (0x80130040, vector), (0x80130080, initial)):
                for i, b in enumerate(data):
                    ref.write(address+i, 1, b)
            dest = 0x80130040 if alias else 0x80130080
            C.memset(state, 0, C.sizeof(state))
            ref.call(0x80030450, (0x80130000, 0x80130040, dest))
            expected = bytes(ref.ram[dest-0x80000000:dest-0x80000000+16])
            assert lib.ae_sdk_apply_matrix_lv(m, v, target) == 1 and bytes(target) == expected, (
                matrix.hex(), vector.hex(), alias, bytes(target).hex(), expected.hex())
            cases += 1
            aliases += int(alias)
    guards = 0
    for m, v, nullout in ((None, vec(), False), (buf(), None, False), (buf(), vec(), True)):
        out = vec(*([0xA5]*16))
        assert lib.ae_sdk_apply_matrix_lv(m, v, None if nullout else out) == 0 and bytes(out) == b'\xA5'*16
        guards += 1
    report = dict(oracle_commit=gte_oracle.COMMIT, whole_original_apply_cases=cases,
                  exact_alias_cases=aliases, external_gte_steps=steps, guards=guards, failures=0)
    (OUT / 'sdk-apply-validation.json').write_text(json.dumps(report, indent=2)+'\n')
    (ROOT / 'notes/port/validation/sdk_apply_validation.md').write_text(
        '# Original ApplyMatrixLV validation\n\nGenerated by check_sdk_apply.py.\n\n' +
        '\n'.join(f'- {k}: {v}' for k, v in report.items()) +
        '\n\nComplete original CPU instructions execute from extracted EXE bytes; actual GTE register transfers '
        'and both high/low matrix commands run through unchanged pinned PCSX-ReARMed source. '
        'All 16 output bytes match, including untouched padding, exact input/output alias, INT32_MIN, '
        'signed extremes, signed16 matrix extremes and randomized raw buffers. '
        'This reproduces the original split/truncation/wrapped arithmetic, not a generic full-precision matrix multiply. '
        'No CameraLookAt, screen projection, runtime matrices, scene or cloud-parity claim.\n')
    print(report)


if __name__ == '__main__':
    main()
