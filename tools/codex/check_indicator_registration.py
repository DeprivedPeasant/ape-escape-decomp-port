"""Compare actual-area presentation placements with original trigger initializers."""
import json
import struct
from pathlib import Path
from mips_ground_reference import Reference, signed
from pack_indicators import registrations, area_members, ROOT, OUT
import dump_objects as objects


def main():
    ref = Reference((ROOT/'extract/members/05B.bin').read_bytes())
    comparisons = disabled = 0
    for area, member in sorted(area_members().items()):
        blob = (ROOT/f'extract/members/{member:03X}.bin').read_bytes()
        rows = registrations(area, blob)
        _, instances = objects.parse(blob)
        ah = struct.unpack_from('<I', blob, 0x4D0)[0]
        co = ah+struct.unpack_from('<I', blob, ah+16)[0]*4
        boxes = co+struct.unpack_from('<I', blob, co+8)[0]
        n = struct.unpack_from('<H', blob, boxes)[0]
        ref.ram[0x130000:0x130000+n*56] = blob[boxes+2:boxes+2+n*56]
        ref.write(0x800F455C, 4, 0x80130000)
        ref.write(0x800F4476, 2, area)
        for row in rows:
            index = row['object']; source = struct.pack('<HHh9h', *instances[index])
            ref.ram[0x13A000:0x13A018] = source
            captured = []

            def register(cpu, regs):
                position = [signed(cpu.read(regs[5]+i*2, 2), 16) for i in range(3)]
                captured.append((signed(regs[4], 16), signed(regs[6], 16), position))
                return 2

            ref.call(0x80091060, (0x8013A000,), hooks={0x80097678: lambda cpu, regs: 0,
                                                   0x800716EC: register})
            assert captured == [(row['kind'], row['angle'], row['position'])], (area, row, captured)
            assert ref.read(0x8013A014, 2) == 2
            comparisons += 1
            ref.ram[0x13A000:0x13A018] = source
            ref.call(0x80091060, (0x8013A000,), hooks={0x80097678: lambda cpu, regs: 1,
                                                   0x800716EC: register})
            assert len(captured) == 1 and ref.read(0x8013A002, 2) == 2
            assert ref.read(0x80130000+row['collider']*56+24, 2)&0x8000
            disabled += 1
    report = dict(areas=101, original_init_placements=comparisons, time_attack_disabled=disabled, failures=0)
    (OUT/'indicator-init-validation.json').write_text(json.dumps(report, indent=2)+'\n')
    (ROOT/'notes/port/validation/indicator_registration_validation.md').write_text(
        '# Indicator placement validation\n\nGenerated by `check_indicator_registration.py`.\n\n'+
        '\n'.join(f'- {k}: {v}' for k, v in report.items())+'\n\n'+
        'The complete original Gimmick_ProxTrigger_Init executes on every actual registered trigger. '
        'Only IsTimeAttack and Indicator_Register are intercepted: the former supplies each mode, '
        'the latter records kind, angle and position. Time attack prevents registration; the native '
        'presentation currently represents the ordinary mode only. No ongoing trigger or progress logic claim.\n')
    print(report)


if __name__ == '__main__':
    main()
