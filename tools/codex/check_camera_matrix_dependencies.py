"""Check long VectorNormal against the existing bounded signed16 math adapter."""
import ctypes as C
import itertools
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
import gte_oracle
from check_camera_math import Tables
from mips_ground_reference import Reference, signed

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


def main():
    oracle = gte_oracle.build()
    dll = OUT / f'camera_long_normal_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', str(ROOT / 'src/camera/native_camera_math.c'),
                    '-o', str(dll), '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    lib.ae_camera_math_load.argtypes = [C.POINTER(Tables), C.c_char_p, C.c_size_t]
    lib.ae_camera_normalize.argtypes = [C.POINTER(Tables), C.POINTER(C.c_int16), C.POINTER(C.c_uint32)]
    exe = (ROOT / 'extract/disc/SCUS_944.23').read_bytes()
    tables = Tables()
    assert lib.ae_camera_math_load(C.byref(tables), exe, len(exe)) == 1
    ref = Reference((ROOT / 'extract/members/05B.bin').read_bytes())
    state = (C.c_uint32 * 64)()
    steps = 0

    def backend(ins, value):
        nonlocal steps
        steps += 1
        return oracle.oracle_gte_step(state, ins, value)

    ref.gte_backend = backend
    rng = random.Random(0x9442300301B0)
    vectors = list(itertools.product((-2147483648, -65535, -32768, -1, 0, 32767, 65535, 2147483647), repeat=3))
    vectors += [tuple(signed(rng.getrandbits(32)) for _ in range(3)) for _ in range(10000)]
    vectors += [(x, y, z) for x, y, z in itertools.product((-65535, -4096, 0, 4096, 65535), repeat=3)]
    cases = excluded = 0
    for vector in vectors:
        narrowed = tuple(signed(x, 16) for x in vector)
        if sum(x*x for x in narrowed) > 2147483647:
            excluded += 1  # Original signed ADD traps; do not execute its undefined continuation.
            continue
        initial = rng.randbytes(16)
        for address, data in ((0x80130000, struct.pack('<3iI', *vector, 0xA5A5A5A5)),
                              (0x80130040, initial)):
            for i, byte in enumerate(data):
                ref.write(address+i, 1, byte)
        C.memset(state, 0, C.sizeof(state))
        result = ref.call(0x800301B0, (0x80130000, 0x80130040))[2]
        v = (C.c_int16 * 3)(*narrowed)
        length = C.c_uint32()
        assert lib.ae_camera_normalize(C.byref(tables), v, C.byref(length)) == 1
        expected = struct.pack('<3i', *v) + initial[12:]
        actual = bytes(ref.ram[0x130040:0x130050])
        assert actual == expected and result == length.value, (vector, actual.hex(), expected.hex())
        cases += 1
    report = dict(whole_original_long_normal_calls=cases, signed_add_trap_cases_excluded=excluded,
                  external_gte_steps=steps, oracle_commit=gte_oracle.COMMIT, failures=0)
    (OUT / 'camera-matrix-dependencies.json').write_text(json.dumps(report, indent=2)+'\n')
    (ROOT / 'notes/port/validation/camera_matrix_dependencies.md').write_text(
        '# Camera matrix dependency validation\n\nGenerated by check_camera_matrix_dependencies.py.\n\n' +
        '\n'.join(f'- {key}: {value}' for key, value in report.items()) +
        '\n\nThe complete original VectorNormal (0x800301B0) and its normalization core execute '
        'from EXE bytes through the actual pinned external GTE backend. Signed32 inputs are '
        'truncated to signed16 by the original IR transfers; the existing bounded native '
        'VectorNormalSS math yields the same three signed32 results and squared length '
        'after this narrowing. All 16 output bytes match, including untouched padding. '
        'Inputs include full signed32 random values, INT32_MIN, signed extremes and '
        'camera eye/target difference boundaries. Original signed ADD overflow cases are '
        'excluded explicitly. This validates the reuse contract, not a new long-vector API '
        'or full CameraLookAt, SquareRoot0, runtime matrices or projection.\n')
    print(report)


if __name__ == '__main__':
    main()
