"""Explicit controller-free launch checks against prior validated camera/proximity traces."""
import hashlib,json,os,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from codex.build_native_viewer import build
from codex.pack_area import pack,OUT
from codex.pack_actor import pack_actor
from codex.pack_ui import pack_ui
from codex.pack_indicators import pack as indicators

def main():
    # These are ignored local baseline artifacts from the pre-option integration suites.
    baselines={}
    for name in ('camera_walk_90_0','camera_walk_180_0','indicator_proximity_01_0','indicator_proximity_05_0','indicator_proximity_15_0'):
        baselines[name]=json.loads((OUT/(name+'.json')).read_text())
    exe=build(ROOT/'src/player');actor=pack_actor();rows=[]
    env=dict(os.environ,SDL_AUDIO_DRIVER='dummy')
    env.pop('SDL_JOYSTICK_DIRECTINPUT',None)
    for name,baseline in baselines.items():
        proximity=name.startswith('indicator')
        area=int(name.split('_')[-2],16) if proximity else 1
        scene=pack(area);ui=pack_ui(area);trace=OUT/('keyboard_'+name+'.json')
        args=[str(exe),scene['pack'],'--actor',actor['path'],'--ground',str(ROOT/f'extract/members/{scene["member"]:03X}.bin'),
              '--collision-exe',str(ROOT/'extract/disc/SCUS_944.23'),'--player-member',str(ROOT/'extract/members/008.bin'),
              '--ui-pack',ui['pack'],'--keyboard-only','--frames',str(len(baseline['frames'])),'--walk-test',str(trace)]
        if proximity:args+=['--indicators-pack',indicators(area,runtime=True)['pack'],'--indicator-proximity']
        else:args+=['--native-camera']
        r=subprocess.run(args,cwd=ROOT,env=env,capture_output=True,text=True,timeout=30)
        (OUT/('keyboard_'+name+'.log')).write_text(r.stdout+'\n'+r.stderr)
        assert not r.returncode,(name,r.stderr)
        result=json.loads(trace.read_text());assert result['frames']==baseline['frames'],name
        rows.append(dict(case=name,frames=len(result['frames'])))
    default=build();scene=pack(1);images=[]
    for flag in ([],['--keyboard-only']):
        image=OUT/('keyboard_default_'+str(len(images))+'.ppm')
        child_env=env if flag else dict(env,SDL_JOYSTICK_DIRECTINPUT='0')
        r=subprocess.run([str(default),scene['pack'],'--frames','2','--capture',str(image),*flag],
                         cwd=ROOT,env=child_env,capture_output=True,text=True,timeout=20)
        assert not r.returncode,r.stderr
        images.append(hashlib.sha256(image.read_bytes()).hexdigest())
    assert images[0]==images[1],'Controller-free renderer differs'
    report=dict(walk_frames=sum(r['frames'] for r in rows),prior_trace_matches=len(rows),default_image_equal=True,
                directinput_hint_used_for_keyboard_only=False,failures=0,cases=rows)
    (OUT/'keyboard-startup-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/keyboard_startup_validation.md').write_text('# Keyboard-only startup validation\n\nGenerated by check_keyboard_startup.py.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items() if k!='cases')+'\n\nUses ignored prior camera/proximity integration traces. Exact frame records match in controller-free runs without disabling DirectInput through environment hints. Default renderer output matches the normal controller-enabled path launched with the documented DirectInput hint. Physical controller behavior is not tested.\n')
    print(report)
if __name__=='__main__':main()
