"""Validate raw per-triangle prop material identity against actual source bytes and OBJ emission."""
import collections,json,struct,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
import dump_areas as da
import export_area_obj as obj
import export_model as em
from codex.prop_materials import load,PropMaterialError,parse_mesh

def main():
 rows=[];total=semi=skipped=inherited=0;modes=collections.Counter();fossil=[]
 for area,member in sorted(da.area_members().items()):
  blob=(da.MEMBERS/f'{member:03X}.bin').read_bytes();d=load(member);tris=d['triangles']
  path=obj.OUT/f'area_{area:02X}'/f'area_{area:02X}.obj'
  if not path.exists():obj.export(area,member,obj.uv_table())
  faces=[];group=material=None
  for line in path.read_text().splitlines():
   if line.startswith('o '):group=line.split()[1]
   elif line.startswith('usemtl '):material=line.split()[1]
   elif line.startswith('f ') and group and group.startswith('prop_'):faces.append((group,material,line))
  assert len(faces)==len(tris),(area,len(faces),len(tris))
  for r,(group,material,face) in zip(tris,faces):
   assert group==f'prop_{r["prop_index"]}_mesh{r["mesh_index"]}'
   expected='white' if r['tpage'] is None else f'tp{r["tpage"]&0x19F:03X}_c{r["clut"]:04X}'
   if material!=expected:
    assert r["tpage"] is None,(area,r,material)
    inherited+=1
   off=r['primitive_offset'];assert blob[off+3]&0xFC==r['code'] and bool(blob[off+3]&2)==r['semi']
   if r['tpage'] is not None:
    assert struct.unpack_from('<H',blob,off+0x12)[0]==r['tpage']
    assert struct.unpack_from('<H',blob,off+0xE)[0]==r['clut']
   assert len(face.split())==4
  ns=sum(r['semi'] for r in tris);total+=len(tris);semi+=ns;skipped+=len(d['skipped'])
  modes.update(r['blend_mode'] for r in tris if r['semi'] and r['tpage'] is not None)
  rows.append(dict(area=f'{area:02X}',member=f'{member:03X}',triangles=len(tris),semi=ns,skipped=len(d['skipped'])))
  if area==1:
   ah=struct.unpack_from('<I',blob,0x4D0)[0];props=ah+struct.unpack_from('<I',blob,ah+12)[0]*4
   for i in sorted({r['prop_index'] for r in tris if r['semi']}):
    values=struct.unpack_from('<HHhhhH',blob,props+4+i*12)
    counts=collections.Counter((r['tpage'],r['clut'],r['blend_mode']) for r in tris if r['prop_index']==i and r['semi'])
    fossil.append(dict(prop=i,mesh=values[0],position=values[2:5],materials=[dict(tpage=k[0],clut=k[1],blend=k[2],triangles=v) for k,v in counts.items()]))
 # Bad table/mesh source ranges must fail, not emit a partial run.
 guard=0
 for blob in (b'',b'\0'*5):
  try:parse_mesh(blob,0,0)
  except PropMaterialError:guard+=1
  else:raise AssertionError('Malformed source accepted')
 report=dict(areas=len(rows),triangles=total,semi_triangles=semi,semi_blend_modes=dict(modes),skipped_placements=skipped,
             untextured_inherited_obj_materials=inherited,malformed_guards=guard,failures=0,area_rows=rows,fossil_semi_props=fossil)
 out=ROOT/'extract/codex/overnight/prop-material-validation.json';out.write_text(json.dumps(report,indent=2)+'\n')
 (ROOT/'notes/port/validation/prop_material_validation.md').write_text('# Prop material metadata validation\n\nGenerated by check_prop_materials.py.\n\n'+
   '\n'.join(f'- {k}: {v}' for k,v in report.items() if k not in ('area_rows','fossil_semi_props'))+'\n\nAll per-triangle placement/mesh identifiers and textured material keys match the existing OBJ emission sequence. Untextured faces inheriting a prior OBJ material are counted separately (exporter emits no usemtl for an initial untextured primitive). Code, semi, tpage and CLUT fields match raw source bytes. This validates metadata identity, not GPU blending, runtime CLUTs, primitive rendering or full original geometry transforms.\n')
 print({k:v for k,v in report.items() if k not in ('area_rows','fossil_semi_props')});print('Fossil semi props',fossil)
if __name__=='__main__':main()
