"""Original-MIPS register and animation-slice checks for world indicators."""
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
from check_camera_math import Tables
from mips_ground_reference import Reference, signed
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT/'extract/codex/native'


class Indicator(C.Structure):
    _fields_ = [('raw', C.c_uint8*24)]


def main():
    dll = OUT/f'indicators_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror',
                    '-shared', str(ROOT/'src/indicators/native_indicators.c'),
                    str(ROOT/'src/camera/native_camera_math.c'), '-o', str(dll), '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll)); ip = C.POINTER(Indicator)
    lib.ae_camera_math_load.argtypes = [C.POINTER(Tables), C.c_char_p, C.c_size_t]
    lib.ae_indicator_register.argtypes = [ip, C.POINTER(C.c_uint32), C.c_int16, C.c_char_p,
                                        C.c_int32, C.POINTER(Tables)]
    lib.ae_indicator_step.argtypes = [ip, C.POINTER(C.c_uint16), C.POINTER(C.c_uint16)]
    t = Tables(); exe = (ROOT/'extract/disc/SCUS_944.23').read_bytes()
    assert lib.ae_camera_math_load(C.byref(t), exe, len(exe))
    ref = Reference((ROOT/'extract/members/05B.bin').read_bytes()); rng = random.Random(94423)
    for case in range(2000):
        initial = rng.randbytes(96); slots = (Indicator*4).from_buffer_copy(initial)
        count = C.c_uint32(case%4); pos = rng.randbytes(8)
        kind = rng.randrange(-32768, 32768); angle = rng.randrange(-2147483648, 2147483648)
        ref.ram[0xBBD34:0xBBD94] = initial
        ref.write(0x800BBC50, 4, count.value); ref.ram[0x13A000:0x13A008] = pos
        result = ref.call(0x800716EC, (kind, 0x8013A000, angle))[2]
        assert lib.ae_indicator_register(slots, C.byref(count), kind, pos, angle, C.byref(t)) == result
        assert count.value == ref.read(0x800BBC50, 4)
        assert bytes(slots) == ref.ram[0xBBD34:0xBBD94], case
    for case in range(6000):
        data = bytearray(rng.randbytes(24))
        kind = rng.choice([-32768, -1, 0, 1, 2, 3, 32767])
        frame = rng.choice([0, 27, 28, 29, 57, 58, 87, 88, 89, 65535, rng.randrange(65536)])
        state = rng.choice([0, 1, 2, 65535])
        timer = rng.choice([-32768, -1, 0, 1, 90, 32767])
        struct.pack_into('<h', data, 0, kind); struct.pack_into('<h', data, 10, timer)
        struct.pack_into('<HH', data, 20, frame, state)
        slot = Indicator.from_buffer_copy(data); a = C.c_uint16(12345); b = C.c_uint16(54321)
        ref.ram[0xBBD34:0xBBD4C] = data
        ref.write(0x800BBCB0, 2, a.value); ref.write(0x800BBD20, 2, b.value)
        # Execute exactly the recovered animation block; GTE/drawing are outside
        # this slice. Set the original live s1/s5/s6 on entry, exit before RTPS reads.
        def live(pc, regs):
            if pc == 0x80071A90:
                regs[17] = 0x800BBD34; regs[21] = 1; regs[22] = 0x800BBC50
        ref.trace = live
        ref.call(0x80071A90, hooks={0x80071B6C: lambda cpu, regs: 0})
        lib.ae_indicator_step(C.byref(slot), C.byref(a), C.byref(b))
        assert bytes(slot) == ref.ram[0xBBD34:0xBBD4C], (case, kind, frame, state, timer)
        assert (a.value, b.value) == (ref.read(0x800BBCB0, 2), ref.read(0x800BBD20, 2))
    ref.trace = None
    slots = (Indicator*4).from_buffer_copy(rng.randbytes(96)); before = bytes(slots)
    count = C.c_uint32(4)
    assert lib.ae_indicator_register(slots, C.byref(count), 0, bytes(8), 0, C.byref(t)) == -1
    assert bytes(slots) == before and count.value == 4
    count.value = 0; t.loaded = 0
    assert lib.ae_indicator_register(slots, C.byref(count), 0, bytes(8), 0, C.byref(t)) == -1
    assert bytes(slots) == before and count.value == 0
    report = dict(register_cases=2000, original_animation_slice_cases=6000, failure_checks=2, failures=0)
    (OUT/'indicators-state-validation.json').write_text(json.dumps(report, indent=2)+'\n')
    (ROOT/'notes/port/validation/indicators_validation.md').write_text(
        '# Indicator state validation\n\nGenerated by `check_native_indicators.py`.\n\n'+
        '\n'.join(f'- {k}: {v}' for k, v in report.items())+'\n\n'+
        'Registration executes the complete original routine including original SDK trig. '
        'Animation executes the original instruction slice 0x80071A90..0x80071B68 with live '
        'registers supplied explicitly. GTE, draw, activation and progress logic are outside these checks.\n')
    print(report)


if __name__ == '__main__':
    main()
