from codex.pack_indicators import pack as indicators
from codex.build_native_viewer import build
from codex.check_native_viewer import ppm

def main():
    exe=build(ROOT/'src/player');actor=pack_actor();rows=[];count=0
    for area in (1,5,0x15):
        baseline=json.loads((OUT/f'indicator_proximity_{area:02X}_0.json').read_text())['frames']
        scene=pack(area,prop_materials=True);ui=pack_ui(area);world=indicators(area,runtime=True)
        args=[str(exe),scene['pack'],'--actor',actor['path'],'--ground',str(ROOT/f'extract/members/{scene["member"]:03X}.bin'),
              '--collision-exe',str(ROOT/'extract/disc/SCUS_944.23'),'--player-member',str(ROOT/'extract/members/008.bin'),
              '--ui-pack',ui['pack'],'--indicators-pack',world['pack'],'--indicator-proximity','--keyboard-only']
        runs=[]
        for repeat in range(2):
            trace=OUT/f'materials_walk_{area:02X}_{repeat}.json';image=trace.with_suffix('.ppm')
            r=subprocess.run([*args,'--frames','90','--walk-test',str(trace),'--capture',str(image)],cwd=ROOT,
                             env=dict(os.environ,SDL_AUDIO_DRIVER='dummy'),capture_output=True,text=True,timeout=30)
            (trace.with_suffix('.log')).write_text(r.stdout+'\n'+r.stderr);assert not r.returncode,r.stderr
            frames=json.loads(trace.read_text())['frames'];assert frames==baseline,(area,'movement changed')
            runs.append(ppm(image));count+=len(frames)
        assert runs[0]==runs[1],(area,'render nondeterministic')
        untextured=OUT/f'materials_untextured_{area:02X}.ppm'
        r=subprocess.run([*args,'--untextured','--frames','1','--capture',str(untextured)],cwd=ROOT,
                         capture_output=True,text=True,timeout=30);assert not r.returncode,r.stderr;ppm(untextured)
        rows.append(dict(area=f'{area:02X}',frames=180,untextured_check=True))
    report=dict(deterministic_material_walk_frames=count,unchanged_prior_movement=True,untextured_captures=3,failures=0,cases=rows)
    (OUT/'prop-demo-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/prop_demo_validation.md').write_text('# Material-aware demo validation\n\nGenerated by check_prop_demo.py.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items() if k!='cases')+'\n\nRepeated SDL captures are byte deterministic in areas01/05/15. Every player/world trace frame equals the prior proximity prototype output. Textured and untextured views render successfully; static material conversion does not establish console visual parity.\n')
    print(report)
if __name__=='__main__':main()
