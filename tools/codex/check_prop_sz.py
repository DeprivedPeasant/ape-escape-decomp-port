"""Depth-only RTPS result against unchanged pinned emulator; no screen projection claim."""
import ctypes as C
import itertools
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
import gte_oracle
import prop_materials as pm

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'extract/codex/native'


def main():
    oracle = gte_oracle.build()
    dll = OUT / f'prop_sz_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'), '-std=c11', '-Wall', '-Wextra', '-Werror', '-O2',
                    '-shared', str(ROOT / 'src/render/native_prop_sz.c'), '-o', str(dll),
                    '-static-libgcc'], check=True)
    lib = C.CDLL(str(dll))
    vec = C.c_int16 * 3
    lib.ae_prop_sz.argtypes = [C.POINTER(C.c_int16), C.c_int32, C.POINTER(C.c_int16), C.POINTER(C.c_uint16)]
    row, vertex, output = vec(), vec(), C.c_uint16()
    cases = 0

    def check(r, tz, v):
        nonlocal cases
        row[:] = r
        vertex[:] = v
        assert lib.ae_prop_sz(row, tz, vertex, C.byref(output)) == 1
        wanted = oracle.oracle_sz(row, tz, vertex)
        assert output.value == wanted, (r, tz, v, output.value, wanted)
        cases += 1
    for r in itertools.product((-32768, -1, 0, 4096, 32767), repeat=3):
        for v in itertools.product((-32768, 0, 32767), repeat=3):
            for tz in (-2147483648, -2147483647, -65536, -1, 0, 65535, 65536, 2147483647):
                check(r, tz, v)
    edge = cases
    rng = random.Random(944230180001)
    for _ in range(100000):
        check(tuple(rng.randrange(-32768, 32768) for _ in range(3)),
              rng.randrange(-2147483648, 2147483648),
              tuple(rng.randrange(-32768, 32768) for _ in range(3)))
    areas = source_vertices = 0
    for area, member in sorted(pm.da.area_members().items()):
        blob = (pm.MEMBERS / f'{member:03X}.bin').read_bytes()
        for mesh in pm.load(member)['meshes'].values():
            m, count = mesh['offset'], mesh['verts']
            start = m + struct.unpack_from('<H', blob, m + 0x10)[0] * 4
            for i in range(count):
                v = struct.unpack_from('<hhh', blob, start + i * 8)
                check((0, 0, 4096), 8000, v)
                check((2048, -1024, 3072), -2000, v)
                source_vertices += 1
        areas += 1
    alias = 0
    for _ in range(2000):
        r = tuple(rng.randrange(-32768, 32768) for _ in range(3))
        v = tuple(rng.randrange(-32768, 32768) for _ in range(3))
        tz = rng.randrange(-2147483648, 2147483648)
        check(r, tz, v)
        wanted = output.value
        assert lib.ae_prop_sz(row, tz, vertex, C.cast(vertex, C.POINTER(C.c_uint16))) == 1
        assert vertex[0] & 0xFFFF == wanted
        vertex[:] = v
        assert lib.ae_prop_sz(row, tz, vertex, C.cast(row, C.POINTER(C.c_uint16))) == 1
        assert row[0] & 0xFFFF == wanted
        alias += 2
    guards = 0
    for r, v, out in ((None, vertex, C.byref(output)), (row, None, C.byref(output)),
                      (row, vertex, None)):
        output.value = 0xA5A5
        assert lib.ae_prop_sz(r, 0, v, out) == 0 and output.value == 0xA5A5
        guards += 1
    report = dict(oracle_commit=gte_oracle.COMMIT, areas=areas, source_vertices=source_vertices,
                  edge_cases=edge, total_depth_cases=cases, alias_cases=alias, guards=guards, failures=0)
    (OUT / 'prop-sz-validation.json').write_text(json.dumps(report, indent=2) + '\n')
    (ROOT / 'notes/port/validation/prop_sz_validation.md').write_text(
        '# Depth-only RTPS validation\n\nGenerated by check_prop_sz.py.\n\n' +
        '\n'.join(f'- {k}: {v}' for k, v in report.items()) +
        '\n\nIndependent oracle executes full RTPS(sf1/lm0) from unchanged pinned PCSX-ReARMed source. '
        'Only resulting SZ3 is compared. Extreme signed32 translations exercise signed44 wrap; signed16 '
        'rows/vertices, randomized inputs, actual mesh vertices at two synthetic transforms, aliases and guards agree. '
        'The transforms are test inputs, not captured original camera matrices. Flags, other GTE registers/FIFOs, '
        'matrix composition, screen projection, runtime matrices, draw culling and GPU ordering remain excluded. '
        'No viewer fog integration or visual-parity claim.\n')
    print(report)


if __name__ == '__main__':
    main()
