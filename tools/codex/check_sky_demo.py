"""Sky SDL captures / exact prior movement and legacy visual regression."""
import json,os,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from codex.pack_area import pack,OUT
from codex.pack_actor import pack_actor
from codex.pack_ui import pack_ui
from codex.pack_indicators import pack as indicators
from codex.build_native_viewer import build
from codex.check_native_viewer import ppm

def main():
    exe=build(ROOT/'src/player');actor=pack_actor();frames_checked=0;legacy_equal=0
    for area in (1,5,0x15):
        baseline=json.loads((OUT/f'indicator_proximity_{area:02X}_0.json').read_text())['frames']
        prior=OUT/f'pre_sky_materials_walk_{area:02X}.ppm'
        if not prior.exists():prior.write_bytes((OUT/f'materials_walk_{area:02X}_0.ppm').read_bytes())
        ui=pack_ui(area);world=indicators(area,runtime=True);scene=pack(area,sky_props=True)
        args=['--actor',actor['path'],'--ground',str(ROOT/f'extract/members/{scene["member"]:03X}.bin'),
              '--collision-exe',str(ROOT/'extract/disc/SCUS_944.23'),'--player-member',str(ROOT/'extract/members/008.bin'),
              '--ui-pack',ui['pack'],'--indicators-pack',world['pack'],'--indicator-proximity','--keyboard-only']
        def capture(path,label,extra=(),walk=True):
            trace=OUT/f'sky_demo_{area:02X}_{label}.json';image=trace.with_suffix('.ppm')
            options=['--frames','90','--walk-test',str(trace)] if walk else ['--frames','1']
            r=subprocess.run([str(exe),path,*args,*extra,*options,'--capture',str(image)],cwd=ROOT,
                env=dict(os.environ,SDL_AUDIO_DRIVER='dummy'),capture_output=True,text=True,timeout=30)
            trace.with_suffix('.log').write_text(r.stdout+'\n'+r.stderr);assert not r.returncode,r.stderr
            if walk:assert json.loads(trace.read_text())['frames']==baseline,(area,label,'movement changed')
            return ppm(image)
        legacy=pack(area,prop_materials=True)
        assert capture(legacy['pack'],'legacy')==ppm(prior),(area,'legacy pixels changed');legacy_equal+=1
        images=[capture(scene['pack'],str(repeat)) for repeat in range(2)]
        assert images[0]==images[1],(area,'sky render nondeterministic');frames_checked+=180
        capture(scene['pack'],'untextured',('--untextured',),walk=False)
        capture(scene['pack'],'combined',('--native-camera','--stage-camera'),walk=False)
    report=dict(sky_exact_prior_walk_frames=frames_checked,legacy_pixel_equal_areas=legacy_equal,
                sky_untextured_captures=3,combined_stage_proximity_launches=3,failures=0)
    (OUT/'sky-demo-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/sky_demo_validation.md').write_text('# Sky demo validation\n\nGenerated by check_sky_demo.py.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items())+'\n\nRepeated sky captures are deterministic in areas01/05/15; all movement/world frames match the prior prototype exactly. Legacy material screenshots remain pixel identical. Untextured views and combined stage-camera/proximity launches succeed. These tests do not establish console scene parity or complete gameplay.\n')
    print(report)
if __name__=='__main__':main()
