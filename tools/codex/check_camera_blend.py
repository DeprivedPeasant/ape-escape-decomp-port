"""Whole original CameraApplySlot instructions and multi-tick blend checks."""
import argparse
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
from check_camera_select import Slot
from mips_ground_reference import Reference

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'extract/codex/native'


def main(source_dir):
    dll=OUT/f'camera_blend_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',
                    str(source_dir/'native_camera_blend.c'),str(ROOT/'src/camera/native_camera.c'),
                    '-o',str(dll),'-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));bp=C.POINTER(C.c_uint8)
    lib.ae_camera_apply_slot.argtypes=[bp,C.POINTER(Slot),bp,bp]
    ref=Reference((ROOT/'extract/members/05B.bin').read_bytes());rng=random.Random(47_94423)
    direct=blended=0

    def compare(data,raw,eye_bytes,target_bytes):
        controls=(C.c_uint8*80).from_buffer_copy(data);slot=Slot.from_buffer_copy(raw)
        eye=(C.c_uint8*8).from_buffer_copy(eye_bytes);target=(C.c_uint8*8).from_buffer_copy(target_bytes)
        ref.ram[0xE68D0:0xE6920]=data;ref.ram[0x130000:0x1300B0]=raw
        ref.ram[0xF45A8:0xF45B0]=eye_bytes;ref.ram[0xF45B0:0xF45B8]=target_bytes
        ref.call(0x80047FF0)
        assert lib.ae_camera_apply_slot(controls,C.byref(slot),eye,target)==1
        assert bytes(controls)==ref.ram[0xE68D0:0xE6920]
        assert bytes(eye)==ref.ram[0xF45A8:0xF45B0] and bytes(target)==ref.ram[0xF45B0:0xF45B8],(
            struct.unpack_from('<H',data,0x30)[0],data[0x2E],bytes(eye).hex(),ref.ram[0xF45A8:0xF45B0].hex())
        assert bytes(slot)==raw and ref.ram[0x130000:0x1300B0]==raw
        return bytes(controls),bytes(eye),bytes(target)

    for case in range(12000):
        data=bytearray(rng.randbytes(80));raw=rng.randbytes(0xB0)
        struct.pack_into('<I',data,8,0x80130000)
        timer=rng.choice([0,0,1,2,3,7,31,32,47,48,127,128,129,255,32767,32768,65535,rng.randrange(65536)])
        struct.pack_into('<H',data,0x30,timer);data[0x2E]=rng.choice([0,1,2,3,4,255])
        compare(data,raw,rng.randbytes(8),rng.randbytes(8))
        if timer:blended+=1
        else:direct+=1
    ticks=0;durations=[]
    for style in range(4):
        data=bytearray(rng.randbytes(80));raw=rng.randbytes(0xB0)
        struct.pack_into('<I',data,8,0x80130000);struct.pack_into('<H',data,0x30,128)
        data[0x2E]=style;eye=rng.randbytes(8);target=rng.randbytes(8);duration=0
        while struct.unpack_from('<H',data,0x30)[0]:
            data,eye,target=compare(data,raw,eye,target);ticks+=1;duration+=1
            assert duration<=128
        data,eye,target=compare(data,raw,eye,target);ticks+=1
        assert eye==raw[0x0A:0x12] and target==raw[0x12:0x1A]
        durations.append(duration)
    controls=(C.c_uint8*80).from_buffer_copy(rng.randbytes(80));slot=Slot.from_buffer_copy(rng.randbytes(0xB0))
    eye=(C.c_uint8*8).from_buffer_copy(rng.randbytes(8));target=(C.c_uint8*8).from_buffer_copy(rng.randbytes(8))
    before=(bytes(controls),bytes(slot),bytes(eye),bytes(target))
    for args in ((None,C.byref(slot),eye,target),(controls,None,eye,target),
                 (controls,C.byref(slot),None,target),(controls,C.byref(slot),eye,None)):
        assert not lib.ae_camera_apply_slot(*args)
        assert (bytes(controls),bytes(slot),bytes(eye),bytes(target))==before
    report=dict(original_blend_cases=12000,direct_copy_cases=direct,blended_cases=blended,
                original_sequence_ticks=ticks,style_durations=durations,null_argument_checks=4,failures=0)
    (OUT/'camera-blend-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/camera_blend_validation.md').write_text(
        '# Camera blend validation\n\nGenerated by check_camera_blend.py.\n\n'+
        '\n'.join(f'- {key}: {value}' for key,value in report.items())+'\n\n'+
        'Complete original CameraApplySlot executes with actual integer instructions. '
        'All80controls/currenteye8/target8/unchangedslot bytes match, including arbitrary '
        '16-bit counters, all blendstyles, negative-coordinate rounding and padding. '
        'Four complete128-to-zero blend sequences also match. This is not renderer/gameplay capture proof.\n')
    print(report)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir',type=Path,default=ROOT/'src/camera')
    main(parser.parse_args().source_dir)
