"""Exercise real viewer draw batches and OpenGL blend states with synthetic local packs."""
import json,os,struct,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from codex.build_native_viewer import build
from codex.pack_area import OUT,HEADER
from codex.check_native_viewer import ppm

def scene(mode,back,front,coverage):
    verts=[]
    for z,size in ((-.1,2),(0,1)):
        corners=((-size,-size),(size,-size),(-size,size),(size,size))
        for i in (0,1,2,2,1,3):verts.append((*corners[i],z,.5,.5,1,1,1))
    data=bytearray(HEADER.pack(b'AEVIEW2\0',2,1,0x5B,12,2,3,0,4,-2,-2,-.1,2,2,0))
    for b in ((0,6,0,1,0xFFFFFFFF,0),(6,6,1,1,2,1|(mode<<1))):data.extend(struct.pack('<6I',*b))
    for v in verts:data.extend(struct.pack('<8f',*v))
    for rgb,alpha in ((back,255),(front,255 if coverage=='opaque' else 0),(front,255 if coverage=='semi' else 0)):
        pixels=bytes((*rgb,alpha))*65536;data.extend(struct.pack('<3I',256,256,len(pixels)));data.extend(pixels)
    return data

def main():
    exe=build();rows=[]
    cases=[(m,(80,120,160),(40,64,96),'semi') for m in range(4)]
    cases += [(1,(224,224,224),(80,64,40),'semi'),(2,(16,32,48),(96,96,96),'semi'),
              (0,(80,120,160),(0,0,0),'semi'),(0,(80,120,160),(40,64,96),'opaque'),
              (0,(80,120,160),(40,64,96),'transparent')]
    for index,(mode,b,f,coverage) in enumerate(cases):
        path=OUT/f'blend_probe_{index}.aev';path.write_bytes(scene(mode,b,f,coverage));image=path.with_suffix('.ppm')
        r=subprocess.run([str(exe),str(path),'--keyboard-only','--frames','1','--target','0','0','0',
                          '--yaw','0','--pitch','0','--distance','6','--capture',str(image)],
                         cwd=ROOT,capture_output=True,text=True,timeout=20)
        assert not r.returncode,r.stderr
        pixels=ppm(image)
        with image.open('rb') as file:
            file.readline();w,h=map(int,file.readline().split())
        offset=((h//2)*w+w//2)*3;actual=tuple(pixels[offset:offset+3])
        if coverage=='opaque':expected=f
        elif coverage=='transparent':expected=b
        else:
            funcs=(lambda B,F:(B+F)/2,lambda B,F:B+F,lambda B,F:B-F,lambda B,F:B+F/4)
            expected=tuple(max(0,min(255,round(funcs[mode](B,F)))) for B,F in zip(b,f))
        assert all(abs(a-e)<=1 for a,e in zip(actual,expected)),(index,actual,expected)
        rows.append(dict(mode=mode,coverage=coverage,actual=actual,expected=expected))
    report=dict(actual_viewer_gl_cases=len(rows),mode_count=4,saturation_and_stp_gating=True,failures=0,cases=rows)
    (OUT/'prop-blend-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/prop_blend_validation.md').write_text('# Prop blend validation\n\nGenerated by check_prop_blending.py.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items() if k!='cases')+'\n\nReal viewer batches exercise four OpenGL equivalents, positive/negative saturation, valid black semi texels, opaque texels and transparent holes. Center RGB agrees within one byte of the documented host formulas. Synthetic data does not establish original PSX five-bit arithmetic, primitive order or scene parity.\n')
    print(report)
if __name__=='__main__':main()
