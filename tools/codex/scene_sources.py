def load_list(member,address):
    b=(em.MEMBERS/f'{member:03X}.bin').read_bytes()
    rows=[]
    for i in range(16):
        offset=address-0x80136000+i*8
        if not 0<=offset<=len(b)-8:raise ValueError('overlay load-list bounds')
        source,post,dest=struct.unpack_from('<HhI',b,offset)
        if post<0:return rows
        if source>=0x200 or post not in (0,1,2):raise ValueError('overlay load record')
        rows.append((source,post,dest))
    raise ValueError('overlay list lacks terminator')


def configurations():
    result={}
    # Two alternating model/animation descriptors, initialized by Ovl182_Init.
    rows=load_list(0x182,0x80137828)
    assert (0x029,0,0x80154000) in rows and (0x028,1,0x80154000) in rows
    result[0x029]=(2,4,8,8,0x028,'ovl182')
    # Two stage-clear actors: model +4+i*4, animation +18+i*4.
    for address in (0x80139544,0x80139564,0x80139584):
        rows=load_list(0x187,address)
        raw=[m for m,p,d in rows if p==0 and d==0x80154000]
        tim=[m for m,p,d in rows if p==1 and d==0x80154000]
        assert len(raw)==len(tim)==1
        result[raw[0]]=(2,4,0x18,4,tim[0],'stageclear')
    # Special entry switches only the raw member, with one TIM override.
    rows=load_list(0x18B,0x801389B4)
    assert (0x02F,0,0x80154000) in rows and (0x02C,1,0x80154000) in rows
    for raw in range(0x02F,0x036):
        result[raw]=(2,4,0x0C,4,0x024 if raw==0x034 else 0x02C,'specialentry')
    # PickScene selects from fourteen 12-byte records; +8 changes raw load member.
    rows=load_list(0x18A,0x80136E34)
    assert (0x045,0,0x80154000) in rows and (0x044,1,0x80154000) in rows
    b=(em.MEMBERS/'18A.bin').read_bytes()
    selected={struct.unpack_from('<H',b,0xE54+i*12)[0] for i in range(14)}
    assert selected==set(range(0x045,0x04A))
    for raw in selected:result[raw]=(2,4,0x0C,4,0x044,'ovl18a')
    return result


def scene_clips():
    result={}
    for member,(slots,modelbase,animbase,stride,tim,label) in configurations().items():
        mem=f'{member:03X}';b=(em.MEMBERS/f'{mem}.bin').read_bytes()
        count=struct.unpack_from('<I',b)[0]
        if not 1<=count<=64:raise ValueError(f'{mem}: descriptor count')
        sections=sorted({struct.unpack_from('<H',b,4+i*4)[0]*4 for i in range(count)})
        if sections[0]!=4+count*4:raise ValueError(f'{mem}: descriptor header extent')
        for slot in range(slots):
            model,mkind=struct.unpack_from('<HH',b,modelbase+slot*stride)
            table,akind=struct.unpack_from('<HH',b,animbase+slot*stride)
            model*=4;table*=4
            if (mkind,akind)!=(3,10):raise ValueError(f'{mem}/{slot}: descriptor type')
            m=em.parse_actor(b,model)
            if not m or not m['ok']:raise ValueError(f'{mem}/{slot}: model invalid')
            clips=struct.unpack_from('<I',b,table)[0]
            if not 1<=clips<=1024:raise ValueError(f'{mem}/{slot}: clip count')
            stream=table+4+clips*4
            limit=next((p for p in sections if p>table),len(b))
            source=[]
            for index in range(clips):
                first,last=struct.unpack_from('<HH',b,table+4+index*4)
                if first>last:raise ValueError(f'{mem}/{slot}/{index}: frame range')
                layout(b,stream,len(m['bones']),last,limit)
                source.append((f'{label}_slot{slot}_clip{index:02X}',stream,first,last,1,'channels'))
            result[(mem,model)]=source
    return result


def scene_vram(member):
    config=configurations().get(int(member,16))
    if config is None:return None
    import vram
    tim=config[4];vr=vram.global_vram()
    images=vram.dt.parse_tims((em.MEMBERS/f'{tim:03X}.bin').read_bytes())
    if not images:raise ValueError('scene texture list empty')
    for image in images:vram.dt.upload(vr,image)
    return vr,tim


def main():
    import export_gltf as gl
    clips=scene_clips();config=configurations();allclips=gl.clip_metadata()
    exported=0
    for member,offset,m in em.scan_members():
        if int(member,16) in config:
            gl.export(member,offset,m,allclips.get((member,offset),[]),30)
            exported+=1
    result={'members':len(config),'actor_associations':len(clips),'clips':sum(map(len,clips.values())),
            'exported_scanner_models':exported,'failures':[]}
    (gl.OUT/'scene-associations.json').write_text(json.dumps(result,indent=2)+'\n')
    note=['# Compact scene actor bundles (generated)','',
          'Generated by tools/codex/scene_sources.py. Private scene-mode-loaders.c, scene-animation-loaders.c '
          'and model-callers.c establish load lists and initializer pairings. All load-list records, '
          'descriptor types, model bodies, inclusive clip ranges and channel extents validate against extracted data.','',
          'Ovl182_Init initializes two actors from alternating model/animation descriptors at +4/+8 with stride eight. '
          'Its fixed list loads raw 029 and TIM 028. Stage-clear mode selects three load lists with raw 02D/02E/026, '
          'TIM 02C/02C/024; DrawWipe initializes two actors from model +4+i*4 and animation +18+i*4. '
          'Member 026 is already resolved by the stage-start loader; the sources match and that naming is retained.','',
          'Special-area entry uses raw 02F by default for destination area 2; branches select 030/031/032/033/034/035 '
          'for source areas 6/0F/14/1E/35/default. Raw 034 also changes TIM 02C to 024. '
          'Its initializer pairs model +4+i*4 with animation +0C+i*4 for two actors.','',
          'Ovl18A_PickScene reads fourteen 12-byte records and selects raw 045..049; the TIM member remains 044. '
          'The two initialized models use the same +4/+0C pairing. The inspected UpdateSpin path draws slot 0 only; '
          'slot 1 animation is nevertheless explicitly initialized, so its source clips are available without '
          'claiming they are shown by that path.','',
          f'Validated {len(config)} source members / {len(clips)} actor associations / {sum(map(len,clips.values()))} clips. '
          f'Refreshed {exported} scanner-model exports. All animation streams are the channel format from notes/61.','',
          '| Data member | Loader | TIM | Actor associations | Clips |','|---|---|---|---|---|']
    for member,c in sorted(config.items()):
        sources=[v for (mem,_),v in clips.items() if int(mem,16)==member]
        note.append(f'| {member:03X} | {c[5]} | {c[4]:03X} | {len(sources)} | {sum(map(len,sources))} |')
    note+=['','This exports source actor clips, not the scene command scripts, actor placement/camera motion, '
           'ripple/backdrop effects or mode behavior. No guessed character identities or mode-function renames are proposed.']
    (gl.ROOT/'notes/62-scene-actor-bundles.md').write_text('\n'.join(note)+'\n')
    print(result)

if __name__=='__main__':main()
