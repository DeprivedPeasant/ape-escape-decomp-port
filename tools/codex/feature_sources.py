"""Area feature indicator animation ranges grounded in main-EXE update code."""
import json
import struct
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import export_model as em
from codex.area_tables import area_members
from codex.channel_animation import layout
from codex.indicator_assets import parse_indicator_actor


def inventory():
    rows=[];clips={}
    for area,member in sorted(area_members().items()):
        mem=f'{member:03X}';b=(em.MEMBERS/f'{mem}.bin').read_bytes()
        header=struct.unpack_from('<I',b,0x4D0)[0]
        if not 0<=header<=len(b)-0x54:raise ValueError('area feature header outside member')
        words=struct.unpack_from('<8I',b,header+0x34)
        feature_starts=[header+(word>>8)*4 for word in words if word&255]
        for word in words:
            kind=word&255
            if kind not in (0x10,0x11,0x40,0x41):continue
            base=header+(word>>8)*4
            if not 0<=base<=len(b)-12:raise ValueError('feature model header outside member')
            model=base+struct.unpack_from('<H',b,base+4)[0]*4
            stream=base+struct.unpack_from('<H',b,base+8)[0]*4
            if not base+12<=model<stream<len(b):raise ValueError('feature model/animation pointers')
            nb=struct.unpack_from('<H',b,model+4)[0]
            m=em.parse_actor(b,model)
            row={'area':area,'member':mem,'kind':kind,'feature':base,'model':model,'stream':stream,
                 'joints':nb,'scanner_supported':bool(m and m['ok']),'associated':False}
            if kind in (0x10,0x11):
                last=88 if kind==0x10 else 87
                limit=min([len(b)]+[p for p in feature_starts if p>stream])
                m=parse_indicator_actor(b,model,stream)
                row['export_supported']=bool(m and m['ok'])
                descriptors,start=layout(b,stream,nb,last,limit)
                row.update({'channels':len(descriptors),'last_frame':last,'frame_end':start+(last+1)*len(descriptors)*4})
                if m and m['ok']:
                    ranges=((0,28),(29,88)) if kind==0x10 else ((0,57),(58,87))
                    clips[(mem,model)]=[(f'indicator{kind:02X}_{label}',stream,first,end,1,'channels')
                                       for label,(first,end) in zip(('loop','activate'),ranges)]
                    row['associated']=True
                else:raise ValueError('known indicator model failed format validation')
            else:
                row['source_header_word']=struct.unpack_from('<I',b,stream)[0]
                # +8 source is rebased with +4 by AreaSetSpecialActor, unlike indicators.
                # Runtime clip selection/timing not established; no guessed raw clip.
            rows.append(row)
    return clips,rows


def feature_clips():return inventory()[0]


def main():
    import export_gltf as gl
    clips,rows=inventory();exported=0
    for row in rows:
        member,offset=row['member'],row['model']
        if (member,offset) in clips:
            b=(em.MEMBERS/f'{member}.bin').read_bytes()
            m=parse_indicator_actor(b,offset,row['stream'])
            gl.export(member,offset,m,clips[(member,offset)],30);exported+=1
    indicators=[r for r in rows if r['kind'] in (0x10,0x11)]
    special=[r for r in rows if r['kind'] in (0x40,0x41)]
    result={'features':rows,'indicator_streams':len(indicators),'known_feature_associations':len(clips),
            'clips':sum(map(len,clips.values())),'one_joint_known_features':sum(r['joints']==1 for r in indicators),
            'unsupported_models':sum(not r['export_supported'] for r in indicators),
            'special_sources_unresolved':len(special),'exported_models':exported,'failures':[]}
    (gl.OUT/'feature-associations.json').write_text(json.dumps(result,indent=2)+'\n')
    note=['# Area feature actor sources (generated)','',
          'Generated by tools/codex/feature_sources.py. Evidence: AreaSetIndicatorModelA/B, '
          'Indicator_Activate (0x800717B4), IndicatorsUpdateDraw (0x800719F8), '
          'AreaSetSpecialActor (0x8009B3CC); private indicator-activate.c, indicator-actor-frames.c, model-callers.c.','',
          'Each area feature word has low byte id and an upper-24-bit word offset from AreaHeader. '
          'Features 10/11 contain model and direct-channel word offsets at +4/+8, relative to the feature block. '
          'There is no intervening clip table. Feature 10 serves indicator kinds 0/1; feature 11 serves kind 2.','',
          'The update code wraps feature-10 idle at frame 28, activation starts at 29 and returns to idle after 88. '
          'Feature-11 idle wraps at 57, activation starts at 58 and returns after 87. '
          'The exporter exposes these source ranges inclusively. Activation can be incremented before drawing; '
          'the source starting frame is retained rather than inventing a gameplay state-machine bake.','',
          f'Validated {len(indicators)} direct streams, including {result["one_joint_known_features"]} one-joint models '
          f'outside the shared scanner, decoded only at known feature pointers by indicator_assets.py. Added {len(clips)} known-feature associations / {sum(map(len,clips.values()))} clips '
          f'and refreshed {exported} exports using their existing area load-list VRAM. '
          'Channel extents stop before the next feature header when present; all remain within their member.','',
          f'Also inventoried {len(special)} feature-40/41 sources. Their initializer rebases +8 and adds four bytes; '
          'observed source header values are 2 or 30, inconsistent with the direct indicator channel header for '
          'the three-bone models. This appears to be another framed source, but runtime selection/timing is '
          'not yet established, so no automatic clip is assigned. Five three-bone models remain candidates; '
          'two other special actors fall outside scanner limits. This is an evidence gap, not a decode failure.','',
          '| Area | Member | Feature | Model | Joints | Stream | Associated |','|---|---|---|---|---|---|---|']
    note += [f'| {r["area"]:02X} | {r["member"]} | {r["kind"]:02X} | 0x{r["model"]:X} | {r["joints"]} | 0x{r["stream"]:X} | {r["associated"]} |' for r in rows]
    (gl.ROOT/'notes/63-feature-actor-bundles.md').write_text('\n'.join(note)+'\n')
    print({k:v for k,v in result.items() if k!='features'})

if __name__=='__main__':main()
