"""Original camera direction/focus helpers, full output-byte comparison."""
import argparse
import ctypes as C
import json
import os
import random
import shutil
import struct
import subprocess
from pathlib import Path
from check_camera_select import Slot
from mips_ground_reference import Reference, signed

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'extract/codex/native'

def main(source_dir):
    dll=OUT/f'camera_focus_{os.getpid()}.dll'
    subprocess.run([shutil.which('gcc'),'-std=c11','-O2','-Wall','-Wextra','-Werror','-shared',
                    str(source_dir/'native_camera_focus.c'),str(ROOT/'src/camera/native_camera.c'),
                    '-o',str(dll),'-static-libgcc'],check=True)
    lib=C.CDLL(str(dll));bp=C.POINTER(C.c_uint8)
    lib.ae_camera_get_player_dir.argtypes=[C.c_int32,bp,bp]
    lib.ae_camera_get_focus_point.argtypes=[C.POINTER(Slot),C.c_int32,C.POINTER(C.c_int32),bp,bp,bp]
    ref=Reference((ROOT/'extract/members/05B.bin').read_bytes());rng=random.Random(48_94423)
    counts={'direction':0,'focus':0};mode_counts={}
    for case in range(8000):
        mode=rng.choice([0,0,1,2,3,255,-1,-2147483648,2147483647,signed(rng.getrandbits(32))])
        raw=rng.randbytes(0xB0);facing=rng.randbytes(8);region=rng.randbytes(8)
        output=rng.randbytes(8);player=[signed(rng.getrandbits(32)) for _ in range(3)]
        slot=Slot.from_buffer_copy(raw);fa=(C.c_uint8*8).from_buffer_copy(facing)
        rf=(C.c_uint8*8).from_buffer_copy(region);out=(C.c_uint8*8).from_buffer_copy(output)
        ref.ram[0xEC240:0xEC248]=facing;ref.ram[0x130100:0x130108]=output
        ref.call(0x8004B880,(0x80130000,mode,0x80130100))
        assert lib.ae_camera_get_player_dir(mode,fa,out)
        assert bytes(out)==ref.ram[0x130100:0x130108],('direction',case,mode)
        counts['direction']+=1
        out=(C.c_uint8*8).from_buffer_copy(output)
        ref.ram[0x130000:0x1300B0]=raw;ref.ram[0x130100:0x130108]=output
        ref.ram[0xE68C0:0xE68C8]=region
        for i,v in enumerate(player):ref.write(0x800EC204+i*4,4,v)
        ref.call(0x8004B8F4,(0x80130000,mode,0x80130100))
        assert lib.ae_camera_get_focus_point(C.byref(slot),mode,(C.c_int32*3)(*player),fa,rf,out)
        assert bytes(out)==ref.ram[0x130100:0x130108],('focus',case,mode,bytes(out),bytes(ref.ram[0x130100:0x130108]))
        assert bytes(slot)==raw and bytes(fa)==facing and bytes(rf)==region
        counts['focus']+=1;mode_counts[str(mode)]=mode_counts.get(str(mode),0)+1
    out=(C.c_uint8*8)(*range(8));before=bytes(out)
    assert not lib.ae_camera_get_player_dir(0,None,out) and bytes(out)==before
    assert not lib.ae_camera_get_player_dir(1,None,None)
    assert lib.ae_camera_get_player_dir(3,None,out) and bytes(out)==before
    assert lib.ae_camera_get_focus_point(None,1,None,None,None,out) and bytes(out)==before
    assert not lib.ae_camera_get_focus_point(None,0,None,None,None,out) and bytes(out)==before
    assert not lib.ae_camera_get_focus_point(None,2,None,None,None,out) and bytes(out)==before
    assert not lib.ae_camera_get_focus_point(None,1,None,None,None,None)
    report=dict(original_cases=sum(counts.values()),counts=counts,guard_checks=7,failures=0)
    (OUT/'camera-focus-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'notes/port/validation/camera_focus_validation.md').write_text(
        '# Camera focus validation\n\nGenerated by check_camera_focus.py.\n\n'+
        '\n'.join(f'- {k}: {v}' for k,v in report.items())+'\n\n'+
        'Complete original direction and focus instructions execute. Arbitrary signed modes, '
        'full-word positions, signed facing/offset multiplication, byte copies and padding '
        'match. Mode0 focus preserves output padding; mode1 changes nothing. '
        'This does not settle the original caller stack padding or gameplay capture parity.\n')
    print(report)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source-dir',type=Path,default=ROOT/'src/camera')
    main(p.parse_args().source_dir)
