"""Validate objective-text evidence while investigating area display names.

Uses Claude's glyph decoder without editing it. Game text output stays ignored.
uv run --offline python tools/codex/stage_titles.py [--propose]
"""
import argparse
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import dump_text
from codex.stage_catalog import catalog

ROOT = Path(__file__).resolve().parents[2]
RECORDS = [(0x553C,3),(0x554E,3),(0x5560,2),(0x5572,3),(0x5584,2),(0x5596,2),(0x55BA,1),(0x55CC,3)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--propose',action='store_true')
    options = parser.parse_args()
    b = (ROOT/'extract/members/188.bin').read_bytes()
    raw = b[0x5490:0x553C]
    strings = [s for s in raw.split(b'\0') if s]
    decoded = [dump_text.decode(s) for s in strings]
    assert len(decoded) == 14 and all('<' not in s for s in decoded), 'glyph table mismatch'
    records = []
    for offset,count in RECORDS:
        for index in range(count):
            string,x,y = struct.unpack_from('<hhh',b,offset+index*6)
            if string < 0:
                continue
            assert 0 <= string < len(decoded), 'objective string reference outside table'
            assert 0 <= x < 512 and 0 <= y < 256, 'objective text placement outside screen'
            records.append({'address':0x80136000+offset+index*6,'string_index':string,'x':x,'y':y})
    stages=catalog()
    result = {'table_address':0x8013B490,'strings':decoded,'records':records,'stages':stages,'failures':[]}
    (ROOT/'extract/codex/stage-title-evidence.json').write_text(json.dumps(result,indent=2)+'\n')
    note = ['# Stage title investigation and objective text (generated)','',
            'Generated by tools/codex/stage_titles.py; imports tools/dump_text.py without editing it.', '',
            'The function currently named StageStartUi_DrawStageTitle (ovl_188::80139248) '
            'does not select a stage-name string. It branches on game mode and level progress '
            'to select objective/status records, then draws capture counters. The packed string '
            'table at ovl_188::8013B490 contains capture objectives, clearance/completion status, '
            'race/time-attack instructions and icon labels. Examples are “Capture”, “CLEARED” '
            'and “Beat the best time!”. This is evidence to correct the tentative function name, '
            'not evidence assigning an English stage title to an area.', '',
            f'Validation: {len(decoded)} NUL-delimited glyph strings, zero unknown glyphs; '
            f'{len(records)} active text placement records across {len(RECORDS)} selected lists. '
            'All indices and screen placements validate. Full strings and records are written '
            'only to extract/codex/stage-title-evidence.json (ignored).', '',
            'Record format used by StageStartUi_DrawTitleLines (ovl_188::8013912C): '
            'three signed halfwords {stringIndex, screenX, screenY}; negative stringIndex suppresses '
            'the remaining line. At most three records are consumed. Strings are indexed by '
            'walking NUL terminators in the same packed glyph table.', '',
            'Private evidence: area-title.c and stage-title-rendering.c in notes/decomp/codex '
            '(ignored). StageStartUi_DrawNumber draws capture/count fractions and icons; '
            'StageStartUi_DrawStageIcon selects small sprite/CLUT variants for special areas. '
            'Neither supplies an area-title text mapping in the inspected paths.', '',
            '## Resolved stage names','',
            'StageStartUi_StringTableIndex maps AreaGetLevel through the byte table at '
            'ovl_188::8013B450 into22 NUL-terminated names at ovl_188::8013AED0; '
            'the selected glyph string is copied to800F4458. tools/codex/stage_catalog.py '
            'validates all101 active areas and86 named areas against the real overlay/EXE. '
            'Levels31..33 are hub/special areas with no name in this list. '
            'This resolved mapping is separate from the objective/status table discussed above. '
            'Full generated area rows and sound-bank identities remain under ignored extract/.', '',
            '| Level | Stage | Areas |','|---|---|---|']
    for level in sorted({s['level'] for s in stages}):
        group=[s for s in stages if s['level']==level]
        note.append(f'| {level} | {group[0]["name"] or "unnamed hub/special"} | '+', '.join(f'0x{s["area"]:02X}' for s in group)+' |')
    note += ['',
            '## Validated record references','', '| Address | String index | X | Y |',
            '|---|---|---|---|']
    note += [f'| ovl_188::{r["address"]:08X} | {r["string_index"]} | {r["x"]} | {r["y"]} |' for r in records]
    (ROOT/'notes/59-stage-titles.md').write_text('\n'.join(note)+'\n',encoding='utf-8')
    if options.propose:
        symbols = {}
        for line in (ROOT/'tools/symbols.csv').read_text(encoding='utf-8').splitlines():
            if line and not line.startswith('#'):
                key,name,*_ = line.split(',',2)
                symbols[key.lower()] = name
        key = 'ovl_188::80139248'
        old = symbols.get(key)
        proposed = 'StageStartUi_DrawObjectives'
        inbox = ROOT/'notes/codex-inbox.md'
        text = inbox.read_text(encoding='utf-8')
        title = 'stage UI objective text correction'
        if old != proposed and title not in text:
            text += ('\n## 2026-10-06 14:16 AEDT — '+title+'  [status: open]\n'
                     'Evidence: notes/59-stage-titles.md, tools/codex/stage_titles.py; all 14 packed strings '
                     'and 14 active record references validate. The current tentative stage-title comment '
                     'describes objective/status text as stage names. This routine chooses capture/clear/race '
                     'instructions and counters, not a level-name table. Please keep protos.txt in sync if renamed.\n'
                     'symbols (rename existing symbol):\n```csv\n'+key+','+proposed+
                     ',Rename '+str(old)+': selects objective/status text by mode/progress and draws capture counters; no stage-name lookup.\n```\n')
            inbox.write_text(text,encoding='utf-8')
    print(f'strings={len(decoded)} active_records={len(records)} lists={len(RECORDS)} failures=0')


if __name__ == '__main__':
    main()
