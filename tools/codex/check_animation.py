"""Verify monkey clip endpoints and AnimDecodeLerp from independently read words.

uv run --offline python tools/codex/check_animation.py
No game bytes or decompiled code are copied into this tool or generated notes.
"""
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import export_gltf as gl
import export_model as em


def signed(value,bits):
    value &= (1<<bits)-1
    return value-(1<<bits) if value >> (bits-1) else value


def div_zero(value):
    return abs(value)//4096 * (-1 if value < 0 else 1)


def reference(b,nb,clip,frame):
    # Read raw packed words; independently reproduce the decoder's shifts.
    _,offset,key_start,_,step,duration = clip
    frame_a = key_start+frame//step
    weight = ((frame*4096)//step) & 4095
    words = []
    for key in (frame_a,frame_a+1):
        words.append(struct.unpack_from('<'+'I'*(nb+2),b,offset+key*(nb+2)*4))
    root = []
    for shift,bits in ((0,10),(10,12),(22,10)):
        a = signed(words[0][1]>>shift,bits)
        z = signed(words[1][1]>>shift,bits)
        root.append(div_zero(a*(4096-weight)+z*weight))
    angles = []
    for bone in range(nb):
        result = []
        for shift,bits in ((0,10),(10,12),(22,10)):
            a = signed(words[0][bone+2]>>shift,bits)*4
            z = signed(words[1][bone+2]>>shift,bits)*4
            delta = z-a
            if delta >= 2049:
                a += 4096
            elif delta <= -2049:
                z += 4096
            result.append(div_zero(a*(4096-weight)+z*weight))
        angles.append(tuple(result))
    return tuple(root),angles


def main():
    # Hand-derived wrapping/tie/negative-division fixtures, independent of data.
    zero = ((-3,0,0),[(2044,0,0)])
    end = ((0,0,0),[(-2044,0,0)])
    actual = gl.interpolate_pose(zero,end,2048)
    assert actual == ((-1,0,0),[(2048,0,0)]),actual
    assert gl.interpolate_pose(((0,0,0),[(0,0,0)]),((0,0,0),[(2048,0,0)]),2048)[1][0][0] == 1024
    assert gl.interpolate_pose(((0,0,0),[(0,0,0)]),((0,0,0),[(-2048,0,0)]),2048)[1][0][0] == -1024
    metadata = gl.clip_metadata()
    seen = set()
    associations,samples,clipped,maximum_shortening = 0,0,0,0
    failures = []
    for member,offset,m in em.scan_members():
        b = (em.MEMBERS/f'{member}.bin').read_bytes()
        for clip in metadata.get((member,offset),[]):
            if len(clip) != 6 or not isinstance(clip[5], (int,float)):
                continue
            associations += 1
            shortening = (clip[3]-clip[2])*clip[4]-clip[5]
            clipped += shortening > 0
            maximum_shortening = max(maximum_shortening,shortening)
            key = (member,len(m['bones']),*clip[1:])
            if key in seen:
                continue
            seen.add(key)
            times,poses = gl.sample_clip(b,len(m['bones']),clip)
            assert times[0] == 0 and times[-1] == clip[5]
            assert len(poses) == clip[5]+1
            for frame,actual in enumerate(poses):
                expected = reference(b,len(m['bones']),clip,frame)
                if actual != expected:
                    failures.append(f'{member}+{offset:X} {clip[0]} frame={frame}')
                samples += 1
    result = {'monkey_clip_associations':associations,'unique_clip_sources':len(seen),
              'integer_frame_poses':samples,'clips_shortened_to_game_range':clipped,
              'maximum_frames_removed':maximum_shortening,'synthetic_checks':3,'failures':failures}
    (gl.OUT/'animation-validation.json').write_text(json.dumps(result,indent=2)+'\n')
    note = ['# Actor animation timing and interpolation (generated)','',
            'Generated by `uv run --offline python tools/codex/check_animation.py`.', '',
            'ActorAnimDecode (0x80014E34) and ActorAnimDecodeEntry (0x80014EF0) read '
            '8-byte entries: first game frame, last game frame, key spacing, starting key. '
            'They select key floor((current-first)/spacing), then the next key as an interpolation neighbor. '
            'The fractional weight is the low 12 bits of floor((current-first)*4096/spacing). '
            'The next key can be outside the playable frame range; it must be read but must not extend the exported clip.', '',
            'AnimDecodeLerp (0x80014FA0) interpolates packed Euler components separately, '
            'adjusting endpoints by 4096 only when their difference is outside [-2048,2048]. '
            'Weighted sums divide by 4096 toward zero, including negative root positions. '
            'The exporter now bakes each integer monkey game frame, converts that pose with Rz*Ry*Rx, '
            'and ends at (last-first)/fps. Player/enemy contiguous frame clips retain their existing sample timing.', '',
            f'Validated {associations} monkey clip associations, {len(seen)} distinct packed sources, '
            f'{samples} integer-frame poses. Independent raw-word arithmetic comparison failures: {len(failures)}. '
            'Three hand-derived fixtures cover wrapped crossing, exact ±2048 ties and negative division.', '',
            f'{clipped} associations previously exported an extra neighbor span; correction removes '
            f'up to {maximum_shortening} game frames from their duration. Source range and baked duration '
            'are recorded in animation extras.', '',
            'Limits: glTF LINEAR quaternions interpolate between the baked poses. At integer game frames '
            'the exported Euler pose matches the decoded/interpolated values; subframe quaternion interpolation '
            'still differs from PSX Euler interpolation. Matrix sine/cosine calculations remain floating point. '
            'Player runtime speed, looping, transition blends and gameplay state changes are not clip metadata.', '',
            'Private evidence exports: notes/decomp/codex/animation-timing.c and animation-lerp.c '
            '(ignored; never committed). No name proposals needed: these functions are already named.', '',
            '## Failures','']+(failures or ['None.'])
    (gl.ROOT/'notes/55-animation-timing.md').write_text('\n'.join(note)+'\n',encoding='utf-8')
    print(result)
    if failures:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
