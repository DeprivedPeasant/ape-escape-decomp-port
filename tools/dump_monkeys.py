"""Dump per-area monkey spawns, nav graphs and area exits.

Monkey section: area blob +0x4E4 -> M (all offsets below relative to M):
    s32 words: [0] magic 0x11, [1] nav section, [2..4] LOD models 0-2, [5] [6] [7],
               [8] anim set, [9] anim set for states 0x32-0x34, [10] low16 = max active monkeys
Nav section N = M + [1]:
    +0x00 s16 version?, +0x02 s16 end of nav nodes (byte ofs), +0x04 u16, +0x06 s16 links ofs
    +0x08 per monkey 16 bytes: s16[8] spawn node candidates (-1 terminated); a leading -1
          ends the monkey list (max 8)
    +0x88 per monkey 0x80 bytes: 8 patrol groups x s16[8] node ids (-1 terminated)
    +0x488 nav nodes, 0x18 bytes: flags u32 (bit0 = on moving collider), x/y/z s16 at +4,
           link count u8 at +0xA, collider s16 at +0x10 when bit0
Area exits: blob +0x240 count u32, then 0x28-byte entries:
    s32[10] {type, x, y, z, radius, halfX, halfY, halfZ, destArea, destEntry}

Usage: uv run python tools/dump_monkeys.py  -> notes/15-monkeys-exits.md
"""
import struct
from pathlib import Path

import dump_areas

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "notes/15-monkeys-exits.md"
EXIT_TYPES = {0: "sphere", 1: "sphere(r4)", 2: "box", 3: "disabled", 4: "box -> time machine"}


def monkeys(blob: bytes) -> dict | None:
    m = struct.unpack_from("<I", blob, 0x4E4)[0]
    if m == 0 or m + 44 > len(blob):  # areas without a monkey section (boss arenas, some special areas)
        return None
    hdr = struct.unpack_from("<11i", blob, m)
    if hdr[0] != 0x11:
        return None
    nav = m + hdr[1]
    nodes_end = struct.unpack_from("<h", blob, nav + 2)[0]
    node_count = (nodes_end - 0x488) // 0x18
    spawns = []
    for i in range(8):
        e = struct.unpack_from("<8h", blob, nav + 8 + i * 16)
        if e[0] == -1:
            break
        spawns.append([x for x in e if x != -1])
    groups = []
    for i in range(len(spawns)):
        gs = []
        for g in range(8):
            e = [x for x in struct.unpack_from("<8h", blob, nav + 0x88 + i * 0x80 + g * 16) if x != -1]
            if not e:
                break
            gs.append(e)
        groups.append(gs)
    def node_pos(n):
        flags, x, y, z = struct.unpack_from("<Ihhh", blob, nav + 0x488 + n * 0x18)
        return x, y, z, flags & 1
    return {"max_active": hdr[10] & 0xFFFF, "nodes": node_count, "spawns": spawns,
            "groups": groups, "pos": node_pos}


def exits(blob: bytes) -> list:
    n = struct.unpack_from("<I", blob, 0x240)[0]
    return [struct.unpack_from("<10i", blob, 0x244 + i * 0x28) for i in range(min(n, 64))]


def main() -> None:
    out = ["# Monkeys and exits per area (generated)", "",
           "Generated by `tools/dump_monkeys.py`. Formats in the script header and "
           "notes/05-monkeys.md / notes/12-level-collision.md. Positions are world units "
           "(y negative-up). `*` = node rides a moving collider.", "",
           "| Area | Monkeys | Max active | Nav nodes | Exits |", "|---|---|---|---|---|"]
    details = []
    total = 0
    for area, member in sorted(dump_areas.area_members().items()):
        blob = (ROOT / f"extract/members/{member:03X}.bin").read_bytes()
        mk = monkeys(blob)
        ex = exits(blob)
        n = len(mk["spawns"]) if mk else 0
        total += n
        out.append(f"| 0x{area:02X} | {n} | {mk['max_active'] if mk else '-'} | "
                   f"{mk['nodes'] if mk else '-'} | {len(ex)} |")
        lines = [f"## Area 0x{area:02X} (member 0x{member:03X})", ""]
        if mk and mk["spawns"]:
            lines += ["| Monkey | Spawn node (x, y, z) | Patrol groups (node ids) |", "|---|---|---|"]
            for i, (sp, gs) in enumerate(zip(mk["spawns"], mk["groups"])):
                spos = []
                for s in sp:
                    x, y, z, mov = mk["pos"](s)
                    spos.append(f"{s} ({x}, {y}, {z}){'*' if mov else ''}")
                lines.append(f"| {i} | {'<br>'.join(spos)} | {' / '.join(','.join(map(str, g)) for g in gs)} |")
            lines.append("")
        if ex:
            lines += ["| Exit | Type | Pos | Radius / half size | Dest area / entry |", "|---|---|---|---|---|"]
            for i, (t, x, y, z, r, hx, hy, hz, da, de) in enumerate(ex):
                size = f"r={r}" if t in (0, 1) else f"{hx}x{hy}x{hz}"
                lines.append(f"| {i} | {EXIT_TYPES.get(t, t)} | ({x}, {y}, {z}) | {size} | 0x{da:02X} / {de} |")
            lines.append("")
        if len(lines) > 2:
            details.append("\n".join(lines))
    out[2] += f" Total monkeys across areas: {total}."
    OUT.write_text("\n".join(out) + "\n\n" + "\n".join(details), encoding="utf-8")
    print(f"wrote {OUT}: {total} monkeys")


if __name__ == "__main__":
    main()
